#!/usr/bin/env python3
"""QUESTION ANSWERED: per lane and per tree, which functions MATCH in the near-miss index but are not yet built from
C in main (notes/cc900-c-nearmiss/ready.tsv), how many bytes they are, and where their C is (the copy in c/, and
`c_elsewhere`: a lane worktree, a branch main has not merged, or `none` when the copy in c/ is the only C)?

Reads ready.tsv only (written by `nearmiss.py --recheck --update`, `--add-new` or `--ready`); writes an aligned
Markdown summary for the coordinator to hand rows to the lanes.

usage: python3 -B notes/cc900-c-nearmiss/probes/ready_summary.py [READY.tsv [OUT.md]]
       (defaults: notes/cc900-c-nearmiss/ready.tsv, notes/cc900-c-nearmiss/ready-by-lane.md)"""
import os
import sys
from collections import OrderedDict

HERE = os.path.dirname(os.path.abspath(__file__))
NOTES = os.path.dirname(HERE)


def table(head, rows):
    w = [max(len(str(x)) for x in col) for col in zip(head, *rows)]
    out = ['| ' + ' | '.join(str(h).ljust(n) for h, n in zip(head, w)) + ' |',
           '|' + '|'.join('-' * (n + 2) for n in w) + '|']
    for r in rows:
        out.append('| ' + ' | '.join(str(x).ljust(n) for x, n in zip(r, w)) + ' |')
    return '\n'.join(out)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(NOTES, 'ready.tsv')
    dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(NOTES, 'ready-by-lane.md')
    lines = open(src).read().splitlines()
    cols = lines[0].split('\t')
    rows = [dict(zip(cols, l.split('\t'))) for l in lines[1:] if l.strip()]
    lanes = OrderedDict()
    for r in rows:
        lanes.setdefault(r['lane'], OrderedDict()).setdefault(r['tree'], []).append(r)

    def nb(rs):
        return sum(int(r['bytes'] or 0) for r in rs)

    out = ['# Ready, not yet built (generated by `probes/ready_summary.py` from `ready.tsv`)', '',
           'Functions whose best V4.23 attempt MATCHes the ROM but that the src-root (main) does not build from C. '
           '`c_elsewhere`: where else C for the function exists (a lane worktree, `branch:<name>` for a branch main '
           'has not merged, `src-root:staged`); `none` = the copy in `c/` is the only C.  Check each row against the '
           'tree before staging it (the copy may lack a `cc900-name:` / `cc900-module:` line).', '',
           '## Totals', '']
    tot = []
    for lane, trees in lanes.items():
        for tree, rs in trees.items():
            none = [r for r in rs if r['c_elsewhere'] == 'none']
            tot.append([lane, tree, len(rs), nb(rs), len(none), nb(none)])
    allr = [r for t in lanes.values() for rs in t.values() for r in rs]
    alln = [r for r in allr if r['c_elsewhere'] == 'none']
    tot.append(['all', '', len(allr), nb(allr), len(alln), nb(alln)])
    out.append(table(['lane', 'tree', 'functions', 'bytes', 'C only in c/', 'bytes (C only in c/)'], tot))
    for lane, trees in lanes.items():
        out += ['', '## ' + lane, '']
        body = []
        for tree, rs in trees.items():
            for r in sorted(rs, key=lambda r: r['function']):
                body.append([tree, r['function'], r['bytes'], r['run'], r['opt'], r['c_copy'] or '(none)',
                             r['c_elsewhere']])
        out.append(table(['tree', 'function', 'bytes', 'run', 'opt', 'c_copy', 'c_elsewhere'], body))
    with open(dst, 'w') as f:
        f.write('\n'.join(out) + '\n')
    for t in tot:
        print('%-9s %-9s %5d functions %7d B   C only in c/: %4d functions %6d B' % tuple(t))


if __name__ == '__main__':
    main()
