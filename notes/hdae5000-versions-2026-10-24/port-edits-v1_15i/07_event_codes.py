"""v1.x numbers the HD-AE5000's own messages differently: its own shared/event_codes.s.

The tree's message-name table (registered as 0x1EA) lists 13 methods in v1.15i, v2.x's 18
less MT_SelectAll and the four MT_Fd*: so every method after MT_SelectSAVE is one lower,
MT_SetStrAdr 0x01ea0009 (v2.x 0x01ea000a), MT_SelectDEL 0x01ea000b, MT_SelectDelFile
0x01ea000c.  unidasm counts 31 uses of 0x01ea0009 in v1.15i and none of 0x01ea000a; v2.01i
has 31 of 0x01ea000a.  Its event-name table (0x1CA) has 3 entries, EV_SeqStop / AfterLoad /
TimerBack (0x01ca0000-2, as in v2.x): the lyric and floppy-selector events are not there.

The file is hdae5000/shared/event_codes.s with those constants changed or dropped; the
tree finds it before hdae5000/'s through its own -I (the main-CPU trees likewise keep one
event_codes.s each).  v1.10i takes it from here.
"""
import os
import re
from _edit import ROOT, path

src = open(os.path.join(ROOT, "hdae5000", "shared", "event_codes.s"), "rb").read()
NEW = {b"EVT_HDAE_SET_STR_ADR": 0x1ea0009, b"EVT_HDAE_SELECT_DEL": 0x1ea000b,
       b"EVT_HDAE_SELECT_DEL_FILE": 0x1ea000c}
GONE = {b"EVT_HDAE_SELECT_ALL", b"EVT_HDAE_FD_FRESH_UP", b"EVT_HDAE_FD_INFO", b"EVT_HDAE_FD_LOAD_LYRIC",
        b"EVT_HDAE_FD_SAVE_LYRIC"}
out, seen = [], set()
for ln in src.split(b"\n"):
    m = re.match(rb"^\.equ (EVT_HDAE_\w+), (0x[0-9a-f]+)", ln)
    if m:
        name, val = m.group(1), int(m.group(2), 16)
        if name in GONE or (val >> 16 == 0x01ca and val & 0xffff >= 3):
            seen.add(name)
            continue
        if name in NEW:
            seen.add(name)
            ln = ln.replace(m.group(2), b"0x%x" % NEW[name], 1) + b"  [v1.x numbering]"
    out.append(ln)
assert NEW.keys() <= seen and GONE <= seen
hdr = (b"; HD-AE5000 v1.15i / v1.10i: hdae5000/shared/event_codes.s with the HD-AE5000's own message\n"
       b"; ids renumbered (v1.x has no MT_SelectAll) and its lyric / floppy-selector events dropped;\n"
       b"; generated by notes/hdae5000-versions-2026-10-24/port-edits-v1_15i/07_event_codes.py.\n")
os.makedirs(path("shared"), exist_ok=True)
open(path(os.path.join("shared", "event_codes.s")), "wb").write(hdr + b"\n".join(out))
print("ok: %d constants changed or dropped" % len(seen))
