"""Give two UI object constants of v2.01i their right values, and undo the code edit that hid it.

The UI object section of hdae5000_v2_01i/hdae5000_data_tables.s was regenerated by
`port_hdae5000_version.py uitables`, which writes HDAE5000_OBJ_<name> = 0x007F0000 + n
from the v2.01i name table: #130 SW_HD_FORMAT, #220 CP_FD_HDSWTO, #222 CP_FD_HDSWSEL.
A later `fix` round then retargeted two of those constants to make one routine's bytes
match, and left them wrong:

    HDAE5000_OBJ_SW_HD_FORMAT   0x007f00de  (#222)   should be 0x007f0082 (#130)
    HDAE5000_OBJ_CP_FD_HDSWSEL  0x007f00dc  (#220)   should be 0x007f00de (#222)

The routine (the tail of the function in hdae5000_ui_display.s that hides the file-load
switches, right before HDAE5000_NameHistory_AfterPushNop) was respelled to fit: it named
HDSWSEL for object 220, SW_HD_FORMAT for object 222, and spelled the third block with a
numeric `ld xwa, 0x7f0082` and a raw `ld_sril XHL, (xwa + 0x294)`.  The v2.01i bytes hide
objects 220, 222 and 130 in that order -- CP_FD_HDSWTO, CP_FD_HDSWSEL, SW_HD_FORMAT, the
same three objects v2.06i hides there -- so the routine's text is restored to v2.06i's.

Found by the reviewer; port_hdae5000_version.py's `fix` no longer retargets HDAE5000_OBJ_*
once uitables has run, and hdae5000_version_label_check.py now checks every OBJ constant
against the name table.

RUN (once): python3 notes/hdae5000-versions-2026-10-24/port-edits/18_obj_constant_values.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
T = os.path.join(ROOT, "hdae5000_v2_01i")


def rep(fn, old, new):
    p = os.path.join(T, fn)
    s = open(p, "rb").read()
    assert s.count(old) == 1, (fn, s.count(old), old[:60])
    open(p, "wb").write(s.replace(old, new))


rep("hdae5000_data_tables.s",
    b"\t.equ HDAE5000_OBJ_SW_HD_FORMAT, 0x007f00de\n",
    b"\t.equ HDAE5000_OBJ_SW_HD_FORMAT, 0x007f0082\n")
rep("hdae5000_data_tables.s",
    b"\t.equ HDAE5000_OBJ_CP_FD_HDSWSEL, 0x007f00dc\n",
    b"\t.equ HDAE5000_OBJ_CP_FD_HDSWSEL, 0x007f00de\n")

SETVIS = (b"\tld bc, iz\n"
          b"\tld xwa, (HDAE5000_RAM_MainWorkspacePtr:24)\n"
          b"\tld xwa, (xwa + WS_RootFnTable)\n"
          b"\tld xhl, (xwa + RootFn_SetVisible)\n")
rep("hdae5000_ui_display.s",
    b"\tld xwa, HDAE5000_OBJ_HD_FILE_LOAD_SW_DELFILE\n\tcall (xhl)\n"
    + SETVIS + b"\tld xwa, HDAE5000_OBJ_CP_FD_HDSWSEL\n\tcall (xhl)\n"
    + SETVIS + b"\tld xwa, HDAE5000_OBJ_SW_HD_FORMAT\n"
    b"\tcall\t(xhl)\n"
    b"\tld\tbc, iz\n"
    b"\tld\txwa, (HDAE5000_RAM_MainWorkspacePtr:24)\n"
    b"\tld\tXWA, (xwa + WS_RootFnTable)\n"
    b"\tld_sril\tXHL, (xwa + 0x294)\n"
    b"\tld\txwa, 0x7f0082\n"
    b"\tcall (xhl)\n\tpopw iz\n\tret\n",
    b"\tld xwa, HDAE5000_OBJ_HD_FILE_LOAD_SW_DELFILE\n\tcall (xhl)\n"
    + SETVIS + b"\tld xwa, HDAE5000_OBJ_CP_FD_HDSWTO\n\tcall (xhl)\n"
    + SETVIS + b"\tld xwa, HDAE5000_OBJ_CP_FD_HDSWSEL\n\tcall (xhl)\n"
    + SETVIS + b"\tld xwa, HDAE5000_OBJ_SW_HD_FORMAT\n"
    b"\tcall (xhl)\n\tpopw iz\n\tret\n")
print("ok")
