#!/usr/bin/env python3
"""Helper AV, lane_sub round 44: writes scripts/analysis/cc900/corpus/firmware/sub_AV_44{a,b,c}.c
(DSP_SOS_LUT_Fetch and DSP_SOS_Coeff_Compute, KN5000 sub-CPU payload v1.42, core/14_dsp_control_routines.s),
from round 43's verdicts (run 2026-11-20-7-sub-r43b).

The cc900-data lines are read from notes/cc900-c-subcpu-2026-11-16/helper-generators/fpconst.txt (address order =
V4.23's code order of the constants).  Run from the worktree root:

    python3 -B ~/compartilhado/tmp/cc900-tab/lane_sub/AV/gen_AV_44.py
"""
import os

ROOT = os.getcwd()
OUT = os.path.join(ROOT, 'scripts', 'analysis', 'cc900', 'corpus', 'firmware')
FPC = os.path.join(ROOT, 'notes', 'cc900-c-subcpu-2026-11-16', 'helper-generators', 'fpconst.txt')
assert os.path.isdir(OUT), OUT


def consts(prefixes):
    out = []
    for ln in open(FPC, encoding='latin-1'):
        f = ln.split()
        if len(f) >= 2 and any(f[1].startswith(p) for p in prefixes):
            out.append((int(f[0], 16), f[1]))
    return [n for _, n in sorted(out)]


LUT_C = consts(['FPConst_DSP_SOS_LUT_'])
SOS_C = consts(['FPConst_DSP_SOS_Coeff_Compute_', 'FPConst_DSP_SOS_Algo'])
assert len(LUT_C) == 4 and len(SOS_C) == 63, (len(LUT_C), len(SOS_C))

T = 'DSP_EQ_FreqHz_Table'

FORMS = {
    'a': dict(
        what="""   Round 43 (run 2026-11-20-7-sub-r43b): only the `volatile float` table (form 43c) made V4.23 call `._fld_ff`
   (FP_SP_Raw4Copy) for the table read; `+T[k]` and a one-float struct member stayed inline copies.  Form a:
   - DSP_SOS_LUT_Fetch: the volatile table kept; the int index first copied to a local k (`k = tbl[i];
     fr = T[k];`): with `T[tbl[i]]` V4.23 scaled the index in 32 bits (exts / sll / add) and held the address in
     XIZ, which spilled i; the ROM scales a 16-bit index (`sla wa,2` / `lda xbc,(xbc+wa)`, as V4.23 did for the
     char index of the type-2 read) and keeps i in IZ.  The class byte as `switch (c)` with the default first:
     a switch moves its selector into WA (the ROM's `ld a,c; cp a,0x10`; DSP_FilterLUT_Fetch's ROM `ld wa,bc`),
     an if compared C in place (43c).
   - DSP_SOS_Coeff_Compute: 43c's code was the ROM's but for two things.  (1) V4.23 gave IZ to s and spilled chip
     (`register` on the parameter, 43b, changed nothing); the ROM has chip in IZ (`ld IZ,WA` at entry) and s in QIZ:
     here chip is copied into a `register int ch` (DSP_DetuneCurve_SignedFP's `register long x; x = v;`), ch
     declared before s.  (2) Three temporaries sit lower than the ROM's (the double at +60 for the ROM's +72, the
     second float at +112 for +120, both under the slots of the case-1 writes / pow); the `(float)` cast moved them
     further down (43a), so here the `(long)` casts of the writers' arguments are dropped too (implicit
     conversion through the prototype).""",
        lut_i='register unsigned int i', lut_j=False, sw='c',
        regs='    register int ch;\n    int s;\n', cmp0='0.0F'),
    'b': dict(
        what="""   Form a with these changes:
   - DSP_SOS_LUT_Fetch: the switch on the expression `(unsigned char)(*p++ & 0xf0)` (no local c).
   - DSP_SOS_Coeff_Compute: s declared before ch.""",
        lut_i='register unsigned int i', lut_j=False, sw='expr',
        regs='    int s;\n    register int ch;\n', cmp0='0.0F'),
    'c': dict(
        what="""   Form a with these changes:
   - DSP_SOS_LUT_Fetch: i a plain parameter copied into a `register unsigned int j` (the DetuneCurve idiom).
   - DSP_SOS_Coeff_Compute: the sign tests written `gain >= 0` (an int zero; does V4.23 count the converted
     constant differently when it orders the temporaries?).""",
        lut_i='unsigned int i', lut_j=True, sw='c',
        regs='    register int ch;\n    int s;\n', cmp0='0'),
}

HEAD = """/* lane_sub round 44, helper AV, form %s (KN5000 sub-CPU payload v1.42, core/14_dsp_control_routines.s): floating point.
%s
   Generated by ~/compartilhado/tmp/cc900-tab/lane_sub/AV/gen_AV_44.py.
   cc900-options: -Xr */
"""


def lut(d):
    ix = 'j' if d['lut_j'] else 'i'
    decl = '    float fr;\n    float g;\n    int m;\n'
    if d['sw'] == 'c':
        decl += '    unsigned char c;\n'
    decl += '    int k;\n'
    if d['lut_j']:
        decl += '    register unsigned int j;\n'
    body = ''
    if d['lut_j']:
        body += '    j = i;\n'
    body += '    m = *p & 0xf;\n'
    if d['sw'] == 'c':
        body += '    c = *p++ & 0xf0;\n    switch (c) {\n'
    else:
        body += '    switch ((unsigned char)(*p++ & 0xf0)) {\n'
    body += ('    default:\n'
             '        k = tbl[%(x)s];\n'
             '        fr = %(T)s[k];\n'
             '        g = tbl[%(x)s + 1] * 0.5 + -12.0;\n'
             '        break;\n'
             '    case 0x10:\n'
             '        k = tbl[%(x)s - 1];\n'
             '        fr = %(T)s[k];\n'
             '        g = tbl[%(x)s] * 0.5 + -12.0;\n'
             '        break;\n'
             '    }\n'
             '    if (m == 2) {\n'
             '        fr = %(T)s[*p++ & 0x1f];\n'
             '    }\n'
             '    *mo = m;\n'
             '    *fo = fr;\n'
             '    *go = g;\n'
             '    return p;\n') % dict(x=ix, T=T)
    return ('\n/* cc900-module: DSP_SOS_LUT_Fetch DSP_SOS_Coeff_Compute */\n%s\n'
            'unsigned char *DSP_SOS_LUT_Fetch(%s, float *fo, float *go, int *mo, int *tbl, unsigned char *p)\n'
            '{\n%s\n%s}\n') % (data('DSP_SOS_LUT_Fetch', LUT_C), d['lut_i'], decl, body)


K = '0.0001424758573'
SINCOS = '(sin(freq * %s) - 1.0) / cos(freq * %s)' % (K, K)

SOS = """
%(data)s
unsigned char *DSP_SOS_Coeff_Compute(int chip, unsigned int slot, unsigned int v, unsigned char *p,
                                     unsigned int a, int *rec, int *st, int f0)
{
    float freq;
    float gain;
    float k1;
    float k2;
    float nrm;
    float c1;
    float c2;
    float r;
    float amp;
    int type;
%(regs)s
    ch = chip;
    p = DSP_SOS_LUT_Fetch(v, &freq, &gain, &type, rec, p);
    switch (type) {
    case 0:
        amp = pow(10.0, gain / 20.0F);
        if (gain >= %(z)s) {
            k1 = %(sc)s;
            r = (k1 + 1.0F) / (1.0F - k1);
            k2 = (1.0F - amp / r) / (amp / r + 1.0F);
        } else {
            k2 = %(sc)s;
            r = (1.0F - k2) / (k2 + 1.0F);
            k1 = (amp / r - 1.0F) / (amp / r + 1.0F);
        }
        nrm = (1.0F - k2) / (1.0F - k1);
        c1 = k1 * nrm;
        c2 = -k2;
        s = DSP_WriteOscParam(a, c1 * 4194304.0F, ch, f0);
        s = DSP_WriteParamWord(c2 * 4194304.0F, ch);
        s = DSP_WriteParamWord(nrm * 4194304.0F, ch);
        break;
    case 1:
        amp = pow(10.0, gain / 20.0F);
        if (gain >= %(z)s) {
            k1 = %(sc)s;
            r = (1.0F - k1) / (k1 + 1.0F);
            k2 = (amp / r - 1.0F) / (amp / r + 1.0F);
        } else {
            k2 = %(sc)s;
            r = (k2 + 1.0F) / (1.0F - k2);
            k1 = (1.0F - amp / r) / (amp / r + 1.0F);
        }
        nrm = (k2 + 1.0F) / (k1 + 1.0F);
        c1 = k1 * nrm;
        c2 = -k2;
        s = DSP_WriteOscParam(a, c1 * 2097152.0F, ch, f0);
        s = DSP_WriteParamWord(c2 * 4194304.0F, ch);
        s = DSP_WriteParamWord(nrm * 2097152.0F, ch);
        break;
    case 2:
        amp = pow(10.0, gain / 20.0F);
        if (gain >= %(z)s) {
            k1 = %(sc)s;
            r = (1.0F - k1) / (k1 + 1.0F);
            k2 = (amp / r - 1.0F) / (amp / r + 1.0F);
        } else {
            k2 = %(sc)s;
            r = (k2 + 1.0F) / (1.0F - k2);
            k1 = (1.0F - amp / r) / (amp / r + 1.0F);
        }
        nrm = (k2 + 1.0F) / (k1 + 1.0F);
        c1 = k1;
        c2 = -k2;
        s = DSP_WriteOscParam(a, c2 * 4194304.0F, ch, f0);
        s = DSP_WriteCoeffData_5B_Direct(nrm * 4194304.0F, ch, f0);
        s = DSP_WriteCoeffData_5B_Direct(c1 * 4194304.0F, ch, f0);
        break;
    }
    *st = s;
    return p;
}
"""


def data(func, names):
    return '\n'.join('/* cc900-data: %s %d = %s */' % (func, i + 1, n) for i, n in enumerate(names))


for form, d in FORMS.items():
    txt = HEAD % (form, d['what']) + '\n'
    txt += '\n'.join([
        'extern double __cdecl pow(double x, double y);',
        'extern double __cdecl sin(double x);',
        'extern double __cdecl cos(double x);',
        'extern volatile float %s[];' % T,
        'extern int DSP_WriteOscParam(unsigned int a, long v, register int chip, int base);',
        'extern int DSP_WriteParamWord(long v, int chip);',
        'extern int DSP_WriteCoeffData_5B_Direct(long v, int chip, int f0);',
        'unsigned char *DSP_SOS_LUT_Fetch(%s, float *fo, float *go, int *mo, int *tbl, unsigned char *p);' % d['lut_i'],
        'unsigned char *DSP_SOS_Coeff_Compute(int chip, unsigned int slot, unsigned int v, unsigned char *p,',
        '                                     unsigned int a, int *rec, int *st, int f0);',
    ]) + '\n'
    txt += lut(d)
    txt += SOS % dict(data=data('DSP_SOS_Coeff_Compute', SOS_C), regs=d['regs'], z=d['cmp0'], sc=SINCOS)
    path = os.path.join(OUT, 'sub_AV_44%s.c' % form)
    with open(path, 'w', encoding='latin-1') as fh:
        fh.write(txt)
    print('wrote', path)
