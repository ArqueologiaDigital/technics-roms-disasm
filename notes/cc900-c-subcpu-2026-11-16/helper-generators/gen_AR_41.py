def read(name):
    return open(os.path.join(CORP, name), 'rb').read().decode('latin-1')


def func(text, name):
    """The function NAME's definition, with the cc900-data lines right above it."""
    lines = text.split('\n')
    start = None
    for i, l in enumerate(lines):
        if l and not l.startswith(' ') and (name + '(') in l and not l.rstrip().endswith(';') and not l.startswith('/*'):
            start = i
            break
    assert start is not None, name
    s = start
    while s > 0 and lines[s - 1].startswith('/* cc900-data: ' + name + ' '):
        s -= 1
    e = start
    while lines[e] != '}':
        e += 1
    return '\n'.join(lines[s:e + 1]) + '\n'


def rep(text, old, new):
    assert text.count(old) == 1, (old, text.count(old))
    return text.replace(old, new)


