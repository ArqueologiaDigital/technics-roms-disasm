#!/usr/bin/env python3
"""Promote verified staged sub-CPU C into the build, and write the sizes the splice needs.

QUESTION ANSWERED / WHY: staged C (<tree>/subcpu/cc900-staged/*.c) that V4.23 reproduces moves into
<tree>/subcpu/cc900/, where `make` builds it, in all three trees (v141 / v140 are generated from v142's hand source,
so each needs its own C next to the `.include` lines the generators carry over).  This script does the bookkeeping:

    python3 -B notes/cc900-c-subcpu-2026-11-16/promote.py sizes OUT.tsv
        function<TAB>bytes for every function that MATCHed in v142: staged_v423.tsv's rows and the probe verdicts
        (verdicts/*.tsv), the input of scripts/tools/cc900_splice.py --sizes
    python3 -B notes/cc900-c-subcpu-2026-11-16/promote.py list [--except PATTERN ...]
        the staged files to promote (v142 names), one per line, leaving out names that contain a PATTERN

The moves themselves are `git mv` commands, the splice is cc900_splice.py on v142, and v141 / v140 are regenerated by
scripts/generators/create_v14[01]_subcpu_source.py; README "Promotion into the build" has the sequence.
"""
import glob, os, sys

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
NOTES = os.path.join(REPO, 'notes', 'cc900-c-subcpu-2026-11-16')


def sizes(out):
    got = {}
    for l in open(os.path.join(NOTES, 'staged_v423.tsv')):
        c = l.rstrip('\n').split('\t')
        if len(c) == 8 and c[0] == 'v142' and c[7] == 'MATCH':
            got[c[5]] = int(c[6])
    for p in sorted(glob.glob(os.path.join(NOTES, 'verdicts', '*.tsv'))):
        for l in list(open(p))[1:]:
            c = l.rstrip('\n').split('\t')
            if len(c) >= 3 and c[2] not in ('-', '') and int(c[1]) > 0:
                got.setdefault(c[0], int(c[1]))
    with open(out, 'w') as fh:
        for n in sorted(got):
            fh.write('%s\t%d\n' % (n, got[n]))
    print('%d functions with sizes in %s' % (len(got), out))


def listing(excl):
    for p in sorted(glob.glob(os.path.join(REPO, 'v142', 'subcpu', 'cc900-staged', '*.c'))):
        n = os.path.basename(p)
        if not any(e in n for e in excl):
            print(n)


def main():
    a = sys.argv[1:]
    if a[:1] == ['sizes'] and len(a) == 2:
        return sizes(a[1])
    if a[:1] == ['list']:
        return listing([a[i + 1] for i, x in enumerate(a) if x == '--except'])
    sys.exit(__doc__)


if __name__ == '__main__':
    sys.exit(main())
