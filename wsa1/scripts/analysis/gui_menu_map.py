#!/usr/bin/env python3
"""gui_menu_map.py -- generate docs/gui-menu-map.md, the browsable index of the SX-WSA1R's screens.

QUESTION IT ANSWERS
  "What screens does the WSA1 have, what does each one draw, which key runs what on it, and which key on
   which screen leads to it?" -- answered from the SOURCES alone, so the map is always the tree's own
   current reading.  Regenerated by `make gui-menu-map`; `make gui-menu-map-check` fails when the
   committed file is not what the sources give.

WHAT IT READS (all of it from wsa1/prom_a and wsa1/prom_b, plus the two ELFs a build leaves in rebuilt_ROMs/)
  * PanelScreen_VtableTable (prom_a 0xF86EC1): 256 screen-object pointers.  Entries 0-47 are the panel
    MODES (view A, indexed by PanelMode); entry 32 + n is SCREEN ID n (view B, PanelScreen_VtableTable_ViewB),
    which is the number every screen request carries.  Each object is three consecutive prom_b directory
    slots, `jp` to its Enter (+0), Leave (+4) and Button (+8) methods (the table's own header, checks V1-V6).
  * the directory (prom_b 0xF40000-0xF44017): `T_name: jp target`, so a thunk name resolves to its routine.
  * every routine body: from its label to the next label that something CALLS / jumps to through a table
    (internal `jr` targets do not end a routine).  In a body it collects
      - display lists: an operand that is the label of a display list (a label whose next record line is a
        dl_* / dlb_* macro, include/wsa1_gui.inc), and the first texts each list draws;
      - key maps: an operand that is the label of a keymap_begin block, and its 32 on_key lines;
      - screen requests: `ldw (UI_Request:16), v` or `ld (UI_Request_Hi:16), hi` + `ld (UI_Request:16), lo`.
        UI_Request_Hi bit 7 = go to screen id <lo> (PanelScreen_ApplyRequestForced), bit 6 = request it
        (PanelScreen_ApplyRequest), bit 1 = mode change (PanelScreen_ApplyModeChange), bit 4 = repaint
        (PanelState_RunRequests; FINDINGS-prom_ab-screen-stage-and-flags.md).
    and follows `call` / `calr` / `jp` / `jr` into other routines (and a fall-through into the next label), through thunks, to depth 3, skipping shared
    helpers (a routine called from more than 6 places).
    A `pushw <code> / call T_Dispatch_Code80_Bracketed` (or T_Dispatch_Code80) is followed into the painter
    prom_b's Dispatch_Code80_PaintTable (or _RepaintFieldTable) holds for that screen code: that is how the
    sound-edit and tone-edit pages paint, from their Enter methods, which Cpu2Reply_HandleNext re-runs for each
    of CPU 2's replies through ScreenCode80_Handlers / ScreenCodeC0_Handlers.
    It also follows a routine handed over by address (`ld XWA,<routine>` before T_CallbackQueue_Post and
    the like), because that is how most screens queue their painters.
  The map is a static reading: a request written through a register, or a list chosen through a pointer
  table, is not seen.  What it shows is what the code SAYS, never more.

RUN (inside wsa1/, after `make all`)
  python3 scripts/analysis/gui_menu_map.py                # writes docs/gui-menu-map.md
  python3 scripts/analysis/gui_menu_map.py --check        # exit 1 if the committed map is stale
  python3 scripts/analysis/gui_menu_map.py --stdout
"""
import argparse
import collections
import glob
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "docs", "gui-menu-map.md")
NM = os.path.join(os.path.expanduser("~"), "compartilhado", "llvm-project", "build", "bin", "llvm-nm")
LABEL = re.compile(r'^([A-Za-z_][\w]*):')
MACRO = re.compile(r'^\s*(dlb?_\w+)\s+(.*)$')
TEXT = re.compile(r'\btext="((?:[^"\\]|\\.)*)"')
DEPTH, FANIN = 3, 6


def src_files(image):
    return [os.path.join(ROOT, image, "wsa1_%s.s" % image)] + \
        sorted(glob.glob(os.path.join(ROOT, image, "modules", "*.s")))


def strip_comment(l):
    q = False
    for i, ch in enumerate(l):
        if ch == '"':
            q = not q
        elif ch == ';' and not q:
            return l[:i]
    return l


def show(s):
    """a macro text= literal, for prose: octal-escaped glyph codes become a middle dot"""
    s = re.sub(r'\\[0-7]{1,3}', '·', s)
    return s.replace('\\"', '"').replace('\\\\', '\\').strip()


class Tree:
    def __init__(self):
        self.lines = {}        # (image, file) -> [lines]
        self.where = {}        # label -> (image, file, index)
        self.order = []        # (image, file, index, label) in source order
        for image in ("prom_a", "prom_b"):
            for f in src_files(image):
                L = open(f, "rb").read().decode("latin-1").split("\n")
                self.lines[(image, f)] = L
                for i, l in enumerate(L):
                    m = LABEL.match(l)
                    if m:
                        self.where.setdefault(m.group(1), (image, f, i))
                        self.order.append((image, f, i, m.group(1)))
        self.syms = {}
        for image in ("prom_a", "prom_b"):
            elf = os.path.join(ROOT, "rebuilt_ROMs", "wsa1_%s.llvm.elf" % image)
            if not os.path.exists(elf):
                sys.exit("build first: %s missing (make all)" % elf)
            d = {}
            for l in subprocess.run([NM, elf], capture_output=True, text=True, check=True).stdout.splitlines():
                p = l.split()
                if len(p) == 3:
                    d[p[2]] = int(p[0], 16)
            self.syms[image] = d
        self.thunk = {}        # directory slot name -> jp target
        self.slot_at = {}      # address -> slot name
        for (image, f), L in self.lines.items():
            if image != "prom_b":
                continue
            for l in L:
                m = re.match(r'^(T_\w+):\s*jp\s+([A-Za-z_]\w*)', l)
                if m:
                    self.thunk[m.group(1)] = m.group(2)
                    a = self.syms["prom_b"].get(m.group(1))
                    if a is not None:
                        self.slot_at.setdefault(a, m.group(1))
        self.classify()
        self.bodies()

    def next_record(self, image, f, i):
        L = self.lines[(image, f)]
        for j in range(i + 1, min(i + 40, len(L))):
            c = strip_comment(L[j]).strip()
            if not c:
                continue
            return c
        return ""

    def classify(self):
        self.dl, self.keymap = {}, {}
        for image, f, i, name in self.order:
            nxt = self.next_record(image, f, i)
            if MACRO.match(nxt):
                texts = []
                L = self.lines[(image, f)]
                j = i + 1
                while j < len(L) and len(texts) < 4:
                    c = strip_comment(L[j]).strip()
                    if c and not MACRO.match(c):
                        if LABEL.match(c):
                            break
                        if not c.startswith("."):
                            break
                    m = TEXT.search(L[j])
                    if m and show(m.group(1)).strip("· "):
                        texts.append(show(m.group(1)))
                    j += 1
                self.dl[name] = texts
            elif nxt.startswith("keymap_begin"):
                L = self.lines[(image, f)]
                rows, cur = [], None
                for j in range(i + 1, len(L)):
                    c = strip_comment(L[j]).strip()
                    if not c:
                        continue
                    if c.startswith("keymap_begin"):
                        cur = []
                    elif c.startswith("keymap_end") or c.startswith("fieldops_end"):
                        rows.append(cur)
                        cur = None
                        nn = strip_comment(L[j + 1]).strip() if j + 1 < len(L) else ""
                        k = j + 1
                        while k < len(L) and not strip_comment(L[k]).strip():
                            k += 1
                        if k >= len(L) or not strip_comment(L[k]).strip().startswith("keymap_begin"):
                            break
                    elif c.startswith("on_key"):
                        m = re.match(r'on_key\s+(\w+)\s*,\s*(\S+)', c)
                        cur.append((m.group(1), m.group(2)))
                    else:
                        break
                self.keymap[name] = rows

    def bodies(self):
        """routine name -> its code lines: from its label to the next label that something calls or jumps
        to through a table, or that starts a display list or a key map (internal `jr` targets do not end it)."""
        import bisect
        callre = re.compile(r'\b(?:call|calr|jp|jrl?|\.long|on_key\s+\w+\s*,)\s*(?:[a-z]+\s*,\s*)?([A-Za-z_]\w*)', re.I)
        self.stripped = {k: [strip_comment(x) for x in L] for k, L in self.lines.items()}
        called = set(self.thunk.values())
        for k, S in self.stripped.items():
            for c in S:
                if "call" in c or "jp" in c or ".long" in c or "on_key" in c or "jrl" in c:
                    for m in callre.finditer(c):
                        if not m.group(0)[:2].lower() == "jr":
                            called.add(m.group(1))
        self.called = called
        self.span = {}
        self.next_label = {}
        stop = called | set(self.dl) | set(self.keymap)
        for k, L in self.lines.items():
            starts = [(i, LABEL.match(l).group(1)) for i, l in enumerate(L) if l[:1].isalpha() or l[:1] == "_"]
            starts = [(i, n) for i, n in [(i, (LABEL.match(L[i]) or [None, None])[1]) for i, _ in starts] if n]
            ends = [i for i, name in starts if name in stop] + [len(L)]
            at = {i: name for i, name in starts}
            for i, name in starts:
                j = ends[bisect.bisect_right(ends, i)]
                self.span.setdefault(name, (k, i, j))
                if j in at:
                    self.next_label.setdefault(name, at[j])
        self._callees = {}
        fan = collections.defaultdict(set)
        for name in self.span:
            if name in called:
                for t in set(self.callees_of(name)):
                    fan[t].add(name)
        self.fan = collections.Counter({t: len(v) for t, v in fan.items()})

    def body(self, name):
        k, i, j = self.span[name]
        return self.stripped[k][i:j]

    def resolve(self, name):
        seen = 0
        while name in self.thunk and seen < 4:
            name = self.thunk[name]
            seen += 1
        return name

    CALL = re.compile(r'^\s*(?:[A-Za-z_]\w*:\s*)?(call|calr|jp|jrl?)\s+(?:(?:[a-z]+|t)\s*,\s*)?([A-Za-z_]\w*)\s*$', re.I)
    REG = re.compile(r'^(xiy|xix|xiz|xhl|xwa|xbc|xde)$', re.I)
    POSTED = re.compile(r'^(?:ld|lda|push)\s+x\w+\s*,\s*([A-Za-z_]\w*)\s*$', re.I)

    def code80_tables(self):
        """Dispatch_Code80_PaintTable / _RepaintFieldTable (prom_b): one painter per screen code 0x80..0xAF;
        codes 0xC0.. use entry code - 0x40 (Dispatch_Code80_Bracketed / Dispatch_Code80, `sub HL,0x00c0` then
        the table + 0x80)."""
        if not hasattr(self, "_c80"):
            self._c80 = {}
            for tname, key in (("Dispatch_Code80_PaintTable", "paint"), ("Dispatch_Code80_RepaintFieldTable", "field")):
                if tname not in self.where:
                    continue
                image, f, i = self.where[tname]
                ents = []
                for l in self.lines[(image, f)][i + 1:]:
                    m = re.match(r'^\s*\.long\s+([A-Za-z_]\w*)\s*(\+\s*0x[0-9a-fA-F]+)?', l)
                    if not m:
                        if l.strip() and not l.strip().startswith(";"):
                            break
                        continue
                    ents.append(None if m.group(2) else m.group(1))
                self._c80[key] = ents
        return self._c80

    def code80_painter(self, sel, key):
        t = self.code80_tables().get(key, [])
        k = sel - 0x80 if sel < 0xC0 else sel - 0xC0 + 0x20
        return t[k] if 0 <= k < len(t) else None

    def callees_of(self, name):
        if name not in self._callees:
            out = []
            prev = ""
            for l in self.body(name):
                # `pushw <code> / call T_Dispatch_Code80[_Bracketed]`: the painter of screen code <code>, from
                # prom_b's Dispatch_Code80_PaintTable (full paint) or _RepaintFieldTable (one field)
                m = re.match(r'^\s*call\s+(T_Dispatch_Code80_Bracketed|T_Dispatch_Code80)\s*$', l, re.I)
                pm = re.match(r'^\s*pushw\s+(0x[0-9a-fA-F]+|\d+)\s*$', prev, re.I)
                if m and pm:
                    tgt = self.code80_painter(int(pm.group(1), 0),
                                              "paint" if m.group(1).endswith("Bracketed") else "field")
                    if tgt:
                        out.append(tgt)
                prev = l
            for l in self.body(name):
                if "c" in l or "j" in l:
                    m = self.CALL.match(l.strip())
                    if m and not self.REG.match(m.group(2)):
                        out.append(self.resolve(m.group(2)))
                        continue
                # a routine handed over by address -- `ld XWA,Paint_X` / `push` / `lda` before
                # T_CallbackQueue_Post and the like -- runs later on this screen's behalf: follow it too
                m = self.POSTED.match(l.strip())
                if m and m.group(1) in self.called and m.group(1) not in self.dl and m.group(1) not in self.keymap:
                    out.append(self.resolve(m.group(1)))
            # a body that does not end in an unconditional transfer falls through into the next routine
            code = [l.strip() for l in self.body(name) if l.strip() and not LABEL.match(l.strip())]
            last = code[-1] if code else ""
            if name in self.next_label and not re.match(r'^(ret|reti|retd\b|jp\s+(t\s*,\s*)?\(?[A-Za-z_(]|jrl?\s+(t\s*,\s*)?[A-Za-z_.])', last, re.I):
                out.append(self.next_label[name])
            self._callees[name] = out
        return self._callees[name]

    def requests(self, body):
        out = []
        hi = None
        for l in body:
            c = l.strip()
            m = re.search(r'\(UI_Request_Hi:16\)\s*,\s*(0x[0-9a-fA-F]+|\d+)\s*$', c)
            if m and re.match(r'^ld\b', c, re.I):
                hi = int(m.group(1), 0)
                continue
            m = re.search(r'\(UI_Request:16\)\s*,\s*(0x[0-9a-fA-F]+|\d+)\s*$', c)
            if m and re.match(r'^ldw?\b', c, re.I):
                v = int(m.group(1), 0)
                if re.match(r'^ldw\b', c, re.I) or v > 0xFF:
                    out.append(v)
                elif hi is not None:
                    out.append((hi << 8) | v)
                hi = None
        return out

    TOK = re.compile(r'[A-Za-z_]\w*')

    def local(self, name):
        """(display lists, key maps, requests) named in this routine's own body; cached"""
        if not hasattr(self, "_local"):
            self._local = {}
        if name not in self._local:
            dls, kms = [], []
            b = self.body(name)
            for l in b:
                end_bound = re.match(r'^\s*ld\s+xix\s*,', l, re.I)   # XIX is a list's exclusive END, not drawn
                for tok in self.TOK.findall(l):
                    if tok in self.dl and tok not in dls and not end_bound:
                        dls.append(tok)
                    if tok in self.keymap and tok not in kms:
                        kms.append(tok)
            self._local[name] = (dls, kms, self.requests([l for l in b if "UI_Request" in l]))
        return self._local[name]

    def scan(self, name, depth=DEPTH, seen=None):
        """-> (display lists, key maps, requests) reached from routine <name>."""
        if seen is None:
            seen = set()
        name = self.resolve(name)
        dls, kms, reqs = [], [], []
        if name in seen or name not in self.span:
            return dls, kms, reqs
        seen.add(name)
        ld, lk, lr = self.local(name)
        dls += ld
        kms += lk
        reqs += lr
        if depth > 0:
            for t in self.callees_of(name):
                if self.fan[t] > FANIN or t in seen:
                    continue
                d2, k2, r2 = self.scan(t, depth - 1, seen)
                dls += [x for x in d2 if x not in dls]
                kms += [x for x in k2 if x not in kms]
                reqs += r2
        return dls, kms, reqs


def vtable(t):
    """[(entry, object name or None)] from PanelScreen_VtableTable and its ViewB alias, by position."""
    image, f, i = t.where["PanelScreen_VtableTable"]
    L = t.lines[(image, f)]
    out = []
    for l in L[i + 1:]:
        m = re.match(r'^\s*\.long\s+([^;\s]+)', l)
        if m:
            out.append(m.group(1))
        elif LABEL.match(l) or not l.strip() or l.strip().startswith(";"):
            continue
        else:
            break
        if len(out) == 256:
            break
    assert len(out) == 256, len(out)
    return out


def object_methods(t, obj):
    if obj == "PanelScreen_NullVtable":
        return None
    if re.match(r'^(0x[0-9a-fA-F]+|\d+)$', obj):
        a = int(obj, 0)
    else:
        a = t.syms["prom_a"].get(obj, t.syms["prom_b"].get(obj))
    if a is None:
        return None
    slots = [t.slot_at.get(a + k) for k in (0, 4, 8)]
    if not any(slots):
        return None         # e.g. entry 13, 0x00F406C4: `ret` filler in the directory, a do-nothing object
    return [(s, t.resolve(s) if s else None) for s in slots]


def describe(v, names):
    hi, lo = v >> 8, v & 0xFF
    parts = []
    if hi & 0x80:
        parts.append("go to screen 0x%02X%s" % (lo, " (%s)" % names[lo] if lo in names else ""))
    elif hi & 0x40:
        parts.append("request screen 0x%02X%s" % (lo, " (%s)" % names[lo] if lo in names else ""))
    if hi & 0x02:
        parts.append("mode change 0x%02X" % lo)
    if hi & 0x10 and not parts:
        parts.append("repaint")
    if not parts:
        parts.append("request 0x%04X" % v)
    return ", ".join(parts)


def table(rows):
    w = [max(len(r[i]) for r in rows) for i in range(len(rows[0]))]
    out = ["| " + " | ".join(c.ljust(w[i]) for i, c in enumerate(rows[0])) + " |",
           "|" + "|".join("-" * (x + 2) for x in w) + "|"]
    for r in rows[1:]:
        out.append("| " + " | ".join(c.ljust(w[i]) for i, c in enumerate(r)) + " |")
    return out


def build():
    t = Tree()
    vt = vtable(t)
    screens = []        # (kind, number, entry, object, methods)
    for e, obj in enumerate(vt):
        m = object_methods(t, obj)
        if not m:
            continue
        if e < 48:
            screens.append(("mode", e, e, obj, m))
        if e >= 32:
            screens.append(("screen", e - 32, e, obj, m))
    names = {}
    for kind, n, e, obj, m in screens:
        if kind == "screen":
            names[n] = m[0][1] or obj
    info = {}
    incoming = collections.defaultdict(list)
    for kind, n, e, obj, m in screens:
        enter, leave, button = [x[1] for x in m]
        dls, kms, reqs = [], [], []
        for meth in (enter, button):
            if meth:
                d, k, r = t.scan(meth)
                dls += [x for x in d if x not in dls]
                kms += [x for x in k if x not in kms]
                if meth == enter:
                    reqs += r
        keys = []
        for km in kms:
            for r, row in enumerate(t.keymap[km]):
                for key, h in row:
                    hres = t.resolve(h)
                    if re.search(r'(_Nop\d*|NoAction|Nop_Ret_\w+|IgnoredKeys_\w+)$', hres) or hres.endswith("_Nop"):
                        continue
                    d, k, rq = t.scan(hres, depth=2)
                    keys.append((km, r, key, hres, rq))
                    for v in rq:
                        if v >> 8 & 0xC0:
                            incoming[v & 0xFF].append((kind, n, key, hres))
        info[(kind, n)] = dict(entry=e, obj=obj, methods=m, dls=dls, kms=kms, keys=keys, reqs=reqs)
    return t, screens, names, info, incoming


def title_of(t, dls):
    for d in dls:
        if t.dl.get(d):
            return " / ".join(t.dl[d][:3])
    return ""


def render():
    t, screens, names, info, incoming = build()
    o = []
    o.append("# SX-WSA1R GUI menu map")
    o.append("")
    o.append("Generated by `wsa1/scripts/analysis/gui_menu_map.py` from the sources; do not edit by hand.")
    o.append("Regenerate with `make -C wsa1 gui-menu-map`; `make -C wsa1 gui-menu-map-check` fails when it is stale.")
    o.append("")
    o.append("Every screen is an object in `PanelScreen_VtableTable` (prom_a): three directory slots, its Enter,")
    o.append("Leave and Button methods. Entries 0-47 are the panel modes, and entry 32 + n is screen id n, the")
    o.append("number a screen request carries. For each one this lists what the code says it draws (the display")
    o.append("lists its Enter and Button methods name, with their first texts), the key map its Button method")
    o.append("reads (the handler per panel key; do-nothing keys left out), and the screen requests those")
    o.append("handlers write. It is a static reading of the sources (the script's docstring says what it")
    o.append("follows), so a request made through a register or a list chosen through a pointer table is")
    o.append("missing; nothing here is more than the code states.")
    o.append("")
    o.append("Record macros: `wsa1/include/wsa1_gui.inc`. Key names: the `KEY_*` equates there.")
    o.append("")
    o.append("## Index")
    o.append("")
    rows = [["kind", "id", "Enter method", "title (first texts drawn)", "keys", "reached from"]]
    for kind, n, e, obj, m in screens:
        I = info[(kind, n)]
        src = ""
        if kind == "screen" and incoming.get(n):
            ins = sorted({"%s 0x%02X" % (k, s) for k, s, key, h in incoming[n]})
            src = ", ".join(ins[:4]) + (" +%d" % (len(ins) - 4) if len(ins) > 4 else "")
        rows.append([kind, "0x%02X" % n, "`%s`" % (m[0][1] or "?"), title_of(t, I["dls"]).replace("|", "\\|")[:60],
                     str(len(I["keys"])), src])
    o += table(rows)
    o.append("")
    for kind, n, e, obj, m in screens:
        I = info[(kind, n)]
        o.append("## %s 0x%02X: `%s`" % (kind, n, m[0][1] or obj))
        o.append("")
        o.append("Object `%s` (`PanelScreen_VtableTable` entry %d). Enter `%s`, Leave `%s`, Button `%s`." % (
            obj, e, m[0][1], m[1][1], m[2][1]))
        o.append("")
        if kind == "screen" and (0x80 <= n < 0xB0 or 0xC0 <= n < 0xD0):
            pt, ft = t.code80_painter(n, "paint"), t.code80_painter(n, "field")
            if pt or ft:
                o.append("Painted by `%s` (`Dispatch_Code80_PaintTable`), one field at a time by `%s` "
                         "(`Dispatch_Code80_RepaintFieldTable`): the Enter method stores CPU 2's replies (it is re-run "
                         "for each one through `ScreenCode%s_Handlers` by `Cpu2Reply_HandleNext`) and then calls "
                         "the painter with `pushw 0x%02X`." % (pt or "-", ft or "-", "80" if n < 0xC0 else "C0", n))
                o.append("")
        if I["dls"]:
            o.append("Draws:")
            o.append("")
            for d in I["dls"][:16]:
                tx = "; ".join('"%s"' % x for x in t.dl[d][:4])
                o.append("- `%s`%s" % (d, ": " + tx if tx else ""))
            if len(I["dls"]) > 16:
                o.append("- ... %d more" % (len(I["dls"]) - 16))
            o.append("")
        if I["reqs"]:
            o.append("Enter requests: " + "; ".join(sorted({describe(v, names) for v in I["reqs"]})) + ".")
            o.append("")
        if I["keys"]:
            o.append("Keys (%s):" % ", ".join("`%s`" % k for k in I["kms"]))
            o.append("")
            rows = [["key map", "key", "handler", "requests"]]
            for km, r, key, h, rq in I["keys"]:
                rows.append(["`%s`%s" % (km, " row %d" % r if len(t.keymap[km]) > 1 else ""), "`%s`" % key, "`%s`" % h,
                             "; ".join(sorted({describe(v, names) for v in rq}))])
            o += table(rows)
            o.append("")
        if kind == "screen" and incoming.get(n):
            o.append("Reached from: " + "; ".join(sorted({"%s 0x%02X `%s` (`%s`)" % (k, s, key, h)
                                                          for k, s, key, h in incoming[n]})) + ".")
            o.append("")
    return "\n".join(o).rstrip() + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--stdout", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.stdout:
        sys.stdout.write(text)
        return
    if a.check:
        old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if old != text:
            print("STALE: %s is not what the sources give; run: make -C wsa1 gui-menu-map" % os.path.relpath(OUT, ROOT))
            sys.exit(1)
        print("OK: %s is up to date" % os.path.relpath(OUT, ROOT))
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write(text)
    print("wrote %s (%d lines)" % (os.path.relpath(OUT, ROOT), text.count("\n")))


if __name__ == "__main__":
    main()
