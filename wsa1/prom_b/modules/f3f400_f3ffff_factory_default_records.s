
; ==============================================================================
; 0xF3F400-0xF3FFFF -- a THIRD record format, cracked this wave.  [op,len]
; back to back, len = payload byte count (NOT interpreter A/B's whole-record
; count); op 0xFF is a 2-byte section terminator.  Walking this rule over the
; whole span lands exactly on the 672-byte 0x00 pad that runs to the physical
; end of the EPROM -- zero drift across 413 steps.  64 of the records (op
; 0x00-0x3F, each exactly once) are a uniform 32-byte SLOT TABLE; the rest are
; one-off records.  Field semantics are deferred; every byte is placed inside
; a record whose framing is proven, not left as an unexplained `.byte` run.
; Full proof: notes/gen_prom_b_f3f400_module.py.
; ==============================================================================
; ==============================================================================
; ⚠ WHAT THE RECORDS ARE (2026-09-25): the FACTORY DEFAULTS of the parameter
; records.  Each `[id, len, payload]` is copied, payload byte H to record byte
; H, into the RAM record ParamNumber_RecordPtrs (prom_a 0xFACDEA, the table
; (0x60F018) points at) gives for its id -- by prom_a PartSettings_ResetToDefault (routine slot
; T_PartSettings_ResetToDefault; ids 0x00-0x3F, through PtrTable_FAD28A), SystemSettings_ResetToDefault (T_SystemSettings_ResetToDefault; the
; 13 others, through ByteTable_FAD38A + PtrTable_FAD397, then ids 0x61-0x63 on
; to DspEffect_ApplyAlgorithmDefaults via T_DspEffect_ApplyAlgorithmDefaults) and MidiSettings_ResetToDefault (T_MidiSettings_ResetToDefault; bytes 0x0D-0x15 of ids
; 0x00-0x1F).  Ids 0x00-0x1F / 0x20-0x3F are the two halves of the 32 PART
; records (prom_a's ParamNumber_RecordPtrs header): part k's channel byte
; (+0x0D) defaults to k.  The first halves are otherwise identical except part
; 0 (+0x0C = 0x08, all others 0x00) and part 9 -- channel 10 -- (+0x01 = 0x20);
; the second halves except part 9's (+0x19, +0x1C, +0x1D).  Ids 0x61-0x63 are the three DSP effect blocks (IndexedTable entries
; 97-99), defaulting to algorithms 1, 35 and 20.  What the other 11 ids hold is
; for their readers to say.  notes/promb-2026-09-25/factory_default_records.py.
; ==============================================================================

