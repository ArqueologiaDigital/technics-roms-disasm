; =============================================================================
; CUSTOM DATA FLASH ROM — Structure Overview
; =============================================================================
; Hardware: AMD AM29LV800B (8Mbit / 1MB) at IC19
; Address range: 0x300000 - 0x3FFFFF (1MB)
;
; User-writable flash programmed from the "initial data disk" at factory setup.
; The firmware identifies this chip via Flash_IdentifyChip (0xEF3724) using the
; AMD flash command protocol (0xAAAA/0x5555 unlock sequence).
; Device IDs checked: 0x2223 (AM29LV800B-T) and 0x22AB (AM29LV800B-B).
;
; CONTENTS:
;   - Custom accompaniment styles (8 sections, "HK" header format)
;   - LCD wallpaper/screenshot storage (76,800 + 1,024 bytes)
;   - Sound-parameter blocks: "HK " header, 3 user banks, one 0x50 block (4KB)
;   - SubCPU payload staging area (for firmware updates)
;
; ROM LAYOUT:
;
;   0x300000-0x316FFF   92KB  Section 0: Custom Style Data
;   0x317000-0x318FFF    8KB  [erased boot block sector gap]
;   0x319000-0x346FFF  184KB  Sections 1-2: Custom Style Data
;   0x347000-0x348FFF    8KB  [erased sector gap]
;   0x349000-0x376FFF  184KB  Sections 3-4: Custom Style Data
;   0x377000-0x378FFF    8KB  [erased sector gap]
;   0x379000-0x3A6FFF  184KB  Sections 5-6: Custom Style Data
;   0x3A7000-0x3AFFFF   36KB  [unused erased area]
;   0x3B0000-0x3B0FFF    4KB  Section 7: block slot store -- header and owner maps (see below)
;   0x3B1000-0x3BFFFF   60KB  [erased: the rest of section 7's slots]
;   0x3C0000-0x3D2FFF   78KB  LCD Wallpaper/Screenshot Storage
;   0x3D3000-0x3D3FFF    4KB  Sound-parameter user banks (SndParam_*)
;   0x3D4000-0x3DFFFF   48KB  [erased]
;   0x3E0000-0x3FFFFF  128KB  SubCPU Payload Staging Area
;
; SECTION POINTER TABLE (computed at runtime by Flash_InitExtMemAddrs, 0xF16A57):
;   Section 0: 0x300000  (RAM 0x0C76)   Section 4: 0x360000  (RAM 0x0C86)
;   Section 1: 0x319800  (RAM 0x0C7A)   Section 5: 0x379800  (RAM 0x0C8A)
;   Section 2: 0x330000  (RAM 0x0C7E)   Section 6: 0x390000  (RAM 0x0C8E)
;   Section 3: 0x349800  (RAM 0x0C82)   Section 7: 0x3B0000  (RAM 0x0C92)
;
; STYLE BANKS (sections 0-6): each is one Composer style image, the format of RHYTHM_PATTERN_BUF_A,
; of a .CMP file and of an .RCM section (scripts/build/style_events.py, BANK LAYOUT, has the evidence):
;   +0x0000  "H\0K\0"; +0x1e capacity / 16 (0x1680); +0x20..+0x2b the directory geometry (0x60,
;            0x60, 30 records, 0x100-byte cells, 340 cells, name at +0x40); +0x2e used size / 16
;            (written by AccPatch_InitSlotChain, read by cmp_sv_mae and FileIO_SaveRcmFromFlash)
;   +0x0060  30 section records x 0x60 (STYLE_SECTION 0..29: variations a/b/c 1-4, then intro,
;            fill-in and ending 1-2 of a, b, c): five part pointers, 0x34 parameter bytes, the name
;   +0x13c0  a 64-byte fill-in cell (AccDemo_LoadFillIn)
;   +0x1400  340 cells of 256 bytes, the first 150 = 30 sections x 5 parts
;
; SOUND-PARAMETER BANKS (0x3D3000; see CustomData_SndParamBanks below):
;   +0x000: "HK " + 13 bytes      +0x010 / +0x110 / +0x210: banks 0-2, 234 bytes
;   each = 39 entries {u32 main-CPU RAM address, u8, u8}, address 0 = unused;
;   +0x400: 0x50 bytes
; =============================================================================

