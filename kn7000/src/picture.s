# IC19, the picture ROM (C3CBMD000098, 64 Mbit mask ROM), as the CPU sees it at 0x57800000:
# the 100 PRESET pictures of the Slide Show, each a 640x240 JPEG in src/picture/.
#
# Only 2 MB of the chip is reachable: its top address pin is tied low on the board (JP10), and
# the half that remains holds this 2 MB twice, so the 8 MB window 0x57800000-0x57FFFFFF shows it
# four times. Read through the CPU on a KN7000 (PROGRAM 893) on 2026-10-19 by tools/cnv_romdump;
# `make verify-picture` checks the rebuild is byte-identical. See notes/ic19-picture-rom.md.
#
# Generated by tools/gen_picture_s.py from that read; edit freely, the build checks the result.

