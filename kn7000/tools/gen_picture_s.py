# gen_picture_s.py IMAGE -- turn a read of IC19, the picture ROM, into src/picture.s plus the 100
# PRESET pictures as files in src/picture/ (preset_00.jpg .. preset_99.jpg), which picture.s includes.
#
# IMAGE is either the 2 MB the CPU sees at 0x57800000, or the 8 MB window as the ROM dumper read it
# (then its four 2 MB quarters must be identical: the window mirrors the 2 MB, notes/ic19-picture-rom.md).
# Every assumption the source makes is checked here first, and `make verify-picture` checks the rebuilt
# image byte for byte:
#   * 0x000: 102 ascending u32 offsets: entry 0, the 100 pictures, and the end of the data;
#   * then zeros up to 0x400, where entry 0 points: the chip's version, ASCII digits ended by a line feed;
#   * each picture is a JPEG (FF D8 .. FF D9) followed only by 0-3 zero bytes, to a 4-byte boundary;
#   * after the end of the data, 0xFF up to 2 MB.
#
#   python3 tools/gen_picture_s.py ../../technics_roms/roms/kn7000/real_dump_v1.3_b893/pass2-run1/IC19.BIN
import hashlib
import os
import struct
import sys

SIZE = 0x200000                 # what the CPU sees; the 8 MB window repeats it
BASE = 0x57800000
NPIC = 100                      # the firmware's picture code accepts PRESET 0..99
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src')

img = open(sys.argv[1], 'rb').read()
if len(img) == 4 * SIZE:
    assert all(img[k * SIZE:(k + 1) * SIZE] == img[:SIZE] for k in range(4)), 'the 8 MB window is not 4 x the same 2 MB'
    img = img[:SIZE]
assert len(img) == SIZE, f'{len(img):#x} bytes: expected 2 MB or 8 MB'

offs = list(struct.unpack_from(f'<{NPIC + 2}I', img, 0))
assert offs == sorted(offs) and offs[0] == 0x400, 'directory not ascending from 0x400'
assert img[4 * len(offs):0x400] == bytes(0x400 - 4 * len(offs)), 'directory not zero-filled to 0x400'
assert offs[1] - offs[0] == 4, 'entry 0 is not one u32'
version = img[offs[0]:offs[1]]
digits = version[:version.index(b'\n')]
assert digits.isdigit() and version[len(digits) + 1:] == bytes(len(version) - len(digits) - 1), 'entry 0 is not "<digits>\\n"'
end = offs[-1]
assert img[end:] == b'\xff' * (SIZE - end), 'not 0xFF after the end of the data'

os.makedirs(os.path.join(SRC, 'picture'), exist_ok=True)
lines = []
for n in range(NPIC):
    span = img[offs[n + 1]:offs[n + 2]]
    jpeg = span[:span.rfind(b'\xff\xd9') + 2]
    pad = span[len(jpeg):]
    assert jpeg[:2] == b'\xff\xd8' and pad == bytes(len(pad)) and len(pad) == -len(jpeg) % 4, f'picture {n}'
    w = h = None
    i = 2
    while i < len(jpeg):                                        # the frame header gives the size
        mark, ln = jpeg[i + 1], struct.unpack_from('>H', jpeg, i + 2)[0]
        if mark in (0xC0, 0xC1, 0xC2):
            h, w = struct.unpack_from('>HH', jpeg, i + 5)
            break
        i += 2 + ln
    name = f'preset_{n:02d}.jpg'
    open(os.path.join(SRC, 'picture', name), 'wb').write(jpeg)
    lines.append(f'PicturePreset{n:02d}:\n    .incbin "src/picture/{name}"'
                 f'{" " * (6 - len(str(len(jpeg))))}# {w}x{h}, {len(jpeg)} bytes\n    .align 4\n')

with open(os.path.join(SRC, 'picture.s'), 'w') as f:
    f.write(f'''# (c) 2026 Felipe Correa da Silva Sanches <juca@members.fsf.org>
# Licensed under the terms of the GNU General Public License v3 or later
#
# IC19, the picture ROM (C3CBMD000098, 64 Mbit mask ROM), as the CPU sees it at 0x57800000:
# the 100 PRESET pictures of the Slide Show, each a 640x240 JPEG in src/picture/.
#
# Only 2 MB of the chip is reachable: its top address pin is tied low on the board (JP10), and
# the half that remains holds this 2 MB twice, so the 8 MB window 0x57800000-0x57FFFFFF shows it
# four times. Read through the CPU on a KN7000 (PROGRAM 893) on 2026-10-19 by tools/cnv_romdump;
# `make verify-picture` checks the rebuild is byte-identical. See notes/ic19-picture-rom.md.
#
# Generated by tools/gen_picture_s.py from that read; edit freely, the build checks the result.

.mnbase 0x{BASE:08X}

# The directory: u32 offsets from 0x{BASE:08X}. The firmware shows PRESET n from entry n+1
# (0x48580A38 in PROGRAM 941), and accepts n < {NPIC} (0x48580ABE).
PictureDirectory:
    .long PictureVersion - PictureDirectory
''')
    for n in range(NPIC):
        f.write(f'    .long PicturePreset{n:02d} - PictureDirectory\n')
    f.write(f'''    .long PictureEnd - PictureDirectory          # where the data ends
    .space 0x400 - .                             # zeros up to entry 0

# Entry 0: the chip's version, ASCII digits and a line feed ("{digits.decode()}\\n"), padded to 4 bytes.
# The SOFT VERSION screen shows it as PICTURE (AcAromVerBoxProc, 0x48488A0B in PROGRAM 941).
PictureVersion:
    .byte {', '.join(f'0x{c:02X}' for c in version)}

''')
    f.write('\n'.join(lines))
    f.write(f'''
PictureEnd:
    .space 0x{SIZE:X} - (PictureEnd - PictureDirectory), 0xFF
''')
print(f'wrote src/picture.s and {NPIC} pictures; the 2 MB has SHA-1 {hashlib.sha1(img).hexdigest()}')
