"""gen_ic21own_s.py -- write the typed includes of the user-settings blocks of a whole KN7000 IC21 image
(the custom-data flash, 2 MB at CPU 0x96800000) below its CUSTOM STYLE bank:

  midi.inc       chip 0x04000, 0xAA4 bytes: the settings Initial Setting keeps -- the USER MIDI SETTINGs
                 (the .MD part: header, the parameter-id list, three settings), the CUSTOM PANEL (0x7F0
                 bytes of PANEL MEMORY records, PMR_* of src/include/panel_memory.inc) and the 26
                 system-setting halfwords (USR_SETUP)
  favorites.inc  chip 0x10000, 0x198 bytes: FAVORITES (FAV_HEADER, four FAV_BANKs of ten FAV_ITEMs)
  homepage.inc   chip 0x11000, 0x4442 bytes: the HOME PAGE record (HP_HEADER, 64 HP_PARTs) and its BMP,
                 an .incbin of the committed picture the record carries (checked byte for byte)

The macros are those of kn7000/src/include/user_settings.inc; the format and its evidence are in
kn7000/notes/ic21-own/README.md.  The whole-chip source kn7000/src/ic21own/ic21.s (written by hand: it
documents the chip) includes these files, the erased areas, the flash-test pattern and the CUSTOM bank
(src/ic21own/custom.s, gen_customdata_s.py --base 0x20000 --part).  Every emitted line is checked here
against the image: a source this writes either rebuilds the image or the generator stops.

Usage:  gen_ic21own_s.py --rom IMAGE --ref REF_AS_THE_SOURCE_NAMES_IT --out-dir src/ic21own
        [--bmp PATH_AS_THE_SOURCE_NAMES_IT]
"""
import argparse
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "..", "floppy", "tools", "kd"))
from gen_customdata_s import qstr  # noqa: E402
import kn_panel  # noqa: E402  (block(): the tag/length record lists of a panel memory)

SIG = b"JK \0"
UMD, UMD_SIZE = 0x4000, 0xAA4
FAV, FAV_SIZE = 0x10000, 0x198
HP, HP_REC, HP_BMP = 0x11000, 0x18C, 0x42B6
DEFAULT_BMP = "src/b893/program/data/media/Bmp_48743E5C.bmp"

# What each USER MIDI SETTING parameter is (ids from the image; names from the panel-record fields that hold
# the same parameters, src/include/panel_memory.inc, and the MIDI grids that read them).
PARAM = {
    0x204000: "LOCAL (part; PMR_PART midi_octave_local bit 5)",
    0x204001: "MIDI CHANNEL (part; 0xFF = OFF; MidiPartGrid)",
    0x204004: "MIDI OCTAVE (part; -3..+3 stored 0..6)",
    0x00F101: "MIDI CONTROL channel (0xFF = OFF; MidiPartGrid row CONTROL)",
    0x002000: "MIDI message flag (MidiInputGrid)", 0x002001: "MIDI message flag (MidiInputGrid)",
    0x002010: "MIDI message flag (MidiInputGrid)", 0x002012: "MIDI message flag (MidiInputGrid)",
    0x002011: "MIDI message flag (MidiInputGrid, MidiControlGrid)",
    0x002013: "MIDI message flag (MidiInputGrid, MidiControlGrid)",
    0x002014: "MIDI message flag (MidiInputGrid, MidiControlGrid)",
    0x002020: "MIDI message flag (MidiInputGrid, MidiControlGrid)",
    0x002021: "MIDI message flag, 2 bits (MidiInputGrid, MidiControlGrid)",
    0x002022: "MIDI message flag (MidiInputGrid, MidiControlGrid)",
    0x002023: "MIDI message flag (MidiInputGrid, MidiControlGrid)",
    0x002025: "MIDI setting, 2 bits (panel tag 0x47 +2 bits 3-4)",
    0x008090: "MIDI input mode 0..2 (AcMidiInputGridBoxProc)",
    0x008091: "MIDI input setting (MidiInputGrid)",
    0x008092: "MIDI input value 1..127 (MidiInputGrid)",
    0x008060: "split mode (AcSplitBoxProc); not loaded when 0xFF",
    0x008061: "SPLIT POINT, key 21..108 (AcSplitBoxProc); not loaded when 0xFF",
}
for i in list(range(0x2040, 0x2044)) + list(range(0x2080, 0x209A)):
    PARAM.setdefault(i, "MIDI message flag (panel tag 0x47)")

# The 26 halfwords of USR_SETUP (user_settings.inc), in order.
SETUP = ("language disp_time1 disp_time2 disp_time3 disp_time4 disp_time5 disp_time6 jump_insert file_priority "
         "para_load1 para_load2 para_load3 para_load4 wall_home1 wall_home2 wall_home3 wall_home4 s35a6 s35a8 s35aa "
         "data_protect cus_mem_mode s35b0 rsp_select panel_sw1 panel_sw2").split()


def per_part(pid):
    """func_4C01BC28 (lib 0x4C01BC28): 1 = a part parameter, 32 values."""
    return ((pid >> 16) & 0xF0) in (0x20, 0x80, 0x90, 0xB0, 0xC0, 0xD0, 0xE0)


class Out:
    def __init__(self, data, pos, name):
        self.d, self.pos, self.name = data, pos, name
        self.lines = [f"# {name}: part of src/ic21own/ic21.s; GENERATED by kn7000/tools/gen_ic21own_s.py "
                      f"from the reference image (macros: src/include/user_settings.inc)"]

    def w(self, s=""):
        self.lines.append(s)

    def emit(self, text, model, comment=None, label=None):
        got = self.d[self.pos:self.pos + len(model)]
        if got != model:
            sys.exit(f"{self.name}: model mismatch at {self.pos:#x} for {text!r}: {got.hex()} != {model.hex()}")
        line = (f"{label}:" if label else "") + f"\t{text}" + (f"\t# {comment}" if comment else "")
        self.lines.append(line)
        self.pos += len(model)

    def label(self, name):
        self.lines.append(f"{name}:")


def b(vals):
    return ", ".join(f"{x:#04x}" for x in vals)


def gen_midi(d):
    o = Out(d, UMD, "midi.inc")
    m = d[UMD:UMD + UMD_SIZE]
    w = struct.unpack_from("<6H", m, 4)
    if m[:4] != SIG or w[1:] != (0x10, 0xC0, 0xD0, 0x90, 3):
        sys.exit("midi.inc: not a USER MIDI SETTING image")
    o.label("PersistentSettings")
    o.w(f"# ---- the USER MIDI SETTINGs: the .MD part (0x280 bytes, the layout of a .MD file)")
    o.emit(f"UMD_HEADER {w[0]}, UmdParams - UserMidiSetting, UmdParams_End - UmdParams, UmdSet1 - UserMidiSetting, "
           f"UmdSet2 - UmdSet1, 3", m[0:0x10], label="UserMidiSetting")
    ids = list(struct.unpack_from("<48I", m, 0x10))
    o.label("UmdParams")
    live = []
    for pid in ids:
        if pid == 0xFFFFFF:
            o.emit("UMD_PARAM_END", struct.pack("<I", pid))
            continue
        if live and live[-1] == 0xFFFFFF:
            sys.exit("midi.inc: an id after the end marker")
        live.append(pid)
        o.emit(f"UMD_PARAM {pid:#08x}", struct.pack("<I", pid), PARAM.get(pid, "[no name traced]"))
    o.label("UmdParams_End")
    used = sum(32 if per_part(p) else 1 for p in live)
    for k in range(3):
        o.w()
        o.w(f"# USER MIDI SETTING {k + 1}: one value per parameter of UmdParams, in its order ({used} bytes)")
        o.label(f"UmdSet{k + 1}")
        for pid in live:
            if per_part(pid):
                v = m[o.pos - UMD:o.pos - UMD + 32]
                o.emit(f"UMD_PARTS {b(v)}", v, f"{pid:#08x} {PARAM.get(pid, '')}")
            else:
                v = m[o.pos - UMD:o.pos - UMD + 1]
                o.emit(f"UMD_VALUE {pid:#08x}, {v[0]:#04x}", v, PARAM.get(pid))
        pad = 0x90 - used
        o.emit(f".space {pad}, 0xff", b"\xff" * pad, f"not written: the 0x90-byte setting holds {used} values")
    o.w()
    o.w("# ---- the CUSTOM PANEL (+0x280, 0x7F0 bytes): the live panel state 0x84000020 as func_4C021903 stores it")
    o.w("# (SET + CUSTOM PANEL: func_4C021F7F / func_4C021FD9) and recalls it (func_4C021FB8 / func_4C022012): a")
    o.w("# PANEL MEMORY record (0x750 bytes, 43 records), then a second record list (0xA0 bytes), each ended by FF FF")
    p = m
    q = 0x280
    for blk, lab in ((1, "CustomPanel"), (2, "CustomPanel_Rest")):
        recs, end = kn_panel.block(p, q)
        if recs is None:
            sys.exit(f"midi.inc: CUSTOM PANEL block {blk} does not parse")
        o.label(lab)
        for r, t, n in recs:
            pay = p[r + 2:r + 2 + n]
            whole = p[r:r + 2 + n]
            v = ", ".join(str(x) for x in pay)
            if t == 0x40 and n == 18:
                o.emit("PMR_NAME_HEAD", whole[:2])
                o.emit(f".ascii {qstr(pay[:16])}", pay[:16], "the memory's name")
                o.emit(f"PMR_NAME_TAIL {pay[16]}, {pay[17]}", pay[16:18])
            elif t in kn_panel.PARTS and n == 72:
                o.emit(f"PMR_PART {t:#04x}, {v}", whole)
            elif 0x13 <= t <= 0x1A and n == 4:
                o.emit(f"PMR_ENTRY {t:#04x}, {v}", whole)
            elif (t, n) in kn_panel.OTHER:
                o.emit(f"PMR_{t:02X}_{n} {v}", whole)
            else:
                sys.exit(f"midi.inc: panel record tag {t:#x} length {n} has no macro")
        o.emit("PMR_END", b"\xff\xff")
        q = end
    if q != 0xA70:
        sys.exit(f"midi.inc: the CUSTOM PANEL ends at +{q:#x}, not +0xA70")
    o.w()
    o.w("# ---- system settings (+0xA70, 26 halfwords)")
    hw = struct.unpack_from("<26H", m, 0xA70)
    o.emit("USR_SETUP " + ", ".join(f"{x:#06x}" if x >= 0x100 else str(x) for x in hw), m[0xA70:0xAA4],
           label="SystemSetup")
    o.label("PersistentSettings_End")
    if o.pos != UMD + UMD_SIZE:
        sys.exit("midi.inc: size")
    return o


def gen_fav(d):
    o = Out(d, FAV, "favorites.inc")
    f = d[FAV:FAV + FAV_SIZE]
    if f[:4] != SIG:
        sys.exit("favorites.inc: no signature")
    stamp = struct.unpack_from("<I", f, 4)[0]
    o.emit(f"FAV_HEADER {stamp:#010x}", f[:8], label="Favorites")
    for k in range(4):
        r = f[8 + 100 * k:8 + 100 * (k + 1)]
        o.w()
        o.emit(f"FAV_BANK {qstr(r[:16])}, {struct.unpack_from('<I', r, 16)[0]}", r[:20], f"bank {k + 1}",
               label=f"FavBank{k + 1}")
        for i in range(10):
            kind, val = struct.unpack_from("<II", r, 20 + 8 * i)
            o.emit(f"FAV_ITEM {kind}, {val:#x}", r[20 + 8 * i:28 + 8 * i])
    o.label("Favorites_End")
    return o


def gen_hp(d, bmp_src, bmp_path):
    o = Out(d, HP, "homepage.inc")
    h = d[HP:HP + HP_REC]
    if h[:4] != SIG:
        sys.exit("homepage.inc: no signature")
    stamp, typ = struct.unpack_from("<II", h, 4)
    o.emit(f"HP_HEADER {stamp:#x}, {typ}", h[:12], label="HomePage")
    for i in range(64):
        k, x, y = struct.unpack_from("<3H", h, 12 + 6 * i)
        o.emit(f"HP_PART {k:#06x}, {x:#06x}, {y:#06x}", h[12 + 6 * i:18 + 6 * i], f"part {i}" if i % 8 == 0 else None)
    pic = open(bmp_path, "rb").read()
    if d[HP + HP_REC:HP + HP_REC + HP_BMP] != pic or len(pic) != HP_BMP:
        sys.exit(f"homepage.inc: the BMP at {HP + HP_REC:#x} is not {bmp_path}")
    o.w()
    o.w("# The home-page picture: byte for byte program 893's default BMP (HpBmpResetDefault programs it here;")
    o.w("# 941 Bmp_48745718 and 04HPGINI.HMP's picture are the same 17,078 bytes), 160 x 100.")
    o.lines.append(f'HomePageBmp:\t.incbin "{bmp_src}"')
    o.pos += HP_BMP
    o.label("HomePage_End")
    return o


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rom", required=True)
    ap.add_argument("--ref", required=True)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--bmp", default=DEFAULT_BMP)
    a = ap.parse_args()
    d = open(a.rom, "rb").read()
    if len(d) != 0x200000:
        sys.exit(f"{a.rom}: {len(d):#x} bytes, expected the whole 2 MB chip")
    os.makedirs(a.out_dir, exist_ok=True)
    for o in (gen_midi(d), gen_fav(d), gen_hp(d, a.bmp, a.bmp)):
        path = os.path.join(a.out_dir, o.name)
        open(path, "w").write("\n".join(o.lines) + "\n")
        print(f"wrote {path}: {len(o.lines)} lines")


if __name__ == "__main__":
    main()
