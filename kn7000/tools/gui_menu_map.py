r"""gui_menu_map.py -- the KN7000 GUI as a browsable Markdown map, read from the source.

QUESTION ANSWERED
-----------------
"Which screens does the program have, what is on each of them, and which
title / menu entry leads where?"  It reads only the committed source of the
typed data region (src/program/data/*.s, gui_classes.inc, gui_ids.inc, all
generated by tools/gen_data_s.py), never the ROM, so the map is exactly what
the source says:

  * every widget record is a class-macro invocation `Class name, super=...,
    title=TT_..., exit=TT_..., ...` (gui_classes.inc lists the class macros);
  * an OBJ line puts an object in its block's Viewable table;
  * gui_ids.inc gives every title id (TT_*) the screen object its
    RegisterTitle call opens (`# screen <object>`).

The map lists, per OT block, each top-level object (a Screen, Window, ...)
with the titles that open it, then its widget tree (class, name, label text,
rect, and where a title menu / exit leads), and ends with an index of the
titles: the screen each opens and the widgets that lead to it.

RUN
    python3 tools/gui_menu_map.py                  # write notes/gui-data-region/menu-map.md
    python3 tools/gui_menu_map.py --check          # exit 1 if that file is stale (make verify-gui-map)
"""

import argparse
import collections
import glob
import os
import re
import sys

KN7 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(KN7, "src", "program", "data")
OUT = os.path.join(KN7, "notes", "gui-data-region", "menu-map.md")
# --profile: another program tree generated by tools/gen_data_s.py --profile <name>
# (SRC, OUT, the map's title; paths relative to kn7000/)
PROFILES = {
    "kn6000": ("../kn6000/src/program/data", "../kn6000/notes/gui-menu-map.md",
               "SX-KN6000 GUI menu map (program v7.1)"),
    "kn6500": ("../kn6500/src/program/data", "../kn6500/notes/gui-menu-map.md",
               "SX-KN6500 GUI menu map (program v1.3)"),
    "kn2400": ("../kn2400/src/program/data", "../kn2400/notes/gui-menu-map.md",
               "SX-KN2400 / SX-KN2600 GUI menu map (program v1.1)"),
    "hdsx3": ("../hdsx3/src/program/data", "../hdsx3/notes/gui-menu-map.md",
              "KN6000 / KN6500 expansion-board XAPR plug-in (sx6-113, HD-SX6) GUI menu map"),
}
HEADING = "KN7000 GUI menu map (program build 941)"
BLOCKS = "OT blocks"           # what a Viewable table is called (the KN6000 has no OT blocks)
LINK_FIELDS = ("title", "exit", "titleNow1", "titleExit1", "titleNow2", "titleExit2", "titleNow3",
               "titleExit3", "titleNow4", "titleExit4", "title2", "snd_exit", "screen", "window", "mode")


def split_args(s):
    out, buf, q = [], "", False
    for ch in s:
        if ch == '"':
            q = not q
        if ch == "," and not q:
            out.append(buf.strip())
            buf = ""
        else:
            buf += ch
    if buf.strip():
        out.append(buf.strip())
    return out


def read_source():
    macros = set()
    for line in open(os.path.join(SRC, "gui_classes.inc"), encoding="latin-1"):
        m = re.match(r"\.macro\s+(\w+)", line)
        if m and m.group(1) not in ("CLASS", "OBJ", "IDNAME"):
            macros.add(m.group(1))
    titles = {}
    for line in open(os.path.join(SRC, "gui_ids.inc"), encoding="latin-1"):
        m = re.match(r"\.equ\s+(\w+),\s*0x[0-9A-Fa-f]+(?:\s*#\s*screen\s+(\S+))?", line)
        if m:
            titles[m.group(1)] = m.group(2)
    objs, order, block_of = {}, [], {}
    for f in sorted(glob.glob(os.path.join(SRC, "data_*.s"))):
        for line in open(f, encoding="latin-1"):
            m = re.match(r"^\t+(\w+)\t(.*)$", line.rstrip("\n"))
            if not m:
                continue
            op, rest = m.group(1), m.group(2)
            text, cm = rest, ""
            if "\t# " in rest:
                text, cm = rest.split("\t# ", 1)
            if op == "OBJ":
                a = split_args(text)
                block_of[a[0]] = a[1].rsplit("_Viewables", 1)[0]
                continue
            if op not in macros:
                continue
            a = split_args(text)
            name = a[0]
            kv = {}
            for x in a[1:]:
                k, _, v = x.partition("=")
                kv[k.strip()] = v.strip()
            texts = re.findall(r'(\w+) "((?:[^"\\]|\\.)*)"', cm)
            objs[name] = dict(name=name, cls=op, kv=kv, texts=texts, children=[])
            order.append(name)
    return macros, titles, objs, order, block_of


def build(objs, order):
    roots = []
    for n in order:
        o = objs[n]
        sup = o["kv"].get("super")
        if sup and sup in objs:
            objs[sup]["children"].append(n)
        else:
            roots.append(n)
    # sibling order: follow next= from the first child (the source order is the ROM's)
    for o in objs.values():
        kids = o["children"]
        if len(kids) > 1:
            first = [k for k in kids if not objs[k]["kv"].get("prev")]
            seq, seen = [], set()
            cur = first[0] if first else kids[0]
            while cur and cur in objs and cur not in seen:
                seq.append(cur)
                seen.add(cur)
                cur = objs[cur]["kv"].get("next")
            o["children"] = seq + [k for k in kids if k not in seen]
    return roots


def rect(kv):
    try:
        return f"{kv.get('X', '0')},{kv.get('Y', '0')} {kv['W']}x{kv['H']}"
    except KeyError:
        return ""


def describe(o, titles):
    kv = o["kv"]
    bits = [f"`{o['cls']}` **{o['name']}**"]
    for k, t in o["texts"]:
        if t:
            bits.append(f'{k} "{t}"')
    r = rect(kv)
    if r:
        bits.append(f"({r})")
    for f in LINK_FIELDS:
        v = kv.get(f)
        if v and re.match(r"TT_\w+$", v):
            scr = titles.get(v)
            arrow = "exit" if "xit" in f else f
            bits.append(f"{arrow} -> {v}" + (f" ({scr})" if scr else ""))
        elif v and f in ("mode",) and v.startswith("MD_"):
            bits.append(f"mode {v}")
        elif v and f in ("screen", "window") and v.endswith("_id"):
            bits.append(f"{f} {v[:-3]}")
    return ", ".join(bits)


def render(titles, objs, order, block_of):
    roots = build(objs, order)
    leads = collections.defaultdict(list)
    for o in objs.values():
        for f in LINK_FIELDS:
            v = o["kv"].get(f)
            if v and v.startswith("TT_") and "xit" not in f:
                leads[v].append(o["name"])
    screen_titles = collections.defaultdict(list)
    for t, scr in titles.items():
        if scr:
            screen_titles[scr].append(t)
    by_block = collections.OrderedDict()
    for r in roots:
        by_block.setdefault(block_of.get(r, "?"), []).append(r)
    L = [f"# {HEADING}", "",
         "GENERATED by `tools/gui_menu_map.py` from the typed data region (`src/program/data/`), itself",
         "generated by `tools/gen_data_s.py`; do not edit by hand (`make gui-map`; `make verify-gui-map` checks it).",
         "", f"{len(objs)} widget objects in {len(by_block)} {BLOCKS}; {len(roots)} top-level objects;",
         f"{sum(1 for t in titles if t.startswith('TT_'))} titles.  A title (TT_*) is what a menu entry or",
         "an EXIT asks for; `gui_ids.inc` gives the screen object each title's RegisterTitle call opens.",
         "Per object: class, name, label text, rect (X,Y WxH), and where a title menu or exit leads.", ""]
    L += ["## Blocks", ""]
    for b, rs in by_block.items():
        L.append(f"- [{b}](#block-{b.lower()}): {len(rs)} top-level objects")
    L.append("")

    def tree(n, depth):
        o = objs[n]
        L.append("  " * depth + "- " + describe(o, titles))
        for c in o["children"]:
            tree(c, depth + 1)
    for b, rs in by_block.items():
        L += [f"## Block {b}", ""]
        for r in rs:
            o = objs[r]
            opened = screen_titles.get(r, [])
            L.append(f"### {r}")
            L.append("")
            L.append(f"`{o['cls']}`" + (f", opened by {', '.join(opened)}" if opened else ""))
            L.append("")
            tree(r, 0)
            L.append("")
    L += ["## Titles", "", "| title | screen | led to from |", "|---|---|---|"]
    rows = []
    for t in sorted(titles):
        if not t.startswith("TT_"):
            continue
        rows.append((t, titles[t] or "", ", ".join(leads.get(t, [])[:6]) + (" ..." if len(leads.get(t, [])) > 6 else "")))
    w = [max(len(x) for x in col) for col in zip(("title", "screen", "led to from"), *rows)]
    L[-2] = "| " + " | ".join(h.ljust(w[i]) for i, h in enumerate(("title", "screen", "led to from"))) + " |"
    L[-1] = "|" + "|".join("-" * (x + 2) for x in w) + "|"
    for r in rows:
        L.append("| " + " | ".join(c.ljust(w[i]) for i, c in enumerate(r)) + " |")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out")
    ap.add_argument("--profile", choices=sorted(PROFILES), help="another program tree (default: build 941)")
    a = ap.parse_args()
    global SRC, HEADING, BLOCKS
    if a.profile:
        src, out, HEADING = PROFILES[a.profile]
        BLOCKS = "Viewable tables"
        SRC = os.path.normpath(os.path.join(KN7, src))
        a.out = a.out or os.path.normpath(os.path.join(KN7, out))
    a.out = a.out or OUT
    _m, titles, objs, order, block_of = read_source()
    text = render(titles, objs, order, block_of)
    if a.check:
        old = open(a.out).read() if os.path.exists(a.out) else ""
        if old != text:
            print(f"gui_menu_map: {os.path.relpath(a.out, KN7)} is stale: run make gui-map")
            sys.exit(1)
        print(f"OK    {os.path.relpath(a.out, KN7)} is up to date ({len(objs)} objects)")
        return
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    open(a.out, "w").write(text)
    print(f"gui_menu_map: wrote {os.path.relpath(a.out, KN7)} ({len(objs)} objects)")


if __name__ == "__main__":
    main()
