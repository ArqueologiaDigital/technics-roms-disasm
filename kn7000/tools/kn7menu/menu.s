# The panel: the firmware's debounced switch bitmaps, one byte per segment, a bit per switch, set while
# the button is down (technics-anotherworld kn7000/probes/PANEL-INPUT.md): CPR segments at V_PANEL + n,
# CPL/CPC segments at V_PANEL + 0x30 + n.

# ReadButtons -> d0 = the B_* bits of the buttons down now (0 without the bitmaps), less the ones
# BUTTONS_USED leaves out.
ReadButtons:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    clr     d2
    mov     (V_PANEL), a2
    cmp     0, a2
    beq     rb_ret
    mov     ButtonTab, a3
    clr     d3                      # bit number
rb_one:
    movbu   (a3), d0                # offset
    mov     a2, a0
    add     d0, a0
    movbu   (a0), d0
    movbu   (1, a3), d1             # mask
    and     d1, d0
    beq     rb_up
    mov     1, d0
    asl     d3, d0
    or      d0, d2
rb_up:
    add     2, a3
    inc     d3
    cmp     NBUTTONS, d3
    bcs     rb_one
    mov     BUTTONS_USED, d0
    and     d0, d2
rb_ret:
    mov     d2, d0
    ret     [d2,d3,a2,a3], 0x30

# FindPanel: V_PANEL = CPR from the panel decoder's two sites (one hit each, the same CPR in both, CPL =
# CPR + 0x30 in both, CPR in work RAM), as technics-anotherworld src/fwfind.s step 0 finds it; else 0.
FindPanel:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    clr     d0
    mov     d0, (V_PANEL)
    mov     sig_panel1, a0
    call    CountFlash, 0, 0
    cmp     1, d0
    bne     fp_ret
    mov     (V_TMP), a2
    mov     sig_panel2, a0
    call    CountFlash, 0, 0
    cmp     1, d0
    bne     fp_ret
    mov     (V_TMP), a3
    mov     a2, a0                  # CPR, from both sites
    add     2, a0
    call    Read32U, 0, 0
    mov     d0, d2
    mov     a3, a0
    add     2, a0
    call    Read32U, 0, 0
    cmp     d2, d0
    bne     fp_ret
    mov     a2, a0                  # CPL, from both
    add     15, a0
    call    Read32U, 0, 0
    mov     d0, d3
    mov     a3, a0
    add     13, a0
    call    Read32U, 0, 0
    cmp     d3, d0
    bne     fp_ret
    mov     d2, d0
    add     0x30, d0
    cmp     d3, d0
    bne     fp_ret
    mov     0x50000000, d0          # in work RAM
    cmp     d0, d2
    bcs     fp_ret
    mov     0x503FFF00, d0
    cmp     d0, d2
    bhi     fp_ret
    mov     d2, (V_PANEL)
fp_ret:
    ret     [d2,d3,a2,a3], 0x30

# CountFlash(a0 = signature) -> d0 = its hits in the program flash; V_TMP = the first.
CountFlash:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     a0, a2
    clr     d2
    mov     d2, (V_TMP)
    mov     0x48400000, a3
cf_next:
    mov     a2, a0
    mov     a3, d0
    mov     0x487FFF00, d1
    call    FindSig, 0, 0
    cmp     0, d0
    beq     cf_done
    cmp     0, d2
    bne     cf_more
    mov     d0, (V_TMP)
cf_more:
    inc     d2
    mov     d0, a3
    inc     a3
    bra     cf_next
cf_done:
    mov     d2, d0
    ret     [d2,d3,a2,a3], 0x30

# FindSig(a0 = signature, d0 = start, d1 = end) -> d0 = the first address in [start, end) where it
# matches, or 0. Elements are 16-bit: 0x00nn = byte nn, 0x0100 = any byte, 0xFFFF = end; the first is a
# byte. (as loader.s FindSig)
FindSig:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     a0, a2
    movhu   (a2), d3
    mov     d0, a3
    mov     d1, (0x14, sp)
fs_loop:
    mov     (0x14, sp), d0
    cmp     d0, a3
    bcc     fs_none
    movbu   (a3), d2
    cmp     d3, d2
    bne     fs_skip
    mov     a2, a0                  # the rest
    add     2, a0
    mov     a3, a1
    inc     a1
fs_cmp:
    movhu   (a0), d0
    mov     0xFFFF, d1
    cmp     d1, d0
    beq     fs_hit
    mov     0x100, d1
    cmp     d1, d0
    beq     fs_any
    movbu   (a1), d1
    cmp     d1, d0
    bne     fs_skip
fs_any:
    add     2, a0
    inc     a1
    bra     fs_cmp
fs_skip:
    inc     a3
    bra     fs_loop
fs_hit:
    mov     a3, d0
    bra     fs_ret
fs_none:
    clr     d0
fs_ret:
    ret     [d2,d3,a2,a3], 0x30

# Read32U(a0) -> d0 = the little-endian word at a0, any alignment. Leaf.
Read32U:
    movbu   (3, a0), d0
    asl     8, d0
    movbu   (2, a0), d1
    or      d1, d0
    asl     8, d0
    movbu   (1, a0), d1
    or      d1, d0
    asl     8, d0
    movbu   (a0), d1
    or      d1, d0
    rets

# Read16U(a0) -> d0 = the little-endian halfword at a0, any alignment. Leaf.
Read16U:
    movbu   (1, a0), d0
    asl     8, d0
    movbu   (a0), d1
    or      d1, d0
    rets

