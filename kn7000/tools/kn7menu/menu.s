# menu.s -- KN7MENU, the program menu: the root KN7APP.BIN that KN7LOAD.CNV (../cnv_romdump/loader.s)
# loads from the SD card. It lists the programs on the card, one per folder of the root (a folder is a
# program when it holds a KN7APP.BIN), each with the name and icon its MANIFEST.TXT gives, and starts the
# one the user picks: it reads that KN7APP.BIN, checks it as the loader would, and hands it to the
# trampoline (tramp.s), which puts it at APP_BASE over the menu and gives it the converter calls.
# README.md describes the menu, the manifest and icon format, the launch block, and what has run where.
#
# How it reads the card: only through the raw sector read the loader found (SV_RAWREAD), parsing the FAT
# itself, read-only. It names no routine that writes (SV_WRITE, SV_RAWWRITE, SV_MKDIR, SV_SETPATH; guard.py
# checks that at every build), and it never writes the loader's resident area.
#
# Each converter call does one step and answers request 5 (a short text, call again), which parks the
# firmware on the converter, as Another World does; the firmware then goes on decoding the panel into its
# switch bitmaps, which the menu reads (found by the panel decoder's code, as Another World's fwfind.s
# finds them). The firmware paints its own text screen when it starts showing request 5 (and on DISPLAY
# HOLD): the menu samples the LCD on every call and draws its screen again when it is no longer its own.
#
# Calling convention: d0, d1, a0, a1 scratch; d2, d3, a2, a3 preserved. A routine that calls anything makes
# a frame first (movm + add -0x20, sp): firmware routines store into 4..0x10(sp) of the caller's frame, so
# a routine's own locals live at 0x14..0x1C(sp).

.include "kn7cnv.inc"
.include "menu.inc"
.include "tramp_syms.inc"           # generated by mkinc.py: T_LAUNCH, T_ERRAPP, TRAMP_LEN (tramp.s)
.mnbase APP_BASE

# ---- application header (mkapp.py fills in the size and the CRC-32) ------------------------------
AppHeader:
    .long   0x41374E4B              # "KN7A"
    .long   LOADER_ABI
    .long   0                       # AH_SIZE
    .long   MenuEntry
    .long   0                       # AH_CRC
    .long   APP_BASE
    .long   0, 0
    .ascii  "KN7000 PROGRAM MENU 1.0"
    .space  AppHeader + 0x40 - .

# ================================================================================================
MenuEntry:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     sp, a0                  # the loader's stack pointer, for the trampoline's return
    add     0x30, a0
    mov     a0, (V_ENTRYSP)
    mov     (V_CALLS), d0
    inc     d0
    mov     d0, (V_CALLS)
    mov     (V_STATE), d0
    cmp     ST_INIT, d0
    beq     me_init
    cmp     ST_PANEL, d0
    beq     me_panel
    cmp     ST_ROOT, d0
    beq     me_root
    cmp     ST_SCAN, d0
    beq     me_scan
    cmp     ST_MENU, d0
    beq     me_menu
    cmp     ST_READ, d0
    beq     me_read
    cmp     ST_FAIL, d0
    beq     me_fail
    bra     me_answer               # ST_END: 0xFE again
me_init:
    call    DoInit, 0, 0
    bra     me_refresh
me_panel:
    call    DoPanel, 0, 0
    bra     me_refresh
me_root:
    call    DoRoot, 0, 0
    bra     me_refresh
me_scan:
    call    DoScan, 0, 0
    bra     me_refresh
me_menu:
    call    DoMenu, 0, 0
    bra     me_refresh
me_read:
    call    DoRead, 0, 0            # starts the program once it is read and sound (no return then)
    bra     me_refresh
me_fail:
    call    DoFail, 0, 0
me_refresh:
    call    Refresh, 0, 0
me_answer:
    mov     MAILBOX, a0
    mov     (V_STATE), d0
    cmp     ST_END, d0
    bne     me_show
    mov     RQ_END, d0              # leave: the firmware's message, then "Continue Next?"
    movbu   d0, (a0)
    bra     me_ret
me_show:
    mov     RQ_SHOW, d0             # request 5: show this text, call again
    movbu   d0, (a0)
    mov     str_request, a1
    mov     40, d1
me_cpy:
    inc     a0
    movbu   (a1), d0
    movbu   d0, (a0)
    inc     a1
    cmp     0, d0
    beq     me_ret
    add     -1, d1
    bne     me_cpy
me_ret:
    ret     [d2,d3,a2,a3], 0x30

# ================================================================================================
# The states.

# DoInit: the loader's service table, the CRC table; the first screen.
DoInit:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     RD_ALL, d0
    mov     d0, (V_REDRAW)
    mov     -1, d0
    mov     d0, (V_FATSEC)
    mov     (SVC+SV_MSCOUNT), d0
    mov     d0, (V_MS)
    mov     str_f_loader, a0        # the table this menu was built for ...
    mov     (SVC+SV_MAGIC), d0
    mov     0x53374E4B, d1          # "KN7S"
    cmp     d1, d0
    bne     di_fail
    mov     (SVC+SV_ABI), d0
    cmp     LOADER_ABI, d0
    bne     di_fail
    mov     str_f_noraw, a0         # ... with a sector read in it
    mov     (SVC+SV_FOUND), d0
    btst    FOUND_RAW, d0
    beq     di_fail
    mov     (SVC+SV_RAWREAD), d0
    cmp     0, d0
    beq     di_fail
    call    InitCrc, 0, 0
    mov     ST_PANEL, d0
    mov     d0, (V_STATE)
    bra     di_ret
di_fail:
    call    Fail, 0, 0
di_ret:
    ret     [d2,d3,a2,a3], 0x30

# DoPanel: the firmware's switch bitmaps (two signature searches of the program flash).
DoPanel:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    call    FindPanel, 0, 0         # V_PANEL, or 0
    mov     str_f_nopanel, a0
    mov     (V_PANEL), d0
    cmp     0, d0
    beq     dp_fail
    mov     ST_ROOT, d0
    mov     d0, (V_STATE)
    mov     RD_STATUS, d0
    mov     d0, (V_REDRAW)
    bra     dp_ret
dp_fail:
    call    Fail, 0, 0
dp_ret:
    ret     [d2,d3,a2,a3], 0x30

# DoRoot: the card's geometry, then the folders of its root directory, the candidates.
DoRoot:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    call    Geometry, 0, 0          # d0 = 0, or a0 = why not
    cmp     0, d0
    bne     dr_fail
    call    ScanRoot, 0, 0          # d0 = 0, or a0 = why not
    cmp     0, d0
    bne     dr_fail
    clr     d0
    mov     d0, (V_SCANI)
    mov     ST_SCAN, d0
    mov     d0, (V_STATE)
    mov     RD_STATUS, d0
    mov     d0, (V_REDRAW)
    bra     dr_ret
dr_fail:
    call    Fail, 0, 0
dr_ret:
    ret     [d2,d3,a2,a3], 0x30

# DoScan: look into the candidates, as many as fit in SCAN_MS (one per call without a clock); then sort
# the programs into ORDER and show the list.
DoScan:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    call    Now, 0, 0
    mov     d0, (V_SCANT0)
ds_next:
    mov     (V_SCANI), d0
    mov     (V_NCAND), d1
    cmp     d1, d0
    bcc     ds_done
    call    RecAddr, 0, 0           # a0 = the record
    call    ScanOne, 0, 0
    mov     (V_SCANI), d0
    inc     d0
    mov     d0, (V_SCANI)
    mov     (V_MS), d0
    cmp     0, d0
    beq     ds_more
    call    Now, 0, 0
    mov     (V_SCANT0), d1
    sub     d1, d0
    cmp     SCAN_MS, d0
    bcs     ds_next
ds_more:
    mov     RD_STATUS, d0
    mov     d0, (V_REDRAW)
    bra     ds_ret
ds_done:
    call    SortPrograms, 0, 0
    clr     d0
    mov     d0, (V_SEL)
    mov     d0, (V_TOP)
    mov     ST_MENU, d0
    mov     d0, (V_STATE)
    mov     RD_ALL, d0
    mov     d0, (V_REDRAW)
    call    ReadButtons, 0, 0       # what is held now is not a press
    mov     d0, (V_BTN)
ds_ret:
    ret     [d2,d3,a2,a3], 0x30

# DoMenu: the buttons. Each press acts once, when it goes down (the bitmaps hold a bit while the button
# is down, and the firmware calls about 20 times a second).
DoMenu:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    call    ReadButtons, 0, 0
    mov     (V_BTN), d1
    mov     d0, (V_BTN)
    not     d1
    and     d1, d0
    mov     d0, d3                  # d3 = the buttons that went down since the last call
    cmp     0, d3
    beq     dm_hold
    mov     (V_PRESSES), d0         # for the tests: how many, and the lowest one
    inc     d0
    mov     d0, (V_PRESSES)
    mov     d3, d1
    clr     d0
dm_low:
    btst    1, d1
    bne     dm_lowset
    lsr     1, d1
    inc     d0
    cmp     NBUTTONS, d0
    bcs     dm_low
dm_lowset:
    mov     d0, (V_LASTBTN)
    clr     d2                      # LCDL 1..5: the program on that row
dm_rows:
    mov     d3, d0
    lsr     d2, d0
    btst    1, d0
    beq     dm_rnext
    mov     (V_TOP), d0
    add     d2, d0
    mov     (V_NPROG), d1
    cmp     d1, d0
    bcc     dm_paging
    mov     d0, (V_SEL)
    bra     dm_moved
dm_rnext:
    inc     d2
    cmp     ROWS, d2
    bcs     dm_rows
dm_paging:
    mov     d3, d0                  # LCDR 1, PAGE UP: the page before
    and     M_UP, d0
    beq     dm_pgdn
    mov     (V_TOP), d0
    cmp     ROWS, d0
    bcs     dm_pgdn
    add     -ROWS, d0
    mov     d0, (V_TOP)
    mov     d0, (V_SEL)
    bra     dm_moved
dm_pgdn:
    mov     d3, d0                  # LCDR 2, PAGE DOWN: the page after
    and     M_DOWN, d0
    beq     dm_prev
    mov     (V_TOP), d0
    add     ROWS, d0
    mov     (V_NPROG), d1
    cmp     d1, d0
    bcc     dm_prev
    mov     d0, (V_TOP)
    mov     d0, (V_SEL)
    bra     dm_moved
dm_prev:
    mov     d3, d0                  # PART SELECT LEFT: the one above
    and     1<<B_PREV, d0
    beq     dm_next
    mov     (V_SEL), d0
    cmp     0, d0
    beq     dm_next
    add     -1, d0
    mov     d0, (V_SEL)
    mov     (V_TOP), d1
    cmp     d1, d0
    bcc     dm_moved
    add     -ROWS, d1
    mov     d1, (V_TOP)
    bra     dm_moved
dm_next:
    mov     d3, d0                  # PART SELECT RIGHT 1: the one below
    and     1<<B_NEXT, d0
    beq     dm_run
    mov     (V_SEL), d0
    inc     d0
    mov     (V_NPROG), d1
    cmp     d1, d0
    bcc     dm_run
    mov     d0, (V_SEL)
    mov     (V_TOP), d1
    add     ROWS, d1
    cmp     d1, d0
    bcs     dm_moved
    mov     d1, (V_TOP)
    bra     dm_moved
dm_run:
    mov     d3, d0                  # LCDR 5, RUN
    and     1<<B_R5, d0
    beq     dm_leave
    call    StartRead, 0, 0
    bra     dm_ret
dm_leave:
    mov     d3, d0                  # LCDR 4, LEAVE: the menu ends when it is let go (so that the firmware's
    and     1<<B_R4, d0             # message, which comes next, never sees this press)
    beq     dm_hold
    mov     1, d0
    mov     d0, (V_LEAVEREQ)
    bra     dm_ret
dm_moved:
    call    ClearMsg, 0, 0
    mov     RD_ALL, d0
    mov     d0, (V_REDRAW)
    bra     dm_ret
dm_hold:
    mov     (V_LEAVEREQ), d0        # LEAVE went down, and is up again: leave
    cmp     0, d0
    beq     dm_exit
    mov     (V_BTN), d0
    and     1<<B_R4, d0
    beq     dm_end
dm_exit:
    call    ExitHeld, 0, 0          # EXIT held QUIT_MS, and let go: leave
    cmp     0, d0
    beq     dm_ret
dm_end:
    mov     ST_END, d0
    mov     d0, (V_STATE)
dm_ret:
    ret     [d2,d3,a2,a3], 0x30

# ExitHeld -> d0 = 1 once EXIT (V_BTN), after being down for QUIT_MS, has been let go, else 0 (V_EXIT_T0
# times it, V_EXITARMED remembers it). Ending on the release keeps the press from reaching the firmware's
# message, which comes up as soon as the menu answers 0xFE.
ExitHeld:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     (V_BTN), d0
    and     1<<B_EXIT, d0
    bne     eh_down
    clr     d0
    mov     d0, (V_EXIT_T0)
    mov     (V_EXITARMED), d0       # let go after the hold: leave
    bra     eh_ret
eh_down:
    call    Now, 0, 0
    mov     (V_EXIT_T0), d1
    cmp     0, d1
    bne     eh_held
    or      1, d0
    mov     d0, (V_EXIT_T0)
    bra     eh_no
eh_held:
    sub     d1, d0
    mov     QUIT_MS, d1
    cmp     d1, d0
    bcs     eh_no
    mov     1, d0
    mov     d0, (V_EXITARMED)
eh_no:
    clr     d0
eh_ret:
    ret     [d2,d3,a2,a3], 0x30

# StartRead: RUN on the selected program: read its KN7APP.BIN to STAGE over the next calls (DoRead).
StartRead:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     (V_NPROG), d0
    cmp     0, d0
    beq     sr_ret
    call    SelRec, 0, 0
    mov     a0, a2
    mov     a2, (V_RUNREC)
    mov     a2, (V_MSGREC)
    mov     (PR_APPSZ, a2), d0      # its size, as the folder gives it
    cmp     0, d0
    beq     sr_size
    mov     STAGE_MAX, d1
    cmp     d1, d0
    bhi     sr_size
    mov     (PR_APPCL, a2), d0
    mov     d0, (V_RDCL)
    clr     d0
    mov     d0, (V_RDPOS)
    mov     d0, (V_RDN)
    mov     CK_NONE, d0
    mov     d0, (PR_CHECK, a2)
    mov     str_m_reading, a0
    mov     C_WARN, d0
    call    SetMsg, 0, 0
    mov     ST_READ, d0
    mov     d0, (V_STATE)
    bra     sr_draw
sr_size:
    mov     CK_SIZE, d0
    mov     d0, (PR_CHECK, a2)
    call    CheckMsg, 0, 0
    mov     C_BAD, d0
    call    SetMsg, 0, 0
sr_draw:
    mov     RD_ALL, d0
    mov     d0, (V_REDRAW)
sr_ret:
    ret     [d2,d3,a2,a3], 0x30

# DoRead: read KN7APP.BIN to STAGE, up to 4 clusters (and about 64 KB) per call; when all of it is there,
# check it as the loader would, and start it (Launch does not return) or say why not.
DoRead:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     (V_RUNREC), a2
    mov     4, d3                   # clusters left for this call
drd_cl:
    mov     (PR_APPSZ, a2), d0      # what is left of the file
    mov     (V_RDPOS), d1
    sub     d1, d0
    beq     drd_check
    mov     (V_CLBYTES), d1
    cmp     d1, d0
    bls     drd_take
    mov     d1, d0
drd_take:
    mov     d0, (0x14, sp)          # bytes from this cluster
    mov     (V_RDN), d1             # a bounded chain
    mov     FILE_MAXCL, d2
    cmp     d2, d1
    bcc     drd_bad
    mov     d0, d1
    mov     STAGE, a0
    mov     (V_RDPOS), d0
    add     d0, a0
    mov     (V_RDCL), d0
    call    ReadCluster, 0, 0       # d0 = cluster, d1 = bytes, a0 = destination -> d0 = 0
    cmp     0, d0
    bne     drd_bad
    mov     (0x14, sp), d0
    mov     (V_RDPOS), d1
    add     d0, d1
    mov     d1, (V_RDPOS)
    mov     (V_RDN), d0
    inc     d0
    mov     d0, (V_RDN)
    mov     (PR_APPSZ, a2), d0
    cmp     d0, d1
    bcc     drd_check               # all of it: no next cluster wanted
    mov     (V_RDCL), d0            # the next cluster
    call    FatNext, 0, 0
    mov     d0, (V_RDCL)
    call    ValidCluster, 0, 0
    cmp     0, d0
    bne     drd_bad
    add     -1, d3
    bne     drd_cl
    bra     drd_ret
drd_bad:
    mov     CK_READ, d0
    bra     drd_verdict
drd_check:
    call    CheckStage, 0, 0        # d0 = CK_*
drd_verdict:
    mov     d0, (PR_CHECK, a2)
    cmp     CK_OK, d0
    bne     drd_refuse
    call    Launch, 0, 0            # does not return
drd_refuse:
    call    CheckMsg, 0, 0          # a0 = the message for d0
    mov     C_BAD, d0
    call    SetMsg, 0, 0
    mov     ST_MENU, d0
    mov     d0, (V_STATE)
    mov     RD_ALL, d0
    mov     d0, (V_REDRAW)
drd_ret:
    ret     [d2,d3,a2,a3], 0x30

# DoFail: the reason stays on screen until EXIT has been held for QUIT_MS (or for HOLD_MS when the
# panel is not known); then the conversion ends.
DoFail:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     (V_PANEL), d0
    cmp     0, d0
    beq     df_time
    call    ReadButtons, 0, 0
    mov     d0, (V_BTN)
    call    ExitHeld, 0, 0
    cmp     0, d0
    bne     df_end
    bra     df_ret
df_time:
    call    Now, 0, 0
    mov     (V_FAILT0), d1
    sub     d1, d0
    mov     HOLD_MS, d1
    cmp     d1, d0
    bcs     df_ret
df_end:
    mov     ST_END, d0
    mov     d0, (V_STATE)
df_ret:
    ret     [d2,d3,a2,a3], 0x30

# Fail(a0 = the reason): the failure screen.
Fail:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     a0, (V_FAIL)
    call    Now, 0, 0
    mov     d0, (V_FAILT0)
    mov     ST_FAIL, d0
    mov     d0, (V_STATE)
    mov     RD_ALL, d0
    mov     d0, (V_REDRAW)
    ret     [d2,d3,a2,a3], 0x30

# Now -> d0 = the kernel's milliseconds, or 50 per converter call without the counter (request 5 is
# answered about 20 times a second). Leaf.
Now:
    mov     (V_MS), a0
    cmp     0, a0
    beq     nw_calls
    mov     (a0), d0
    rets
nw_calls:
    mov     (V_CALLS), d0
    mov     50, d1
    mulu    d1, d0
    rets

# ================================================================================================
# Starting a program; the trampoline (tramp.s) does the rest.

# CheckStage -> d0 = CK_OK, or why the file in STAGE is not one the loader would start: its checks, in its
# order (size, magic, loader ABI, link address, size field, entry), then the CRC-32.
CheckStage:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     (V_RUNREC), a2
    mov     (PR_APPSZ, a2), d2
    mov     CK_HEADER, d3
    mov     0x40, d0
    cmp     d0, d2
    bcs     cs_ret
    mov     (STAGE+AH_MAGIC), d0
    mov     0x41374E4B, d1          # "KN7A"
    cmp     d1, d0
    bne     cs_ret
    mov     CK_ABI, d3
    mov     (STAGE+AH_ABI), d0
    cmp     LOADER_ABI, d0
    bne     cs_ret
    mov     CK_HEADER, d3
    mov     (STAGE+AH_BASE), d0
    mov     APP_BASE, d1
    cmp     d1, d0
    bne     cs_ret
    mov     (STAGE+AH_SIZE), d0
    cmp     d2, d0
    bne     cs_ret
    mov     (STAGE+AH_ENTRY), d0
    mov     APP_BASE+AH_NAME+0x20, d1
    cmp     d1, d0
    bcs     cs_ret
    mov     APP_BASE, d1
    add     d2, d1
    cmp     d1, d0
    bcc     cs_ret
    mov     STAGE+AH_NAME, a0
    mov     d2, d0
    add     -AH_NAME, d0
    call    Crc32, 0, 0
    mov     (STAGE+AH_CRC), d1
    mov     CK_CRC, d3
    cmp     d1, d0
    bne     cs_ret
    mov     CK_OK, d3
cs_ret:
    mov     d3, d0
    ret     [d2,d3,a2,a3], 0x30

# Launch: the program in STAGE is sound. Put the sled, the trampoline and its data in place, empty the
# caches the way the trampoline will (README.md, "Caches"), and call it. It returns to the loader for us,
# not here.
Launch:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     (V_RUNREC), a2
    mov     (PR_APPSZ, a2), d2
    mov     STAGE, a0               # zeros after the file, to a word boundary (the copy goes by words)
    add     d2, a0
    mov     3, d1
    clr     d0
lc_pad:
    movbu   d0, (a0)
    inc     a0
    add     -1, d1
    bne     lc_pad
    mov     T_SLED, a0              # the sled: nops, and a rets as its last two bytes
    mov     SLED_LEN/4, d1
    mov     0xCBCBCBCB, d0
lc_sled:
    mov     d0, (a0)
    add     4, a0
    add     -1, d1
    bne     lc_sled
    mov     0xF0, d0                # its last two bytes
    movbu   d0, (-2, a0)
    mov     0xFC, d0
    movbu   d0, (-1, a0)
    mov     TrampImage, a0          # the trampoline
    mov     T_CODE, a1
    mov     TRAMP_LEN, d1
lc_code:
    movbu   (a0), d0
    movbu   d0, (a1)
    inc     a0
    inc     a1
    add     -1, d1
    bne     lc_code
    mov     T_DATA, a3              # its data
    mov     a3, a0
    mov     TD_LEN/4, d1
    clr     d0
lc_clr:
    mov     d0, (a0)
    add     4, a0
    add     -1, d1
    bne     lc_clr
    mov     (V_ENTRYSP), d0
    mov     d0, (TD_RETSP, a3)
    mov     d2, (TD_SIZE, a3)
    mov     (V_MS), d0
    mov     d0, (TD_MS, a3)
    mov     C_TEXT, d0
    mov     d0, (TD_FG, a3)
    mov     C_BG, d0
    mov     d0, (TD_BG, a3)
    mov     T_DATA+TD_MSG, a0
    mov     str_t_failed, a1
    call    StrCpy, 0, 0
    mov     T_DATA+TD_LB, a3        # the launch block it installs (kn7cnv.inc LB_*)
    mov     LAUNCH_MAGIC, d0
    mov     d0, (LB_MAGIC, a3)
    mov     LAUNCH_ABI, d0
    mov     d0, (LB_ABI, a3)
    mov     d2, (LB_SIZE, a3)
    mov     (STAGE+AH_CRC), d0
    mov     d0, (LB_CRC, a3)
    mov     LAUNCH_CHECK, d0
    mov     d0, (LB_CHECK, a3)
    mov     a3, a0                  # "AW"
    add     LB_DIR, a0
    mov     a2, a1
    add     PR_DIR, a1
    call    StrCpy, 0, 0
    mov     a3, a0                  # "AW\"
    add     LB_PREFIX, a0
    mov     a2, a1
    add     PR_DIR, a1
    call    StrCpy, 0, 0
    mov     0x5C, d0
    movbu   d0, (a0)
    mov     a3, a0                  # "C:\AW"
    add     LB_PATH, a0
    mov     str_croot, a1
    call    StrCpy, 0, 0
    mov     a2, a1
    add     PR_DIR, a1
    call    StrCpy, 0, 0
    mov     a3, a0                  # the name shown
    add     LB_NAME, a0
    mov     a2, a1
    add     PR_NAME, a1
    call    StrCpy, 0, 0
    mov     1, d0
    mov     d0, (V_LAUNCHES)
    call    EvictD, 0, 0            # the trampoline and the sled to RAM, out of the data cache
    mov     T_SLED, a0              # and no old line of their region left in the I-cache
    calls   (a0)
    mov     T_SLED, a0
    calls   (a0)
    mov     T_LAUNCH, a0
    calls   (a0)                    # returns to the loader, not here
lc_hang:
    bra     lc_hang

# EvictD: as tramp.s EvictD -- read EVICT_LEN bytes of program flash, a load per 16-byte line. Leaf.
EvictD:
    mov     EVICT_FROM, a0
    mov     EVICT_LEN/16, d1
ed_line:
    mov     (a0), d0
    add     16, a0
    add     -1, d1
    bne     ed_line
    rets

# CheckMsg(d0 = CK_*) -> a0 = its message. Leaf.
