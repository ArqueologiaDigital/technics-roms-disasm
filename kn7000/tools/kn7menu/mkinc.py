# mkinc.py -- the trampoline (tramp.s, assembled to run at T_CODE) as data inside the menu: the menu copies
# these bytes to T_CODE before it starts a program (menu.s Launch).
#   python3 -I mkinc.py tramp.bin tramp.map OUTDIR
# writes OUTDIR/tramp_bin.inc (.byte lines) and OUTDIR/tramp_syms.inc (T_LAUNCH, T_ERRAPP, TRAMP_LEN), and
# checks that the image fits in T_CODE_MAX (menu.inc) -- passed as the fourth argument when given.
import os
import sys

binf, mapf, out = sys.argv[1:4]
limit = int(sys.argv[4], 0) if len(sys.argv) > 4 else None
img = open(binf, 'rb').read()
syms = {}
for line in open(mapf):
    a, name = line.split()
    syms[name] = int(a, 16)
if limit is not None and len(img) > limit:
    sys.exit(f'mkinc: tramp.bin is {len(img)} bytes, more than T_CODE_MAX {limit}')
with open(os.path.join(out, 'tramp_bin.inc'), 'w') as f:
    f.write('# generated by mkinc.py from tramp.bin: do not edit\n')
    for i in range(0, len(img), 16):
        f.write('    .byte   ' + ', '.join(f'0x{b:02x}' for b in img[i:i + 16]) + '\n')
with open(os.path.join(out, 'tramp_syms.inc'), 'w') as f:
    f.write('# generated by mkinc.py from tramp.map: do not edit\n')
    f.write(f'.equ T_LAUNCH,      0x{syms["Launch"]:08X}\n')
    f.write(f'.equ T_ERRAPP,      0x{syms["ErrApp"]:08X}\n')
    f.write(f'.equ TRAMP_LEN,     {len(img)}\n')
print(f'mkinc: tramp.bin {len(img)} bytes, Launch 0x{syms["Launch"]:08X}, ErrApp 0x{syms["ErrApp"]:08X}')
