# syms.py -- the menu's addresses and constants for the MAME scripts: every .equ of kn7cnv.inc and menu.inc,
# and every label of the menu's and the trampoline's maps, as a Lua table.
#   python3 -I test/syms.py LOADER_DIR BUILD_DIR OUT.lua
import os
import re
import sys

loader, build, out = sys.argv[1:4]
here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
syms = {}
for p in (os.path.join(loader, 'kn7cnv.inc'), os.path.join(here, 'menu.inc')):
    for line in open(p):
        m = re.match(r"\s*\.equ\s+(\w+)\s*,\s*([^#]+)", line)
        if not m:
            continue
        try:
            py = re.sub(r"0x[0-9A-Fa-f]+|\d+|[A-Za-z_]\w*",
                        lambda t: t.group(0) if t.group(0)[0].isdigit() else str(syms[t.group(0)]), m.group(2).strip())
            syms.setdefault(m.group(1), int(eval(py.replace('/', '//'), {"__builtins__": {}})))
        except (KeyError, SyntaxError):
            pass
for mp in ('menu.map', 'tramp.map'):
    for line in open(os.path.join(build, mp)):
        a, name = line.split()
        syms.setdefault(name, int(a, 16))
with open(out, 'w') as f:
    f.write('-- generated by test/syms.py from kn7cnv.inc, menu.inc and the maps\nreturn {\n')
    for k in sorted(syms):
        f.write(f'  {k} = {syms[k]},\n')
    f.write('}\n')
