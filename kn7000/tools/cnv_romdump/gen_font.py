# gen_font.py -- the dumper's 8x13 text font, from the X11 misc-fixed 8x13 font ("Public domain font.
# Share and enjoy."). Writes font8x13.inc: 13 bytes per glyph (top row first, bit 7 = leftmost pixel)
# for the 95 printable ASCII characters 0x20..0x7E, labelled Font8x13. Also writes a PNG preview.
#   python3 -I gen_font.py /usr/share/fonts/X11/misc/8x13-ISO8859-1.pcf.gz font8x13.inc [preview.png]
import gzip
import io
import os
import sys
import tempfile

from PIL import Image, ImageDraw, ImageFont, PcfFontFile

src, out = sys.argv[1:3]
raw = gzip.open(src).read() if src.endswith('.gz') else open(src, 'rb').read()
with tempfile.TemporaryDirectory() as tmp:
    base = os.path.join(tmp, 'font')
    PcfFontFile.PcfFontFile(io.BytesIO(raw)).save(base)      # writes font.pil + font.pbm
    font = ImageFont.load(base + '.pil')
lines = ['# generated by gen_font.py from the X11 misc-fixed 8x13 font (public domain); do not edit',
         'Font8x13:']
sheet = Image.new('1', (8 * 16, 13 * 6))
for ch in range(0x20, 0x7f):
    im = Image.new('1', (8, 13))
    ImageDraw.Draw(im).text((0, 0), chr(ch), font=font, fill=1)
    rows = [sum(0x80 >> x for x in range(8) if im.getpixel((x, y))) for y in range(13)]
    lines.append('    .byte   ' + ', '.join(f'0x{r:02x}' for r in rows) + f'   # {chr(ch)!r}')
    i = ch - 0x20
    sheet.paste(im, ((i % 16) * 8, (i // 16) * 13))
open(out, 'w').write('\n'.join(lines) + '\n')
if len(sys.argv) > 3:
    sheet.resize((sheet.width * 4, sheet.height * 4)).save(sys.argv[3])
print(f'{out}: 95 glyphs')
