# Recovers the MILK toolkit's named-constant / enumeration tables from the
# program image. The firmware's property system keeps a big block of
# {name_pointer, value} pairs in the data region (~0x1A0000..0x1D0000): the UI
# colour palette names (CL_*), view flags (VF_*), class flags (CF_*), and the
# part/track/step enumerations (PT_/TR_/SS_/...). Each entry is a 32-bit pointer
# to a NUL-terminated identifier string followed by the 32-bit constant value.
#
# These are the same symbolic names the KN5000 uses (shared MILK framework), and
# they cross-check cleanly against the rest of the reverse engineering: VF_* are
# exactly the object flag bits SetVisible/SetChange/SetConst test, and CL_* index
# the 256-entry display CLUT (with CL_Transparent = 0xF7, the transparent index).
#
# Outputs a human-readable listing (stdout) and, with --inc, an assembler
# include of ".equ NAME, VALUE" lines for use by the disassembly.

import argparse
import re
import struct

PROGRAM_BASE = 0x48400000
SCAN_LO, SCAN_HI = 0x1A0000, 0x1D0000
GROUP_RE = re.compile(r"^([A-Za-z][A-Za-z0-9]*_)")


def read_u32(data, off):
    return struct.unpack_from("<I", data, off)[0]


def recover_constants(data):
    """Returns {group_prefix: [(name, value), ...]} for the enum groups."""
    names = {}
    for m in re.finditer(rb"[A-Za-z_][A-Za-z0-9_]{1,30}\x00", data[SCAN_LO:SCAN_HI]):
        names[PROGRAM_BASE + SCAN_LO + m.start()] = m.group(0)[:-1].decode("latin1")

    groups = {}
    o = SCAN_LO
    while o < SCAN_HI - 8:
        ptr = read_u32(data, o)
        if ptr in names:
            name = names[ptr]
            value = read_u32(data, o + 4)
            g = GROUP_RE.match(name)
            if g:
                groups.setdefault(g.group(1), []).append((name, value))
        o += 4

    # keep only real enum groups (a shared prefix used >= 4 times)
    return {p: e for p, e in groups.items() if len(e) >= 4}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("program_rom", nargs="?", default="baserom/kn7000_program.rom")
    ap.add_argument("--inc", help="also write an assembler .equ include here")
    args = ap.parse_args()
    data = open(args.program_rom, "rb").read()
    groups = recover_constants(data)

    total = sum(len(e) for e in groups.values())
    print(f"# {total} MILK framework constants in {len(groups)} enum groups\n")
    for prefix in sorted(groups):
        entries = groups[prefix]
        print(f"## {prefix}* ({len(entries)})")
        for name, value in entries:
            print(f"  {name:20s} = 0x{value & 0xFFFFFFFF:08X}  ({value if value < 0x80000000 else value - (1 << 32)})")
        print()

    if args.inc:
        with open(args.inc, "w") as f:
            f.write("# KN7000 MILK framework constants (generated by "
                    "tools/gen_constants.py -- do not edit).\n")
            f.write("# Colour palette names (CL_*), view flags (VF_*), part/track "
                    "enums, etc.\n\n")
            for prefix in sorted(groups):
                f.write(f"# {prefix}*\n")
                seen = set()
                for name, value in groups[prefix]:
                    if name in seen:
                        continue
                    seen.add(name)
                    f.write(f".equ {name}, 0x{value & 0xFFFFFFFF:08X}\n")
                f.write("\n")
        print(f"# wrote {args.inc}")


if __name__ == "__main__":
    main()
