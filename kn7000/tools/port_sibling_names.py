"""Names for KN7000 program-941 routines from the other MN10300 images in this tree.

Question it answers: "which of the KN7000's unnamed routines (func_<ADDR>) is a
routine another image names, although the two copies are linked elsewhere and
need not be byte-for-byte the same?"

The other images and where their names come from:

  KN2400   ../kn2400  the firmware's own MILK reflection tables (kn2400.sym) + manual
  KN6000   ../kn6000  the same (kn6000.sym) + manual
  KN6500   ../kn6500  the same (kn6500.sym) + manual
  HDSX3    ../hdsx3   the same (hdsx3.sym) + manual
  IC18     the KN7000 boot ROM (IC18's first 64 KB): kn7000_ic18.sym, read from its code
  CNV      the KORG Style Convert converter: cnv_manual.sym, read from its code

The siblings' *_ported.sym are NOT read: those names came from the KN7000.

Each image is compared with the KN7000 by tools/fn_similarity.py (whole-routine
bodies, relocation-masked; its header has the rules and the three classes
exact / skeleton / fuzzy). Every image is matched on its own; a KN7000 routine is
named only when every image that names it gives the same name, and a name goes to
one routine only. The result is the GENERATED section at the end of
kn7000_manual.sym, one row per name with its evidence, and, under
notes/sibling-name-port/:

  accepted.tsv   every name carried, with its class, scores and the images that agree
  differs.tsv    routines another image names that the KN7000 already names otherwise
                 (by the same rules): kept as they are, listed for review
  report.md      counts per image: carried per class, not carried per reason, and
                 the AUDIT -- on the names both images already share, how often the
                 rules pick the routine the KN7000 gives that name (a measured error
                 rate for the matcher)

Names this tool wrote before count as unnamed when it runs again, so a rerun after
`make program-src` is a fixed point. Run from kn7000/, with the reference images in
place (make baserom here and in the sibling trees) and MAME's unidasm:

    python3 tools/port_sibling_names.py --unidasm ../../tools/unidasm \\
        [--cache $TMPDIR/kn7000-fn-similarity] [--no-audit]

then `make program-src` (and the targets that read kn7000_manual.sym: symbols-sp7001,
program-src-sp7001, xap-src-sp7001, cnv-src, ic18-src).
"""
import argparse
import collections
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fn_similarity as FS  # noqa: E402
import gen_image_s as GI  # noqa: E402

MANUAL = "kn7000_manual.sym"
BEGIN = "; ==== BEGIN GENERATED by tools/port_sibling_names.py -- do not edit by hand ===="
END = "; ==== END GENERATED by tools/port_sibling_names.py ===="
NOTES = "notes/sibling-name-port"
K7_SYMS = ["kn7000.sym", MANUAL, "kn7000_exports_from_942.sym"]
K7_CODE = ["0x80:0x186000", "0x3b8fd1:0x3f6f01:0x4c000000"]

# image: (rom, base, code ranges as in its Makefile, symbol files)
SIBLINGS = {
    "KN2400": ("../kn2400/baserom/kn2400_program.rom", 0x48400000,
               ["0x0:0x10", "0x1e427c:0x3285be", "0x3285be:0x3965bb:0x50120000"],
               ["../kn2400/kn2400.sym", "../kn2400/kn2400_manual.sym"]),
    "KN6000": ("../kn6000/baserom/kn6000_program.rom", 0x4C000000,
               ["0x0:0x10", "0x80:0x176037", "0x3f47ec:0x3f77e7"],
               ["../kn6000/kn6000.sym", "../kn6000/kn6000_manual.sym"]),
    "KN6500": ("../kn6500/baserom/kn6500_program.rom", 0x4C000000,
               ["0x0:0x10", "0x80:0x176839", "0x37e44c:0x381447"],
               ["../kn6500/kn6500.sym", "../kn6500/kn6500_manual.sym"]),
    "HDSX3": ("../hdsx3/baserom/hdsx3_extapr.rom", 0x97800000, ["0x80:0x3ded6"],
              ["../hdsx3/hdsx3.sym", "../hdsx3/hdsx3_manual.sym"]),
    # IC18: ROM code run in place, then the program image the reset code copies to
    # work RAM 0x50000010 (tools/gen_ic18_s.py's layout)
    "IC18": ("baserom/kn7000_ic18_boot.bin", 0x40000000, ["0x594:0xb00", "0xb00:0xfa0c:0x50000010"],
             ["kn7000_ic18.sym"]),
    # a .CNV is one absolute image linked at 0x502B8000 (tools/gen_cnv_s.py)
    "CNV": ("baserom/cnv/korg.cnv", 0x502B8000, None, ["cnv_manual.sym:KORG"]),
}


def ranges(specs, base):
    out = []
    for r in specs:
        f = [int(x, 0) for x in r.split(":")]
        out.append((f[0], f[1], (f[2] - f[0]) if len(f) > 2 else base))
    return sorted(out)


def load_names(paths):
    """{cpu: name} from .sym files; `file:STEM` reads cnv_manual.sym's `STEM 0xADDR NAME` rows."""
    out = {}
    for p in paths:
        stem = None
        if ":" in p:
            p, stem = p.split(":")
        for line in open(p, encoding="utf-8"):
            if line.lstrip().startswith(";"):
                continue
            m = (re.match(rf"{stem}\s+0x([0-9A-Fa-f]+)\s+([A-Za-z_]\w*)", line) if stem else
                 re.match(r"0x([0-9A-Fa-f]+)\s+([A-Za-z_]\w*)", line))
            if m:
                out.setdefault(int(m.group(1), 16), m.group(2))
    return out


def split_manual():
    """kn7000_manual.sym as (text before the generated section, the section's
    {cpu: name}, text after it)."""
    text = open(MANUAL, encoding="utf-8").read()
    if BEGIN not in text:
        return text, {}, ""
    head, rest = text.split(BEGIN + "\n", 1)
    body, tail = rest.split(END + "\n", 1)
    gen = {}
    for line in body.splitlines():
        m = re.match(r"0x([0-9A-Fa-f]+)\s+(\w+)", line)
        if m:
            gen[int(m.group(1), 16)] = m.group(2)
    return head, gen, tail


def kn7000_side(unidasm, cache, generated):
    img = FS.cached_image("baserom/kn7000_program.rom", 0x48400000, ranges(K7_CODE, 0x48400000),
                          unidasm, cache)
    allnames = {c: n for c, n in load_names(K7_SYMS).items() if c not in generated}
    names = {c: n for c, n in allnames.items() if not n.endswith("_entry") and img.off(c) is not None}
    unnamed = {}
    for f in sorted(glob.glob("src/program/*.s")):
        for m in re.finditer(rb"^(func_([0-9A-F]{8})):", open(f, "rb").read(), re.M):
            unnamed[int(m.group(2), 16)] = m.group(1).decode()
    for c, n in generated.items():
        unnamed[c] = n
    return FS.Side(img, names, unnamed), set(allnames.values())


def other_side(key, unidasm, cache):
    rom, base, code, syms = SIBLINGS[key]
    if code is None:
        code = [f"0x0:{os.path.getsize(rom):#x}:{base:#x}"]
    img = FS.cached_image(rom, base, ranges(code, base), unidasm, cache)
    names = {c: n for c, n in load_names(syms).items()
             if not n.endswith("_entry") and img.off(c) is not None}
    return FS.Side(img, names, {})


def table(header, rows):
    """An aligned Markdown table (the tree's rule: space-padded columns)."""
    cols = list(zip(*([header] + rows))) if rows else [[h] for h in header]
    w = [max(len(str(x)) for x in c) for c in cols]
    line = lambda r: "| " + " | ".join(str(x).ljust(w[i]) for i, x in enumerate(r)) + " |"  # noqa: E731
    return [line(header), "|" + "|".join("-" * (x + 2) for x in w) + "|"] + [line(r) for r in rows]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--unidasm", default=os.environ.get("UNIDASM", "../../tools/unidasm"))
    ap.add_argument("--cache", help="keep unidasm's decodes here between runs")
    ap.add_argument("--no-audit", action="store_true", help="skip the audit (faster)")
    ap.add_argument("--only", nargs="*", default=list(SIBLINGS), help="images to read (default: all)")
    a = ap.parse_args()

    head, generated, tail = split_manual()
    B, taken = kn7000_side(a.unidasm, a.cache, generated)
    b_cands = {B.img.off(c) for c in B.unnamed if B.img.off(c) is not None}
    base_names = dict(B.names)
    proposals = collections.defaultdict(list)       # B cpu -> [(image, Row)]
    report, differs, audits = {}, [], {}
    for key in a.only:
        print(f"port_sibling_names: {key}", flush=True)
        A = other_side(key, a.unidasm, a.cache)
        B.names = dict(base_names)                  # every image sees the same KN7000
        a_cands = {A.img.off(c): n for c, n in A.names.items()
                   if not re.fullmatch(r"(func|sub|loc|FUN|LABEL)_[0-9A-Fa-f]+", n)}
        rows, rejected, diff = FS.carry(A, B, a_cands, b_cands, taken,
                                        log=lambda s: print(s, flush=True))
        for r in rows:
            proposals[r.b_cpu].append((key, r))
        report[key] = (collections.Counter(r.cls for r in rows), rejected, len(a_cands))
        differs += [(key,) + d for d in diff]
        if not a.no_audit:
            B.names = dict(base_names)
            bn = {n: B.img.off(c) for c, n in base_names.items()}
            common = {A.img.off(c): bn[n] for c, n in A.names.items() if n in bn}
            audits[key] = (len(common),) + FS.audit(A, B, common)
    B.names = base_names

    # merge: one name per routine, one routine per name, every image agreeing
    accepted, conflicts = [], []
    by_name = collections.defaultdict(set)
    for cpu, ps in proposals.items():
        for _k, r in ps:
            by_name[r.name].add(cpu)
    for cpu, ps in sorted(proposals.items()):
        names = {r.name for _k, r in ps}
        if len(names) != 1 or len(by_name[next(iter(names))]) != 1:
            conflicts.append((cpu, sorted(f"{k}:{r.name}" for k, r in ps)))
            continue
        rank = {"exact": 0, "skeleton": 1, "fuzzy": 2}
        ps = sorted(ps, key=lambda kr: (rank[kr[1].cls], -kr[1].st))
        accepted.append((cpu, ps))

    # the generated section of kn7000_manual.sym
    sec = [BEGIN,
           "; Names carried from other MN10300 images where a routine is the same code, linked",
           "; elsewhere (tools/port_sibling_names.py; the rules are in tools/fn_similarity.py,",
           "; the evidence per name in notes/sibling-name-port/accepted.tsv). Each row: the image",
           "; and address the name comes from, the match class, the routine's length.",
           ";"]
    for cpu, ps in accepted:
        k, r = ps[0]
        also = "".join(f"; also {k2} 0x{r2.a_cpu:08X} ({r2.cls})" for k2, r2 in ps[1:])
        sec.append(f"0x{cpu:08X}  {r.name:<24s}; = {k} 0x{r.a_cpu:08X}, {r.cls}, "
                   f"{r.n} insns{also}")
    sec.append(END)
    if head and not head.endswith("\n"):
        head += "\n"
    open(MANUAL, "w", encoding="utf-8").write(head + "\n".join(sec) + "\n" + tail)

    os.makedirs(NOTES, exist_ok=True)
    with open(os.path.join(NOTES, "accepted.tsv"), "w") as f:
        f.write("kn7000_addr\tname\tclass\timage\timage_addr\tinsns\tskeleton_ratio\tstrict_ratio"
                "\tagreeing_callees_strings\tmargin_kn7000\tmargin_image\talso_from\n")
        for cpu, ps in accepted:
            k, r = ps[0]
            f.write(f"0x{cpu:08X}\t{r.name}\t{r.cls}\t{k}\t0x{r.a_cpu:08X}\t{r.n}\t{r.sk}\t{r.st}\t"
                    f"{r.agree}\t{r.margin_b}\t{r.margin_a}\t"
                    + ",".join(f"{k2}:0x{r2.a_cpu:08X}:{r2.cls}" for k2, r2 in ps[1:]) + "\n")
    with open(os.path.join(NOTES, "differs.tsv"), "w") as f:
        f.write("image\timage_addr\timage_name\tkn7000_addr\tkn7000_name\tclass\n")
        for k, acpu, an, bcpu, bn, cls in sorted(differs):
            f.write(f"{k}\t0x{acpu:08X}\t{an}\t0x{bcpu:08X}\t{bn}\t{cls}\n")

    classes = ["exact", "skeleton", "fuzzy"]
    L = ["# Names carried into the KN7000 from the other MN10300 images: the counts",
         "",
         "GENERATED by `kn7000/tools/port_sibling_names.py` (its docstring has the command); do not",
         "edit. README.md in this directory says how to read it.",
         "",
         f"Unnamed KN7000 routines considered: {len(b_cands)}. Names carried: {len(accepted)} "
         f"({', '.join(f'{c} {sum(1 for _c, ps in accepted if ps[0][1].cls == c)}' for c in classes)}). "
         f"Routines two images name differently, or names two routines want: {len(conflicts)} (not carried).",
         "",
         "## Carried, per image and class (before the merge)",
         ""]
    L += table(["image", "names read", "exact", "skeleton", "fuzzy"],
               [[k, report[k][2]] + [report[k][0].get(c, 0) for c in classes] for k in report])
    reasons = sorted({r for k in report for r in report[k][1]})
    L += ["", "## Not carried, per image and reason", ""]
    L += table(["reason"] + list(report),
               [[r] + [report[k][1].get(r, 0) for k in report] for r in reasons])
    if audits:
        L += ["", "## Audit: names both images already have",
              "",
              "For each name the KN7000 and the image both give a routine, the rules are run on the",
              "image's routine as if its name were new: `right` = they pick the routine the KN7000",
              "gives that name, `wrong` = another one, `none` = no class (nothing carried).",
              ""]
        rows = []
        for k, (n, tally, _wrong) in audits.items():
            rows.append([k, n, tally.get("none", [0, 0])[0]]
                        + [f"{tally.get(c, [0, 0])[0]} / {tally.get(c, [0, 0])[1]}" for c in classes])
        L += table(["image", "shared names", "none", "exact right / wrong", "skeleton right / wrong",
                    "fuzzy right / wrong"], rows)
        L += ["", "The `wrong` picks, with the KN7000's own name for the routine picked:", ""]
        rows = [[k, nm, cls, f"0x{cpu:08X}", base_names.get(cpu, "-")]
                for k, (_n, _t, wrong) in audits.items() for nm, cls, cpu in wrong]
        L += table(["image", "name", "class", "KN7000 routine picked", "its KN7000 name"], rows)
    if conflicts:
        L += ["", "## Not carried: the images disagree", ""]
        L += table(["KN7000 routine", "proposals"], [[f"0x{c:08X}", " ".join(p)] for c, p in conflicts])
    open(os.path.join(NOTES, "report.md"), "w").write("\n".join(L) + "\n")
    print(f"port_sibling_names: {len(accepted)} names -> {MANUAL} (generated section); "
          f"{len(conflicts)} conflicts; {len(differs)} differs; {NOTES}/")


if __name__ == "__main__":
    main()
