# The DSP: the firmware's own host-port routines (found by DspFind), and what is built on them.

# CallTarget (leaf): a0 = address of a "call d16, regs, imm8" (cd lo hi regs imm) -> d0 = its target, d1 = its
# imm8 (the frame it allocates); d0 = 0 when a0 holds no such instruction. (romdump_dsp.s)
CallTarget:
    movbu   (a0), d0
    cmp     0xCD, d0
    bne     ct_none
    movbu   (2, a0), d0
    asl     8, d0
    movbu   (1, a0), d1
    or      d1, d0
    exth    d0
    mov     a0, d1
    add     d1, d0
    movbu   (4, a0), d1
    rets
ct_none:
    clr     d0
    rets

# CheckEntry (leaf): d0 = a function body, d1 = the frame its callers allocate -> d0 = the entry `calls` needs,
# body - 3, which must be "add -frame, sp" (f8 fe -frame); or 0. (romdump_dsp.s)
CheckEntry:
    mov     d0, a0
    add     -3, a0
    movbu   (a0), d0
    cmp     0xF8, d0
    bne     ce_no
    movbu   (1, a0), d0
    cmp     0xFE, d0
    bne     ce_no
    movbu   (2, a0), d0
    add     d1, d0
    and     0xFF, d0
    bne     ce_no
    mov     a0, d0
    rets
ce_no:
    clr     d0
    rets

# DspFind: the firmware's DSP host-port routines, as romdump_dsp.s DspFind finds them (941 / 893 addresses):
#   sig_dspwait  the handshake wait (0x48404D25 / 0x4840AE77): its operands are the "kernel downloaded" flag
#                (+0x0F) and the "DSP dead" flag (+0x36);
#   sig_dspregs  the 2x16 register write and read (0x484052DD / 0x4840B3F5; the read at +0x3E);
#   the read's calls: the index write (body + 6) and the guarded data read (body + 0xE);
# and, new here, the guarded data WRITE, which the uploads need: the register write's second call (body + 0x14:
# the DM-word writer, 0x4840511A / 0x4840B232) makes it at its own body + 0x11 (0x48404EF8 / 0x4840B010). That
# routine must start "movhu d1, (0x1c, sp); movhu d0, (0x18, sp); movbu (dead), d0" with the same dead flag.
# Every call target must be preceded by the "add -frame, sp" its call allocates. Only when all of it holds is
# V_DSPOK set; otherwise the DSP is not touched at all. (find_dspw.py runs the same search over every build.)
DspFind:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    clr     d2
    clr     d0
    mov     d0, (V_DSPOK)
    mov     d0, (V_DWAIT)
    mov     d0, (V_DREGWR)
    mov     d0, (V_DREGRD)
    mov     d0, (V_DIDXWR)
    mov     d0, (V_DDATARD)
    mov     d0, (V_DDATAWR)
    mov     d0, (V_DDEAD)
    mov     d0, (V_DDOWN)
    mov     2, d0                   # sig_dspwait, scanned by DoFind
    call    CountCached, 0, 0
    cmp     1, d0
    bne     dfd_regs
    or      DF_WAIT, d2
    mov     (V_TMP), a2
    mov     a2, (V_DWAIT)
    mov     a2, a0
    add     0x0F, a0
    call    Read32U, 0, 0           # movbu (downloaded), d0
    mov     d0, (V_DDOWN)
    mov     a2, a0
    add     0x36, a0
    call    Read32U, 0, 0           # movbu d0, (dead)
    mov     d0, (V_DDEAD)
dfd_regs:
    mov     3, d0                   # sig_dspregs, scanned by DoFind
    call    CountCached, 0, 0
    cmp     1, d0
    bne     dfd_end
    or      DF_REGS, d2
    mov     (V_TMP), a2
    mov     a2, (V_DREGWR)
    mov     a2, a0
    add     0x3E, a0
    mov     a0, (V_DREGRD)
    add     9, a0                   # the read's body + 6: call DspAddrWrite
    call    CallTarget, 0, 0
    cmp     0, d0
    beq     dfd_data
    call    CheckEntry, 0, 0
    cmp     0, d0
    beq     dfd_data
    mov     d0, (V_DIDXWR)
    or      DF_IDX, d2
dfd_data:
    mov     (V_DREGRD), a0
    add     0x11, a0                # the read's body + 0xE: call the guarded data read
    call    CallTarget, 0, 0
    cmp     0, d0
    beq     dfd_write
    mov     d0, a3                  # its body: movbu (dead), d0 = fc a8 <dead>
    call    CheckEntry, 0, 0
    cmp     0, d0
    beq     dfd_write
    mov     d0, (V_DDATARD)
    movbu   (a3), d0
    cmp     0xFC, d0
    bne     dfd_write
    movbu   (1, a3), d0
    cmp     0xA8, d0
    bne     dfd_write
    mov     a3, a0
    add     2, a0
    call    Read32U, 0, 0
    mov     (V_DDEAD), d1
    cmp     d1, d0
    bne     dfd_write
    or      DF_DATA, d2
dfd_write:
    mov     (V_DREGWR), a0
    add     0x17, a0                # the write's body + 0x14: call the DM-word writer
    call    CallTarget, 0, 0
    cmp     0, d0
    beq     dfd_end
    mov     d0, a3
    call    CheckEntry, 0, 0
    cmp     0, d0
    beq     dfd_end
    mov     a3, a0
    add     0x11, a0                # its body + 0x11: call the guarded data write
    call    CallTarget, 0, 0
    cmp     0, d0
    beq     dfd_end
    mov     d0, a3
    call    CheckEntry, 0, 0
    cmp     0, d0
    beq     dfd_end
    mov     d0, (0x14, sp)
    mov     WriteHead, a0           # movhu d1, (0x1c, sp); movhu d0, (0x18, sp); movbu (abs32), d0
    clr     d3
dfd_head:
    mov     a3, a1
    add     d3, a1
    movbu   (a1), d0
    mov     a0, a1
    add     d3, a1
    movbu   (a1), d1
    cmp     d1, d0
    bne     dfd_end
    inc     d3
    cmp     8, d3
    bcs     dfd_head
    mov     a3, a0
    add     8, a0
    call    Read32U, 0, 0
    mov     (V_DDEAD), d1
    cmp     d1, d0
    bne     dfd_end
    mov     (0x14, sp), d0
    mov     d0, (V_DDATAWR)
    or      DF_WRITE, d2
dfd_end:
    mov     d2, (V_DFOUND)
    cmp     DF_WAIT|DF_REGS|DF_IDX|DF_DATA|DF_WRITE, d2
    bne     dfd_ret
    mov     1, d0
    mov     d0, (V_DSPOK)
dfd_ret:
    ret     [d2,d3,a2,a3], 0x30

# Calls into the firmware (each makes a frame: the firmware's routines store into 4..0x10(sp) of their caller).
# DspRead(d0 = IOP register) -> d0 = its 32 bits. The firmware's read returns (high << 16) + the low half
# sign-extended; when the low half's bit 15 is set that is 0x10000 short, which is added back here.
DspRead:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     (V_DREGRD), a0
    calls   (a0)
    btst    0x8000, d0
    beq     drd_ret
    mov     0x10000, d1
    add     d1, d0
drd_ret:
    ret     [d2,d3,a2,a3], 0x30

# DspWrite(d0 = IOP register, d1 = 32-bit value): the firmware's 2x16 register write, low half first.
DspWrite:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     d1, d2
    and     0xFFFF, d2
    mov     d2, (0x10, sp)          # its third argument: the low half
    lsr     16, d1                  # d1: the high half
    mov     (V_DREGWR), a0
    calls   (a0)
    ret     [d2,d3,a2,a3], 0x30

DspIndex:                           # d0 = the index to latch at 0x98000000 (the firmware's guarded write)
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     (V_DIDXWR), a0
    calls   (a0)
    ret     [d2,d3,a2,a3], 0x30

DspData:                            # -> d0 = one 16-bit read of 0x9C000000 (0xFFFF once the DSP is "dead")
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     (V_DDATARD), a0
    calls   (a0)
    exthu   d0
    ret     [d2,d3,a2,a3], 0x30

DspDataW:                           # d0 = 16 bits to write to 0x9C000000 (the firmware's guarded write: nothing
    movm    [d2,d3,a2,a3], (sp)     #   once the DSP is "dead")
    add     -0x20, sp
    mov     d0, d1
    exthu   d1
    mov     DATA_PORT, d0
    mov     (V_DDATAWR), a0
    calls   (a0)
    ret     [d2,d3,a2,a3], 0x30

DeadFlag:                           # leaf -> d0 = the firmware's dead flag byte (0 when not found)
    mov     (V_DDEAD), a0
    clr     d0
    cmp     0, a0
    beq     dfl2_ret
    movbu   (a0), d0
dfl2_ret:
    rets

DownFlag:                           # leaf -> d0 = the "kernel downloaded" flag byte (0 when not found)
    mov     (V_DDOWN), a0
    clr     d0
    cmp     0, a0
    beq     ddl_ret
    movbu   (a0), d0
ddl_ret:
    rets

# DspUpload(d0 = DSP address, d1 = words, a0 = their 16-bit halves, least significant first, a1 = DMAC_UP_PM or
# DMAC_UP_DM): the firmware's own upload of a block (941 0x48407AAB, 0x48407A86/0x48407A99, 0x48407ADF):
# IIEP0 = address, IMEP0 = 1, CEP0 = words, DMAC0 = 0xA1 (PM, three halves a word) or 0x41 (DM, two); the index
# latched to EPB0 once; the halves; DMAC0 = 0xA0.
DspUpload:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     a0, a2
    mov     a1, d3
    mov     d1, (0x14, sp)
    mov     d0, d1
    mov     IOP_IIEP0, d0
    call    DspWrite, 0, 0
    mov     IOP_IMEP0, d0
    mov     1, d1
    call    DspWrite, 0, 0
    mov     IOP_CEP0, d0
    mov     (0x14, sp), d1
    call    DspWrite, 0, 0
    mov     IOP_DMAC0, d0
    mov     d3, d1
    call    DspWrite, 0, 0
    mov     IOP_EPB0, d0
    call    DspIndex, 0, 0
    mov     (0x14, sp), d2          # halves: two a word, three for PM
    add     d2, d2
    cmp     DMAC_UP_PM, d3
    bne     dup_half
    mov     (0x14, sp), d0
    add     d0, d2
dup_half:
    cmp     0, d2
    beq     dup_close
    movhu   (a2), d0
    add     2, a2
    call    DspDataW, 0, 0
    add     -1, d2
    bra     dup_half
dup_close:
    mov     IOP_DMAC0, d0
    mov     DMAC_CLOSE, d1
    call    DspWrite, 0, 0
    ret     [d2,d3,a2,a3], 0x30

# DspReadback(d0 = first address, d1 = words, a0 = out, a1 = DMAC_RB_PM or DMAC_RB_DM) -> d0 = words read. The
# pass-7 readback (romdump_dsp.s DspReadback): channel 8, slave mode, transmit: flush; IIEP0 = address, IMEP0 = 1,
# CEP0 = words; DMAC0 = mode. Per word: read DMAC0 until FS says EPB0 holds data (FS_POLLS at most: a read of an
# empty EPB0 would hold the bus), latch EPB0, read 3 (PM) or 2 (DM) halves, least significant first. Then flush,
# and DMAC0's control bits as found (0xA0, what the firmware leaves). V_RBFAIL = 1 when it stopped early.
DspReadback:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     a0, a3
    mov     d0, (0x14, sp)
    mov     d1, (0x18, sp)
    mov     a1, (0x1C, sp)
    mov     1, d0
    mov     d0, (V_RBFAIL)
    clr     d2                      # words read
    call    DeadFlag, 0, 0
    cmp     0, d0
    bne     drb_skip
    mov     IOP_DMAC0, d0
    mov     DMAC_FLSH, d1
    call    DspWrite, 0, 0
    mov     IOP_IIEP0, d0
    mov     (0x14, sp), d1
    call    DspWrite, 0, 0
    mov     IOP_IMEP0, d0
    mov     1, d1
    call    DspWrite, 0, 0
    mov     IOP_CEP0, d0
    mov     (0x18, sp), d1
    call    DspWrite, 0, 0
    mov     IOP_DMAC0, d0
    mov     (0x1C, sp), d1
    call    DspWrite, 0, 0
drb_word:
    mov     (0x18, sp), d0
    cmp     d0, d2
    bcc     drb_done
    clr     d3                      # polls
drb_poll:
    call    DeadFlag, 0, 0
    cmp     0, d0
    bne     drb_end
    mov     IOP_DMAC0, d0
    call    DspRead, 0, 0
    mov     0xC000, d1              # FS: 00 empty, 10 partly full, 11 full
    and     d1, d0
    bne     drb_data
    inc     d3
    cmp     FS_POLLS, d3
    bcs     drb_poll
    bra     drb_end
drb_data:
    mov     IOP_EPB0, d0
    call    DspIndex, 0, 0
    call    DspData, 0, 0
    movhu   d0, (a3)
    add     2, a3
    call    DspData, 0, 0
    movhu   d0, (a3)
    add     2, a3
    mov     (0x1C, sp), d0
    btst    0x20, d0
    beq     drb_next
    call    DspData, 0, 0
    movhu   d0, (a3)
    add     2, a3
drb_next:
    inc     d2
    bra     drb_word
drb_done:
    clr     d0
    mov     d0, (V_RBFAIL)
drb_end:
    mov     IOP_DMAC0, d0
    mov     DMAC_FLSH, d1
    call    DspWrite, 0, 0
    mov     IOP_DMAC0, d0
    mov     (V_DMAC0), d1
    mov     DMAC_KEEP, d3
    and     d3, d1
    call    DspWrite, 0, 0
drb_skip:
    mov     d2, d0
    ret     [d2,d3,a2,a3], 0x30

# Verify(d0 = DSP address, d1 = words, a1 = DMAC_RB_PM or DMAC_RB_DM, a2 = what was uploaded) -> d0 = 0 when the
# readback equals it, else 1.
Verify:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     d1, d2                  # halves to compare: two a word, three for PM
    add     d2, d2
    cmp     DMAC_RB_PM, a1
    bne     vf_read
    add     d1, d2
vf_read:
    mov     d1, d3
    mov     RBBUF, a0
    call    DspReadback, 0, 0
    cmp     d3, d0
    bne     vf_bad
    mov     RBBUF, a0
vf_cmp:
    cmp     0, d2
    beq     vf_good
    movhu   (a0), d0
    movhu   (a2), d1
    cmp     d1, d0
    bne     vf_bad
    add     2, a0
    add     2, a2
    add     -1, d2
    bra     vf_cmp
vf_good:
    clr     d0
    bra     vf_ret
vf_bad:
    mov     1, d0
vf_ret:
    ret     [d2,d3,a2,a3], 0x30

# ReadSlot -> d0 = 0, d1 = the unit-0 CALL slot's low 32 bits, a1 = its high 16; or d0 = 1 (the readback failed).
ReadSlot:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     DSP_SLOT0, d0
    mov     1, d1
    mov     RBBUF, a0
    mov     DMAC_RB_PM, a1
    call    DspReadback, 0, 0
    cmp     1, d0
    bne     rs_bad
    mov     RBBUF, a0
    movhu   (4, a0), d0
    mov     d0, a1
    movhu   (2, a0), d1
    asl     16, d1
    movhu   (a0), d0
    or      d0, d1
    clr     d0
    bra     rs_ret
rs_bad:
    mov     1, d0
rs_ret:
    ret     [d2,d3,a2,a3], 0x30

# PokeSlot(d0 = bits 47-32, d1 = bits 31-0): the unit-0 CALL slot, one PM word, as the firmware pokes it.
PokeSlot:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     sp, a0                  # the three halves at (0x14, sp), least significant first
    add     0x14, a0
    movhu   d1, (a0)
    lsr     16, d1
    movhu   d1, (2, a0)
    movhu   d0, (4, a0)
    mov     DSP_SLOT0, d0
    mov     1, d1
    mov     DMAC_UP_PM, a1
    call    DspUpload, 0, 0
    ret     [d2,d3,a2,a3], 0x30

