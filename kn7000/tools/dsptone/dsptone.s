    mov     L_MSG, d0
    mov     C_BAD, d1
    call    LineBegin, 0, 0
    mov     a2, a1
    call    StrCpy, 0, 0
    mov     L_HELP, d0
    mov     C_DIM, d1
    call    LineBegin, 0, 0
    mov     str_h_fail, a1
    call    StrCpy, 0, 0
    call    Now, 0, 0
