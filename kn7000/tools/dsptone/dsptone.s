# DoInit: the loader's service table; the first lines.
DoInit:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     (SVC+SV_MSCOUNT), d0
    mov     d0, (V_MS)
    mov     1, d0
    mov     d0, (V_REDRAW)
    mov     L_HELP, d0
    mov     C_DIM, d1
    call    LineBegin, 0, 0
    mov     str_h_find, a1
    call    StrCpy, 0, 0
    mov     str_f_loader, a0
    mov     (SVC+SV_MAGIC), d0
    mov     0x53374E4B, d1          # "KN7S"
    cmp     d1, d0
    bne     di_fail
    mov     (SVC+SV_ABI), d0
    cmp     LOADER_ABI, d0
    bne     di_fail
    mov     ST_FIND, d0
    call    SetState, 0, 0
    bra     di_ret
di_fail:
    call    Fail, 0, 0
di_ret:
    ret     [d2,d3,a2,a3], 0x30

# DoFind: the panel's switch bitmaps and the firmware's DSP routines. Each of the four signatures is searched
# for over the whole program flash in a call of its own (about 1 s each on MAME's timing of the unit), then the
# finds are checked against each other.
DoFind:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     (V_FINDSTEP), d2
    cmp     NSIGS, d2
    bcc     dfi_check
    mov     d2, d0                  # the next signature: count its hits, keep the first
    asl     2, d0
    mov     SigTab, a0
    add     d0, a0
    mov     (a0), a0
    call    CountFlash, 0, 0
    mov     d2, d1
    asl     2, d1
    mov     V_SIGN, a0
    add     d1, a0
    mov     d0, (a0)
    mov     V_SIGA, a0
    add     d1, a0
    mov     (V_TMP), d0
    mov     d0, (a0)
    inc     d2
    mov     d2, (V_FINDSTEP)
    bra     dfi_ret
dfi_check:
    call    FindPanel, 0, 0
    call    DspFind, 0, 0
    mov     L_FW, d0                # "Firmware: program build 893; DSP host-port routines found"
    mov     C_TEXT, d1
    call    LineBegin, 0, 0
    mov     str_fw, a1
    call    StrCpy, 0, 0
    mov     (SVC+SV_FOUND), d0
    btst    FOUND_BUILD, d0
    beq     df_nobuild
    mov     (SVC+SV_BUILD), d0
    call    PutDec, 0, 0
    bra     df_routines
df_nobuild:
    mov     str_unknown, a1
    call    StrCpy, 0, 0
df_routines:
    mov     str_fw2, a1
    call    StrCpy, 0, 0
    mov     str_found, a1
    mov     (V_DSPOK), d0
    cmp     0, d0
    bne     df_say
    mov     str_notfound, a1
df_say:
    call    StrCpy, 0, 0
    mov     L_ROUT, d0              # "  read 4840B433  write 4840B3F5  index 4840B19B  data 4840B090/4840B00D"
    mov     C_DIM, d1
    call    LineBegin, 0, 0
    mov     str_rt_rd, a1
    call    StrCpy, 0, 0
    mov     (V_DREGRD), d0
    mov     8, d1
    call    PutHex, 0, 0
    mov     str_rt_wr, a1
    call    StrCpy, 0, 0
    mov     (V_DREGWR), d0
    mov     8, d1
    call    PutHex, 0, 0
    mov     str_rt_dr, a1
    call    StrCpy, 0, 0
    mov     (V_DDATARD), d0
    mov     8, d1
    call    PutHex, 0, 0
    mov     str_rt_dw, a1
    call    StrCpy, 0, 0
    mov     (V_DDATAWR), d0
    mov     8, d1
    call    PutHex, 0, 0
    mov     str_f_nodsp, a0
    mov     (V_DSPOK), d0
    cmp     0, d0
    beq     dfi_fail
    mov     str_f_nopanel, a0
    mov     (V_PANEL), d0
    cmp     0, d0
    beq     dfi_fail
    mov     ST_CHECK, d0
    call    SetState, 0, 0
    bra     dfi_ret
dfi_fail:
    call    Fail, 0, 0
dfi_ret:
    ret     [d2,d3,a2,a3], 0x30

# DoCheck: the DSP as the firmware leaves it? The flags, SYSCON, channel 8 (as pass 7 checked them), and the
# unit-0 CALL slot, read back and taken apart.
DoCheck:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     str_f_dead, a0
    call    DeadFlag, 0, 0
    cmp     0, d0
    bne     dc_fail
    mov     str_f_notdown, a0
    call    DownFlag, 0, 0
    cmp     0, d0
    beq     dc_fail
    mov     IOP_SYSCON, d0
    call    DspRead, 0, 0
    mov     d0, (V_SYSCON)
    mov     IOP_DMAC0, d0
    call    DspRead, 0, 0
    mov     d0, (V_DMAC0)
    mov     IOP_IIEP0, d0
    call    DspRead, 0, 0
    mov     d0, (V_IIEP0)
    mov     IOP_IMEP0, d0
    call    DspRead, 0, 0
    mov     d0, (V_IMEP0)
    mov     IOP_CEP0, d0
    call    DspRead, 0, 0
    mov     d0, (V_CEP0)
    mov     IOP_DMASTAT, d0
    call    DspRead, 0, 0
    mov     d0, (V_DMASTAT)
    mov     L_REGS, d0              # "DSP: SYSCON 00000410  DMAC0 000000A0  DMASTAT 0000033F"
    mov     C_TEXT, d1
    call    LineBegin, 0, 0
    mov     str_regs1, a1
    call    StrCpy, 0, 0
    mov     (V_SYSCON), d0
    mov     8, d1
    call    PutHex, 0, 0
    mov     str_regs2, a1
    call    StrCpy, 0, 0
    mov     (V_DMAC0), d0
    mov     8, d1
    call    PutHex, 0, 0
    mov     str_regs3, a1
    call    StrCpy, 0, 0
    mov     (V_DMASTAT), d0
    mov     8, d1
    call    PutHex, 0, 0
    mov     str_f_precheck, a0
    mov     (V_SYSCON), d0          # SYSCON: HBW = 01 (16-bit host bus), HMSWF = 0 (low half first)
    and     0x70, d0
    cmp     0x10, d0
    bne     dc_fail
    mov     (V_DMAC0), d0           # DMAC0: DEN, CHEN clear
    and     3, d0
    bne     dc_fail
    mov     (V_DMASTAT), d0         # DMASTAT: channel 8 neither active (bit 6) nor chaining (bit 16)
    mov     0x10040, d1
    and     d1, d0
    bne     dc_fail
    call    ReadSlot, 0, 0          # d0 = 0, d1 = its low 32 bits, a1 = its high 16 (or d0 = 1)
    mov     str_f_rb, a0
    cmp     0, d0
    bne     dc_fail
    mov     a1, (V_SLOT_HI)
    mov     d1, (V_SLOT_LO)
    mov     L_SLOT, d0              # "Unit 0 slot PM 8080: 06BE04008400 = CALL 8400 (DB), saved"
    mov     C_TEXT, d1
    call    LineBegin, 0, 0
    mov     str_slot, a1
    call    StrCpy, 0, 0
    mov     (V_SLOT_HI), d0
    mov     (V_SLOT_LO), d1
    call    Put48, 0, 0
    mov     a0, a2                  # the line's end, for what is said about the slot
    mov     str_slot_bad, a3
    mov     (V_SLOT_HI), d0         # the kernel's form: "CALL (0x8xxx) (DB)", target inside its code area
    cmp     DSP_CALLDB_HI, d0
    bne     dc_slotbad
    mov     (V_SLOT_LO), d0
    mov     0xFFFF0000, d1
    and     d1, d0
    mov     0x04000000, d1
    cmp     d1, d0
    bne     dc_slotbad
    mov     (V_SLOT_LO), d0
    exthu   d0
    cmp     0x8000, d0
    bcs     dc_slotbad
    cmp     0x8FFF, d0
    bhi     dc_slotbad
    mov     str_slot_saved, a3
    cmp     DSP_CODE_ADDR, d0       # ours already (an earlier run that never put it back): the effect
    bne     dc_slotok               #   program of unit 0 always lives at 0x8400
    mov     0x04008400, d0
    mov     d0, (V_SLOT_LO)
    mov     str_slot_ours, a3
dc_slotok:
    mov     a2, a0
    mov     a3, a1
    call    StrCpy, 0, 0
    mov     ST_LOAD, d0
    call    SetState, 0, 0
    bra     dc_ret
dc_slotbad:
    mov     a2, a0
    mov     a3, a1
    call    StrCpy, 0, 0
    mov     str_f_slot, a0
dc_fail:
    call    Fail, 0, 0
dc_ret:
    ret     [d2,d3,a2,a3], 0x30

# DoLoad: our program, its sine table and its variables, as the firmware uploads an effect; the four message
# registers it reads; then everything read back and compared.
DoLoad:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     DSP_CODE_ADDR, d0
    mov     DSP_CODE_WORDS, d1
    mov     DspCode, a0
    mov     DMAC_UP_PM, a1
    call    DspUpload, 0, 0
    mov     DSP_TABLE, d0
    mov     256, d1
    mov     DspTable, a0
    mov     DMAC_UP_DM, a1
    call    DspUpload, 0, 0
    mov     DSP_VARS, d0
    mov     DSP_NVARS, d1
    mov     DspVars, a0
    mov     DMAC_UP_DM, a1
    call    DspUpload, 0, 0
    mov     DSP_MSGR4, d0
    clr     d1
    call    DspWrite, 0, 0
    mov     DSP_MSGR5, d0
    clr     d1
    call    DspWrite, 0, 0
    mov     DSP_MSGR7, d0
    clr     d1
    call    DspWrite, 0, 0
    mov     MODE_SINE, d0
    call    SetMode, 0, 0
    mov     str_f_dead, a0
    call    DeadFlag, 0, 0
    cmp     0, d0
    bne     dl_fail
    mov     str_f_verify, a0        # read back: the program (PM), the table and the variables (DM)
    mov     DSP_CODE_ADDR, d0
    mov     DSP_CODE_WORDS, d1
    mov     DMAC_RB_PM, a1
    mov     DspCode, a2
    call    Verify, 0, 0
    cmp     0, d0
    bne     dl_fail
    mov     DSP_TABLE, d0
    mov     256, d1
    mov     DMAC_RB_DM, a1
    mov     DspTable, a2
    call    Verify, 0, 0
    cmp     0, d0
    bne     dl_fail
    mov     DSP_VARS, d0
    mov     DSP_NVARS, d1
    mov     DMAC_RB_DM, a1
    mov     DspVars, a2
    call    Verify, 0, 0
    cmp     0, d0
    bne     dl_fail
    mov     L_LOAD, d0              # "Loaded: 88 words at PM 8200, table and variables at DM 9D00: read back, equal"
    mov     C_OK, d1
    call    LineBegin, 0, 0
    mov     str_load1, a1
    call    StrCpy, 0, 0
    mov     DSP_CODE_WORDS, d0
    call    PutDec, 0, 0
    mov     str_load2, a1
    call    StrCpy, 0, 0
    mov     ST_HOOK, d0
    call    SetState, 0, 0
    bra     dl_ret
dl_fail:
    call    Fail, 0, 0
dl_ret:
    ret     [d2,d3,a2,a3], 0x30

# DoHook: the unit-0 slot -> "CALL (DSP_CODE_ADDR) (DB)", then read back.
DoHook:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     1, d0                   # from here on, every way out puts the slot back
    mov     d0, (V_HOOKED)
    mov     DSP_CALLDB_HI, d0
    mov     0x04000000|DSP_CODE_ADDR, d1
    call    PokeSlot, 0, 0
    call    ReadSlot, 0, 0
    mov     str_f_rb, a0
    cmp     0, d0
    bne     dh_fail
    mov     str_f_hook, a0
    cmp     DSP_CALLDB_HI, a1
    bne     dh_fail
    mov     0x04000000|DSP_CODE_ADDR, d0
    cmp     d0, d1
    bne     dh_fail
    mov     L_HOOK, d0              # "Hooked: PM 8080 = 06BE04008200 = CALL 8200 (DB), read back"
    mov     C_OK, d1
    call    LineBegin, 0, 0
    mov     str_hook, a1
    call    StrCpy, 0, 0
    mov     DSP_CALLDB_HI, d0
    mov     0x04000000|DSP_CODE_ADDR, d1
    call    Put48, 0, 0
    mov     str_hook2, a1
    call    StrCpy, 0, 0
    mov     DSP_MSGR7, d0           # the heartbeat's first window
    call    DspRead, 0, 0
    mov     d0, (V_HB0)
    mov     d0, (V_HB)
    mov     (V_T0), d0
    mov     d0, (V_HB0MS)
    mov     L_HELP, d0
    mov     C_DIM, d1
    call    LineBegin, 0, 0
    mov     str_h_run, a1
    call    StrCpy, 0, 0
    mov     ST_RUN, d0
    call    SetState, 0, 0
    bra     dh_ret
dh_fail:
    call    Fail, 0, 0
dh_ret:
    ret     [d2,d3,a2,a3], 0x30

# DoRun: the heartbeat; the buttons.
DoRun:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    call    Heartbeat, 0, 0
    cmp     0, d0
    bne     dr_ret                  # failed (the dead flag): Heartbeat called Fail
    call    StopAsked, 0, 0
    cmp     0, d0
    bne     dr_stop
    mov     (V_PRESSED), d2
    btst    1<<B_R1, d2
    beq     dr_r2
    mov     MODE_SINE, d0
    call    SetMode, 0, 0
dr_r2:
    btst    1<<B_R2, d2
    beq     dr_r3
    mov     (V_PCMOK), d0
    cmp     0, d0
    beq     dr_upload
    mov     MODE_PCM, d0
    call    SetMode, 0, 0
    bra     dr_r3
dr_upload:
    clr     d0
    mov     d0, (V_PCMDONE)
    mov     d0, (V_STALL)
    mov     ST_UPLOAD, d0
    call    SetState, 0, 0
    bra     dr_ret
dr_r3:
    btst    1<<B_R3, d2
    beq     dr_ret
    mov     MODE_SILENT, d0
    call    SetMode, 0, 0
    bra     dr_ret
dr_stop:
    mov     ST_UNHOOK, d0
    call    SetState, 0, 0
dr_ret:
    ret     [d2,d3,a2,a3], 0x30

# DoUpload: the PCM (DspPcm, 16-bit samples) into SDRAM. Per chunk: wait until the DSP has finished the last
# copy (MSGR4 = 0), stream up to 256 words (512 samples) into STAGE, then MSGR5 = where, MSGR4 = how many; our
# program unpacks two words a frame. UPLOAD_MS of this per call. At the end PCMLEN is read back; then the PCM plays.
DoUpload:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    call    Heartbeat, 0, 0
    cmp     0, d0
    bne     du_ret
    call    StopAsked, 0, 0
    cmp     0, d0
    bne     du_stop
du_chunk:
    call    CopyIdle, 0, 0          # d0 = 1 when the DSP has no copy pending
    cmp     0, d0
    beq     du_waiting
    clr     d0
    mov     d0, (V_STALL)
    mov     (V_PCMDONE), d2
    mov     DSP_PCM_SAMPLES, d0
    cmp     d0, d2
    bcc     du_finish
    sub     d2, d0                  # samples left -> words, at most a STAGE's
    lsr     1, d0
    mov     DSP_STAGE_WORDS, d1
    cmp     d1, d0
    bls     du_n
    mov     d1, d0
du_n:
    mov     d0, d3                  # words in this chunk
    mov     d3, d1
    mov     d2, d0                  # the samples' address: DspPcm + 2 x done
    add     d0, d0
    mov     DspPcm, a0
    add     d0, a0
    mov     DSP_STAGE, d0
    mov     DMAC_UP_DM, a1
    call    DspUpload, 0, 0
    mov     DSP_MSGR5, d0
    mov     d2, d1
    call    DspWrite, 0, 0
    mov     DSP_MSGR4, d0
    mov     d3, d1
    call    DspWrite, 0, 0
    add     d3, d2
    add     d3, d2
    mov     d2, (V_PCMDONE)
    call    PcmLine, 0, 0
    call    DeadFlag, 0, 0
    cmp     0, d0
    bne     du_dead
    call    Now, 0, 0
    mov     (V_T0), d1
    sub     d1, d0
    cmp     UPLOAD_MS, d0
    bcs     du_chunk
    bra     du_ret
du_waiting:
    mov     (V_STALL), d0           # no copy finished in COPY_POLLS reads: try again at the next call
    inc     d0
    mov     d0, (V_STALL)
    cmp     STALL_CALLS, d0
    bcs     du_ret
    mov     str_f_stall, a0
    call    Fail, 0, 0
    bra     du_ret
du_finish:
    mov     DSP_V_LEN, d0           # PCMLEN, read back: every sample copied?
    mov     1, d1
    mov     DMAC_RB_DM, a1
    mov     RBBUF, a0
    call    DspReadback, 0, 0
    cmp     1, d0
    bne     du_badlen
    mov     RBBUF, a0
    movhu   (2, a0), d0
    asl     16, d0
    movhu   (a0), d1
    or      d1, d0
    mov     d0, (V_PCMLEN)
    mov     DSP_PCM_SAMPLES, d1
    cmp     d1, d0
    bne     du_badlen
    mov     1, d0
    mov     d0, (V_PCMOK)
    call    PcmLine, 0, 0
    mov     MODE_PCM, d0
    call    SetMode, 0, 0
    mov     ST_RUN, d0
    call    SetState, 0, 0
    bra     du_ret
du_badlen:
