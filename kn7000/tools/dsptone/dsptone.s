# DrawChar(d0 = character, d1 = x (even), a1 = y): the 8x13 cell in V_FG on V_BG, two pixels a 32-bit store (at
# scale 2 each pixel is doubled: one store a font pixel, each row twice). (loader.s DrawChar, by pairs)
DrawChar:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    cmp     0x20, d0
    bcs     dc_other
    cmp     0x7F, d0
    bcs     dc_ok
dc_other:
    mov     0x3F, d0                # '?'
dc_ok:
    add     -0x20, d0
    mov     13, d2
    mulu    d2, d0
    mov     Font8x13, a3
    add     d0, a3
    mov     a1, d2
    mov     FB_STRIDE, d3
    mulu    d3, d2
    add     d1, d1
    add     d1, d2
    mov     FB, a2
    add     d2, a2
    mov     13, d0
    mov     d0, (0x14, sp)
dch_row:
    movbu   (a3), d2                # the row's 8 bits, the leftmost in bit 7
    inc     a3
    mov     (V_SCALE), d0
    mov     d0, (0x18, sp)
dch_rep:
    mov     a2, a0
    mov     (V_SCALE), d0
    cmp     2, d0
    beq     dch_x2
    mov     0x80, d3                # scale 1: two font pixels a store; d3 = the left one's bit
dch_pair:
    mov     (V_BG), d1
    mov     d2, d0
    and     d3, d0
    beq     dch_l
    mov     (V_FG), d1
dch_l:
    exthu   d1                      # the left pixel: the low half (little-endian)
    mov     d1, (0x1C, sp)
    lsr     1, d3                   # the right one's bit
    mov     (V_BG), d1
    mov     d2, d0
    and     d3, d0
    beq     dch_r
    mov     (V_FG), d1
dch_r:
    asl     16, d1
    mov     (0x1C, sp), d0
    or      d0, d1
    mov     d1, (a0)
    add     4, a0
    lsr     1, d3
    bne     dch_pair
    bra     dch_next
dch_x2:
    mov     0x80, d3                # scale 2: one font pixel a store, two LCD pixels
dch_px2:
    mov     (V_BG), d1
    mov     d2, d0
    and     d3, d0
    beq     dch_p2
    mov     (V_FG), d1
dch_p2:
    exthu   d1
    mov     d1, d0
    asl     16, d0
    or      d0, d1
    mov     d1, (a0)
    add     4, a0
    lsr     1, d3
    bne     dch_px2
dch_next:
    add     FB_STRIDE, a2
    mov     (0x18, sp), d0
    add     -1, d0
    mov     d0, (0x18, sp)
    bne     dch_rep
    mov     (0x14, sp), d0
    add     -1, d0
    mov     d0, (0x14, sp)
    bne     dch_row
    ret     [d2,d3,a2,a3], 0x30

