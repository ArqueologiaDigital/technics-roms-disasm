    mov     a2, a3
    mov     a0, d2
fr_px32:
    mov     d3, (a3)
    add     4, a3
    add     -1, d2
    bne     fr_px32
    add     FB_STRIDE, a2
    add     -1, a1
    cmp     0, a1
    bne     fr_row32
    bra     fr_ret
