# The buttons (the firmware's debounced switch bitmaps, as the program menu reads them).

# Buttons: V_BTN = the buttons down now, V_PRESSED = those that went down since the last call.
Buttons:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    call    ReadButtons, 0, 0
    mov     (V_BTN), d1
    mov     d0, (V_BTN)
    not     d1
    and     d1, d0
    mov     d0, (V_PRESSED)
    ret     [d2,d3,a2,a3], 0x30

# StopAsked -> d0 = 1 when STOP went down, or EXIT has been held QUIT_MS (then let go or not: stopping the sound
# should not wait), else 0.
StopAsked:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     (V_PRESSED), d0
    btst    1<<B_R5, d0
    bne     sa_yes
    call    ExitHeld, 0, 0
    mov     (V_EXITARMED), d0
    cmp     0, d0
    bne     sa_yes
    clr     d0
    bra     sa_ret
sa_yes:
    mov     1, d0
sa_ret:
    ret     [d2,d3,a2,a3], 0x30

# LeaveAsked -> d0 = 1 once LEAVE has gone down and is up again, or EXIT, held QUIT_MS, is let go. Ending on the
# release keeps the press from reaching the firmware's message, which comes up as soon as we answer 0xFE.
LeaveAsked:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     (V_PRESSED), d0
    btst    1<<B_R4, d0
    beq     la_held
    mov     1, d0
    mov     d0, (V_LEAVEREQ)
la_held:
    mov     (V_LEAVEREQ), d0
    cmp     0, d0
    beq     la_exit
    mov     (V_BTN), d0
    btst    1<<B_R4, d0
    beq     la_yes
la_exit:
    call    ExitHeld, 0, 0          # d0 = 1: EXIT held and let go
    cmp     0, d0
    bne     la_yes
    clr     d0
    bra     la_ret
la_yes:
    mov     1, d0
la_ret:
    ret     [d2,d3,a2,a3], 0x30

# ExitHeld -> d0 = 1 once EXIT, after being down for QUIT_MS (V_EXITARMED), has been let go, else 0.
ExitHeld:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     (V_BTN), d0
    btst    1<<B_EXIT, d0
    bne     eh_down
    clr     d0
    mov     d0, (V_EXIT_T0)
    mov     (V_EXITARMED), d0
    bra     eh_ret
eh_down:
    mov     (V_T0), d0
    mov     (V_EXIT_T0), d1
    cmp     0, d1
    bne     eh_held
    or      1, d0
    mov     d0, (V_EXIT_T0)
    bra     eh_no
eh_held:
    sub     d1, d0
    mov     QUIT_MS, d1
    cmp     d1, d0
    bcs     eh_no
    mov     1, d0
    mov     d0, (V_EXITARMED)
eh_no:
    clr     d0
eh_ret:
    ret     [d2,d3,a2,a3], 0x30

# ReadButtons -> d0 = the B_* bits of the buttons down now (0 without the bitmaps).
ReadButtons:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    clr     d2
    mov     (V_PANEL), a2
    cmp     0, a2
    beq     rb_ret
    mov     ButtonTab, a3
    clr     d3                      # bit number
rb_one:
    movbu   (a3), d0                # offset
    mov     a2, a0
    add     d0, a0
    movbu   (a0), d0
    movbu   (1, a3), d1             # mask
    and     d1, d0
    beq     rb_up
    mov     1, d0
    asl     d3, d0
    or      d0, d2
rb_up:
    add     2, a3
    inc     d3
    cmp     NBUTTONS, d3
    bcs     rb_one
rb_ret:
    mov     d2, d0
    ret     [d2,d3,a2,a3], 0x30

# FindPanel: V_PANEL = CPR from the panel decoder's two sites (one hit each, the same CPR in both, CPL = CPR +
# 0x30 in both, CPR in work RAM), as ../kn7menu/menu.s FindPanel; else 0.
FindPanel:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    clr     d0
    mov     d0, (V_PANEL)
    mov     0, d0                   # sig_panel1, scanned by DoFind
    call    CountCached, 0, 0
    cmp     1, d0
    bne     fp_ret
    mov     (V_TMP), a2
    mov     1, d0                   # sig_panel2, scanned by DoFind
    call    CountCached, 0, 0
    cmp     1, d0
    bne     fp_ret
    mov     (V_TMP), a3
    mov     a2, a0                  # CPR, from both sites
    add     2, a0
    call    Read32U, 0, 0
    mov     d0, d2
    mov     a3, a0
    add     2, a0
    call    Read32U, 0, 0
    cmp     d2, d0
    bne     fp_ret
    mov     a2, a0                  # CPL, from both
    add     15, a0
    call    Read32U, 0, 0
    mov     d0, d3
    mov     a3, a0
    add     13, a0
    call    Read32U, 0, 0
    cmp     d3, d0
    bne     fp_ret
    mov     d2, d0
    add     0x30, d0
    cmp     d3, d0
    bne     fp_ret
    mov     0x50000000, d0          # in work RAM
    cmp     d0, d2
    bcs     fp_ret
    mov     0x503FFF00, d0
    cmp     d0, d2
    bhi     fp_ret
    mov     d2, (V_PANEL)
fp_ret:
    ret     [d2,d3,a2,a3], 0x30

# CountCached(d0 = signature number, SigTab) -> d0 = its hits as DoFind counted them; V_TMP = the first. Leaf.
CountCached:
    asl     2, d0
    mov     V_SIGA, a0
    add     d0, a0
    mov     (a0), d1
    mov     d1, (V_TMP)
    mov     V_SIGN, a0
    add     d0, a0
    mov     (a0), d0
    rets

# CountFlash(a0 = signature) -> d0 = its hits in the program flash; V_TMP = the first.
CountFlash:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     a0, a2
    clr     d2
    mov     d2, (V_TMP)
    mov     0x48400000, a3
cf_next:
    mov     a2, a0
    mov     a3, d0
    mov     0x487FFF00, d1
    call    FindSig, 0, 0
    cmp     0, d0
    beq     cf_done
    cmp     0, d2
    bne     cf_more
    mov     d0, (V_TMP)
cf_more:
    inc     d2
    mov     d0, a3
    inc     a3
    bra     cf_next
cf_done:
    mov     d2, d0
    ret     [d2,d3,a2,a3], 0x30

# FindSig(a0 = signature, d0 = start, d1 = end) -> d0 = the first address in [start, end) where it matches, or
# 0. Elements are 16-bit: 0x00nn = byte nn, 0x0100 = any byte, 0xFFFF = end; the first is a byte (loader.s). The
# scan for the first byte keeps everything in registers (five instructions a byte); the rest is compared only there.
FindSig:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     a0, a2
    movhu   (a2), d3
    mov     d0, a3
    mov     d1, a1
    .align  4, 0xCB                 # nops: the loop starts on a fetch word (the scan's speed depends on it)
fs_scan:
    cmp     a1, a3
    bcc     fs_none
    movbu   (a3), d2
    inc     a3
    cmp     d3, d2
    bne     fs_scan
    mov     a1, (0x14, sp)          # a first byte at a3 - 1: the rest
    mov     a2, a0
    add     2, a0
    mov     a3, a1
fs_cmp:
    movhu   (a0), d2
    mov     0xFFFF, d0
    cmp     d0, d2
    beq     fs_hit
    btst    0x100, d2
    bne     fs_any
    movbu   (a1), d1
    cmp     d2, d1
    bne     fs_miss
fs_any:
    add     2, a0
    inc     a1
    bra     fs_cmp
fs_miss:
    mov     (0x14, sp), a1
    bra     fs_scan
fs_hit:
    mov     a3, d0
    add     -1, d0
    bra     fs_ret
fs_none:
    clr     d0
fs_ret:
    ret     [d2,d3,a2,a3], 0x30

Read32U:                            # leaf: a0 = address -> d0 = little-endian u32, any alignment
    movbu   (3, a0), d0
    asl     8, d0
    movbu   (2, a0), d1
    or      d1, d0
    asl     8, d0
    movbu   (1, a0), d1
    or      d1, d0
    asl     8, d0
    movbu   (a0), d1
    or      d1, d0
    rets

# Now -> d0 = the kernel's milliseconds, or 50 per converter call without the counter. Leaf.
Now:
    mov     (V_MS), a0
    cmp     0, a0
    beq     nw_calls
    mov     (a0), d0
    rets
nw_calls:
    mov     (V_CALLS), d0
    mov     50, d1
    mulu    d1, d0
    rets

