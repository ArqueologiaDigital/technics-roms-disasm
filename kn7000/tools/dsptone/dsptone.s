# DoUnhook: silence; the slot back as found, read back; the message registers to 0 (as the kernel leaves them);
# channel 8's registers as found.
DoUnhook:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    call    Unhook, 0, 0
    mov     L_HELP, d0
    mov     C_DIM, d1
    call    LineBegin, 0, 0
    mov     str_h_done, a1
    call    StrCpy, 0, 0
