.equ L_SLOT,        3
.equ L_LOAD,        4
.equ L_HOOK,        5
.equ L_HB,          6
.equ L_PLAY,        7
.equ L_PCM,         8
.equ L_REST,        9
.equ L_MSG,         10
.equ L_HELP,        11

# ---- application header (mkapp.py fills in the size and the CRC-32) ------------------------------
AppHeader:
    .long   0x41374E4B              # "KN7A"
    .long   LOADER_ABI
    .long   0                       # AH_SIZE
    .long   ToneEntry
    .long   0                       # AH_CRC
    .long   APP_BASE
    .long   0, 0
    .ascii  "KN7000 DSP TONE 1.0"
    .space  AppHeader + 0x40 - .

# ================================================================================================
ToneEntry:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     (V_CALLS), d0
    inc     d0
    mov     d0, (V_CALLS)
    call    Now, 0, 0
    mov     d0, (V_T0)
    call    Buttons, 0, 0
    mov     (V_STATE), d0
    cmp     ST_INIT, d0
    beq     te_init
    cmp     ST_FIND, d0
    beq     te_find
    cmp     ST_CHECK, d0
    beq     te_check
    cmp     ST_LOAD, d0
    beq     te_load
    cmp     ST_HOOK, d0
    beq     te_hook
    cmp     ST_RUN, d0
    beq     te_run
    cmp     ST_UPLOAD, d0
    beq     te_upload
    cmp     ST_UNHOOK, d0
    beq     te_unhook
    cmp     ST_DONE, d0
    beq     te_done
    cmp     ST_FAIL, d0
    beq     te_fail
    bra     te_answer               # ST_END: 0xFE again
te_init:
    call    DoInit, 0, 0
    bra     te_refresh
te_find:
    call    DoFind, 0, 0
    bra     te_refresh
te_check:
    call    DoCheck, 0, 0
    bra     te_refresh
te_load:
    call    DoLoad, 0, 0
    bra     te_refresh
te_hook:
    call    DoHook, 0, 0
    bra     te_refresh
te_run:
    call    DoRun, 0, 0
    bra     te_refresh
te_upload:
    call    DoUpload, 0, 0
    bra     te_refresh
te_unhook:
    call    DoUnhook, 0, 0
    bra     te_refresh
te_done:
    call    DoDone, 0, 0
    bra     te_refresh
te_fail:
    call    DoFail, 0, 0
te_refresh:
    call    Refresh, 0, 0
te_answer:
    mov     MAILBOX, a0
    mov     (V_STATE), d0
    cmp     ST_END, d0
    bne     te_show
    mov     RQ_END, d0              # leave: the firmware's message, then "Continue Next?"
    movbu   d0, (a0)
    bra     te_ret
te_show:
    mov     RQ_SHOW, d0             # request 5: show this text, call again
    movbu   d0, (a0)
    mov     str_request, a1
    mov     40, d1
te_cpy:
    inc     a0
    movbu   (a1), d0
    movbu   d0, (a0)
    inc     a1
    cmp     0, d0
    beq     te_ret
    add     -1, d1
    bne     te_cpy
te_ret:
    ret     [d2,d3,a2,a3], 0x30

# SetState(d0 = state): and draw the whole screen (the button labels follow the state). Leaf.
SetState:
    mov     d0, (V_STATE)
    mov     1, d0
    mov     d0, (V_REDRAW)
    rets

