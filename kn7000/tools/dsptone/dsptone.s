    call    SetState, 0, 0
    ret     [d2,d3,a2,a3], 0x30

# Unhook: the work of DoUnhook (also run by DoFail when a failure came while hooked).
Unhook:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     2, d0                   # until it is read back right
    mov     d0, (V_RESTORED)
    mov     str_rest_dead, a2
    call    DeadFlag, 0, 0
    cmp     0, d0
    bne     uh_bad
    mov     MODE_SILENT, d0
    call    SetMode, 0, 0
    mov     (V_SLOT_HI), d0
    mov     (V_SLOT_LO), d1
    call    PokeSlot, 0, 0
    call    ReadSlot, 0, 0          # d0 = 0, d1 = low 32 bits, a1 = high 16
    mov     d1, d3
    mov     a1, d2
    mov     str_rest_rb, a2
    cmp     0, d0
    bne     uh_bad
    mov     str_rest_bad, a2
    mov     (V_SLOT_HI), d0
    cmp     d0, d2
    bne     uh_bad
    mov     (V_SLOT_LO), d0
    cmp     d0, d3
    bne     uh_bad
    clr     d0
    mov     d0, (V_HOOKED)
    mov     1, d0
    mov     d0, (V_RESTORED)
    mov     DSP_MSGR4, d0           # the message registers as the kernel leaves them
    clr     d1
    call    DspWrite, 0, 0
    mov     DSP_MSGR5, d0
    clr     d1
    call    DspWrite, 0, 0
    mov     DSP_MSGR6, d0
    clr     d1
    call    DspWrite, 0, 0
    mov     DSP_MSGR7, d0
    clr     d1
    call    DspWrite, 0, 0
    mov     IOP_IIEP0, d0           # channel 8's registers as found
    mov     (V_IIEP0), d1
    call    DspWrite, 0, 0
    mov     IOP_IMEP0, d0
    mov     (V_IMEP0), d1
    call    DspWrite, 0, 0
    mov     IOP_CEP0, d0
    mov     (V_CEP0), d1
    call    DspWrite, 0, 0
    mov     IOP_DMAC0, d0
    mov     (V_DMAC0), d1
    mov     DMAC_KEEP, d2
    and     d2, d1
    call    DspWrite, 0, 0
    mov     L_REST, d0              # "Restored: PM 8080 = 06BE04008400 = CALL 8400 (DB), read back"
    mov     C_OK, d1
    call    LineBegin, 0, 0
    mov     str_rest, a1
    call    StrCpy, 0, 0
    mov     (V_SLOT_HI), d0
    mov     (V_SLOT_LO), d1
    call    Put48, 0, 0
    mov     str_rest2, a1
    call    StrCpy, 0, 0
    bra     uh_play
uh_bad:
    mov     L_REST, d0
    mov     C_BAD, d1
    call    LineBegin, 0, 0
    mov     a2, a1
    call    StrCpy, 0, 0
uh_play:
    mov     L_PLAY, d0
    mov     C_DIM, d1
    call    LineBegin, 0, 0
    mov     str_play_off, a1
    mov     (V_RESTORED), d0
    cmp     1, d0
    beq     uh_say
    mov     str_play_unknown, a1
uh_say:
    call    StrCpy, 0, 0
    ret     [d2,d3,a2,a3], 0x30

# DoDone: the result stays; LEAVE (let go), or EXIT held and let go, ends the conversion.
DoDone:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    call    LeaveAsked, 0, 0
    cmp     0, d0
    beq     dd_ret
    mov     ST_END, d0
    call    SetState, 0, 0
dd_ret:
    ret     [d2,d3,a2,a3], 0x30

# DoFail: put the slot back if it is ours; then as DoDone, or HOLD_MS without the panel.
DoFail:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     (V_HOOKED), d0
    cmp     0, d0
    beq     dfl_wait
    clr     d0                      # once
    mov     d0, (V_HOOKED)
    call    Unhook, 0, 0
dfl_wait:
    mov     (V_PANEL), d0
    cmp     0, d0
    beq     dfl_time
    call    LeaveAsked, 0, 0
    cmp     0, d0
    bne     dfl_end
    bra     dfl_ret
dfl_time:
    call    Now, 0, 0
    mov     (V_FAILT0), d1
    sub     d1, d0
    mov     HOLD_MS, d1
    cmp     d1, d0
    bcs     dfl_ret
dfl_end:
    mov     ST_END, d0
    call    SetState, 0, 0
dfl_ret:
    ret     [d2,d3,a2,a3], 0x30

# Fail(a0 = the reason): the reason in red, the failure screen.
Fail:
