# CopyIdle -> d0 = 1 when MSGR4 reads 0 (the DSP has finished the last copy) within COPY_POLLS reads, else 0.
CopyIdle:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    clr     d2
ci_poll:
    mov     DSP_MSGR4, d0
    call    DspRead, 0, 0
    cmp     0, d0
    beq     ci_yes
    inc     d2
    cmp     COPY_POLLS, d2
