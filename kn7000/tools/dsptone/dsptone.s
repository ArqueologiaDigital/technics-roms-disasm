# Text: the screen's lines. LineBegin(d0 = line, d1 = colour) -> a0 = its buffer, emptied, marked to be drawn;
# StrCpy, PutHex, PutDec append at a0 and return a0 at the NUL (leaves; ../cnv_romdump/romdump.s).
LineBegin:
    mov     d0, a1
    asl     2, d0
    mov     V_LINECOL, a0
    add     d0, a0
    mov     d1, (a0)
    mov     a1, d0
    mov     1, d1
    asl     d0, d1
    mov     (V_DIRTY), d0
    or      d1, d0
    mov     d0, (V_DIRTY)
    mov     a1, d0
    mov     LINE_LEN, d1
    mulu    d1, d0
    mov     LINES, a0
    add     d0, a0
    clr     d0
    movbu   d0, (a0)
    rets

StrCpy:                             # a1 = source
    movbu   (a1), d0
    movbu   d0, (a0)
    cmp     0, d0
    beq     sc_end
    inc     a0
    inc     a1
    bra     StrCpy
sc_end:
    rets

PutHex:                             # d0 = value, d1 = digits (1..8; the low digits of the value)
    mov     d1, a1                  # left-align: shift by (8 - digits) * 4
    mov     8, d1
    sub     a1, d1
    asl     2, d1
    asl     d1, d0
    mov     a1, d1
    mov     d0, a1
ph_dig:
    mov     a1, d0
    lsr     28, d0
    cmp     10, d0
    bcs     ph_num
    add     7, d0
ph_num:
    add     0x30, d0
    movbu   d0, (a0)
    inc     a0
    mov     a1, d0
    asl     4, d0
    mov     d0, a1
    add     -1, d1
    bne     ph_dig
    clr     d0
    movbu   d0, (a0)
    rets

PutDec:                             # d0 = value, no leading zeros
    mov     DECBUF+0x1F, a1
    clr     d1
    movbu   d1, (a1)
pdc_dig:
    clr     d1
    mov     d1, mdr
    mov     10, d1
    divu    d1, d0
    mov     mdr, d1
    add     0x30, d1
    add     -1, a1
    movbu   d1, (a1)
    cmp     0, d0
    bne     pdc_dig
pdc_copy:
    movbu   (a1), d0
    movbu   d0, (a0)
    cmp     0, d0
    beq     pdc_end
    inc     a0
    inc     a1
    bra     pdc_copy
pdc_end:
    rets

# Put48(d0 = bits 47-32, d1 = bits 31-0): a 48-bit SHARC instruction word in 12 hex digits, and what it is
# when it is "CALL (target) (DB)": " = CALL 8400 (DB)".
Put48:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     d0, d2
    mov     d1, d3
    mov     4, d1
    call    PutHex, 0, 0
    mov     d3, d0
    mov     8, d1
    call    PutHex, 0, 0
    cmp     DSP_CALLDB_HI, d2
    bne     p48_ret
    mov     d3, d0
    mov     0xFFFF0000, d1
    and     d1, d0
    mov     0x04000000, d1
    cmp     d1, d0
    bne     p48_ret
    mov     str_call, a1
    call    StrCpy, 0, 0
    mov     d3, d0
    mov     4, d1
    call    PutHex, 0, 0
    mov     str_db, a1
    call    StrCpy, 0, 0
p48_ret:
    ret     [d2,d3,a2,a3], 0x30

