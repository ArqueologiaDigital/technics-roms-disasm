# dsptone.s -- DSPTONE: our own program on the KN7000's effects DSP (IC306, ADSP-21065L), iteration 1.
# An application of KN7LOAD.CNV (../cnv_romdump/loader.s), started from the program menu (folder DSPTONE\).
# README.md says what it does on the instrument and why it is built this way; in short:
#
#   1. It finds the firmware's own DSP host-port routines (the register read/write, the index write, the data
#      port read/write: ../cnv_romdump/romdump_dsp.s DspFind, plus the guarded data write) and calls them. They
#      keep the firmware's lock, its per-frame handshake wait (INTC group 0x17) and its "DSP dead" guard. It
#      never drives the port itself.
#   2. It checks the DSP is as the firmware leaves it (flags, SYSCON, external-port channel 8) and reads back
#      the kernel's unit-0 CALL slot (PM 0x8080; "CALL (0x8400) (DB)" on the owner's unit, pass 7).
#   3. It uploads our DSP program (dsp_prog.py: 88 words at PM 0x8200), a sine table and its variables
#      (DM 0x9D00-0x9F05) the way the firmware uploads an effect, reads them back and compares.
#   4. It points the unit-0 slot at our program (the firmware's own single-word PM poke) and reads it back.
#      The firmware's kernel keeps running everything else: the SPORT rings, the 44.1 kHz frame loop, the
#      handshake. Our program adds a 440 Hz sine to unit 0's return (the panel REVERB unit).
#   5. The buttons: SINE, CHIRP (uploads a 1 s PCM sweep into SDRAM through a staging buffer, then plays it
#      looped), MUTE, STOP. STOP (or EXIT held) writes the slot back as it was found and reads it back: the
#      firmware's reverb program at 0x8400 was never touched, so its effects run again at once.
#
# Calling convention: d0, d1, a0, a1 scratch; d2, d3, a2, a3 preserved. A routine that calls anything makes a
# frame first (movm + add -0x20, sp): firmware routines store into 4..0x10(sp) of the caller's frame, so a
# routine's own locals live at 0x14..0x1C(sp). guard.py checks this, and the memory map, at every build.

.include "kn7cnv.inc"
