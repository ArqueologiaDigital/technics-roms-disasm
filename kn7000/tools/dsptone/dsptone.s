    clr     d0
    bra     ci_ret
ci_yes:
    mov     1, d0
ci_ret:
    ret     [d2,d3,a2,a3], 0x30

# PcmLine: "PCM: 12288 of 44100 samples in SDRAM 00070000" / "... read back PCMLEN 44100".
