# The screen (640 x 240 RGB565 at FB): a title bar, the lines, the right buttons' labels.
#
# The firmware repaints its own STYLE CONVERT screen (the whole LCD, from its layer buffers: 893 0x48414F92) after a
# converter call that ran long: in MAME, a 200 ms call of 150,000 16-bit LCD stores was followed by a repaint after
# every other call, and our redraw by another (test/run_mame.sh, 2026-10-20). So drawing is kept short: every store
# writes two pixels (32 bits), and a full redraw is spread over RD_STEPS calls (the title and the margins, then
# four lines a call, then the labels). The LCD is sampled on every call (as ../kn7menu/menu_draw.s Refresh); when it
# is no longer what we drew, a full redraw starts again. Between full redraws only the lines that changed are drawn.
.equ RD_STEPS,      5

Refresh:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     (V_STATE), d0
    cmp     ST_END, d0
    beq     rfh_ret
    mov     (V_REDRAW), d0          # a full redraw asked for (a new state): from its first step
    cmp     0, d0
    beq     rfh_check
    clr     d0
    mov     d0, (V_REDRAW)
    mov     1, d0
    mov     d0, (V_RDSTEP)
    bra     rfh_step
rfh_check:
    mov     (V_RDSTEP), d0          # in the middle of one: its next step
    cmp     0, d0
    bne     rfh_step
    call    LcdSum, 0, 0
    mov     (V_LCDSUM), d1
    cmp     d1, d0
    beq     rfh_lines
    mov     (V_NREDRAW), d0         # the firmware painted over us
    inc     d0
    mov     d0, (V_NREDRAW)
    mov     1, d0
    mov     d0, (V_RDSTEP)
rfh_step:
    mov     (V_RDSTEP), d0
    call    DrawStep, 0, 0
    mov     (V_RDSTEP), d0
    inc     d0
    cmp     RD_STEPS+1, d0
    bcs     rfh_more
    clr     d0
rfh_more:
    mov     d0, (V_RDSTEP)
rfh_lines:
    clr     d2                      # the lines that changed (and were not just drawn)
rfh_one:
    mov     (V_DIRTY), d0
    lsr     d2, d0
    btst    1, d0
    beq     rfh_next
    mov     d2, d0
    call    DrawLine, 0, 0
rfh_next:
    inc     d2
    cmp     NLINES, d2
    bcs     rfh_one
    clr     d0
    mov     d0, (V_DIRTY)
    call    LcdSum, 0, 0
    mov     d0, (V_LCDSUM)
rfh_ret:
    ret     [d2,d3,a2,a3], 0x30

# LcdSum -> d0: a checksum of 300 LCD pixels, every 32nd of every 16th row (as menu_draw.s).
LcdSum:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    clr     d2
    clr     d3
    mov     FB+4*FB_STRIDE+16, a2
    mov     15, d0
    mov     d0, (0x14, sp)
ls_row:
    mov     a2, a0
    mov     20, d1
ls_px:
    movhu   (a0), d0
    add     d0, d2
    add     d2, d3
    add     64, a0
    add     -1, d1
    bne     ls_px
    add     16*FB_STRIDE, a2
    mov     (0x14, sp), d0
    add     -1, d0
    mov     d0, (0x14, sp)
    bne     ls_row
    mov     d3, d0
    asl     16, d0
    add     d2, d0
    ret     [d2,d3,a2,a3], 0x30

# DrawStep(d0 = 1..RD_STEPS): one step of a full redraw. 1: the title bar, the margins above and below the lines,
# the labels' column; 2-4: four lines each (with the gaps below them); 5: the labels.
DrawStep:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     d0, d2
    mov     1, d0
    mov     d0, (V_SCALE)
    cmp     1, d2
    bne     ds_lines
    mov     C_TITLE, d0             # the title bar
    call    SetColours, 0, 0
    clr     d0
    clr     d1
    mov     640, a0
    mov     TITLE_H, a1
    call    FillRect, 0, 0
    mov     C_TEXT, d0
    mov     d0, (V_FG)
    mov     2, d0
    mov     d0, (V_SCALE)
    mov     str_title, a0
    mov     8, d0
    mov     1, d1
    call    DrawText, 0, 0
    mov     1, d0
