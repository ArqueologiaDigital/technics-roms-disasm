# SetMode(d0 = MODE_*): MSGR6, and the line that says what plays.
SetMode:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     d0, d2
    mov     d0, (V_MODE)
    mov     d0, d1
    mov     DSP_MSGR6, d0
    call    DspWrite, 0, 0
    mov     L_PLAY, d0
    mov     C_WARN, d1
    call    LineBegin, 0, 0
    mov     str_play_sine, a1
    cmp     MODE_SINE, d2
    beq     sm_say
    mov     str_play_pcm, a1
    cmp     MODE_PCM, d2
    beq     sm_say
    mov     str_play_mute, a1
sm_say:
    call    StrCpy, 0, 0
    ret     [d2,d3,a2,a3], 0x30

# Heartbeat -> d0 = 0, or 1 after a failure: MSGR7 (our program counts its frames there) and its rate over
# RATE_MS windows; the dead flag.
Heartbeat:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    call    DeadFlag, 0, 0
    cmp     0, d0
    beq     hb_alive
    mov     str_f_deadrun, a0
    call    Fail, 0, 0
    mov     1, d0
    bra     hb_ret
hb_alive:
    mov     DSP_MSGR7, d0
    call    DspRead, 0, 0
    mov     d0, (V_HB)
    mov     (V_T0), d2
    mov     d2, (V_HBMS)
    mov     (V_HB0MS), d1
    sub     d1, d2                  # ms in this window
    cmp     RATE_MS, d2
    bcs     hb_say
    mov     (V_HB0), d1
    sub     d1, d0                  # frames in it
    mov     1000, d1
    mulu    d1, d0
    clr     d1
    mov     d1, mdr
    divu    d2, d0
    mov     d0, (V_RATE)
    mov     (V_HB), d0
    mov     d0, (V_HB0)
    mov     (V_HBMS), d0
    mov     d0, (V_HB0MS)
hb_line:
    mov     (V_WINDOWS), d0
    inc     d0
    mov     d0, (V_WINDOWS)
hb_say:
    mov     C_OK, d2                # red when our program has not counted, or stopped counting
    mov     (V_HB), d0
    cmp     0, d0
    bne     hb_c1
    mov     C_BAD, d2
hb_c1:
    mov     (V_WINDOWS), d0
    cmp     0, d0
    beq     hb_c2
    mov     (V_RATE), d0
    cmp     0, d0
    bne     hb_c2
    mov     C_BAD, d2
hb_c2:
    mov     L_HB, d0                # "Heartbeat (MSGR7): 1234567 frames  44087 per second"
    mov     d2, d1
    call    LineBegin, 0, 0
    mov     str_hb1, a1
    call    StrCpy, 0, 0
    mov     (V_HB), d0
    call    PutDec, 0, 0
    mov     str_hb2, a1
    call    StrCpy, 0, 0
    mov     (V_WINDOWS), d0
    cmp     0, d0
    beq     hb_ok
    mov     (V_RATE), d0
    call    PutDec, 0, 0
    mov     str_hb3, a1
    call    StrCpy, 0, 0
hb_ok:
    clr     d0
hb_ret:
    ret     [d2,d3,a2,a3], 0x30

