# FillRect(d0 = x, d1 = y, a0 = width, a1 = height) in V_FG; two pixels per store when x and the width are even
# (as menu_draw.s).
FillRect:
    movm    [d2,d3,a2,a3], (sp)
    add     -0x20, sp
    mov     d0, (0x14, sp)
    mov     d1, d2
    mov     FB_STRIDE, d3
    mulu    d3, d2
    add     d0, d0
    add     d0, d2
    mov     FB, a2
    add     d2, a2
    mov     (V_FG), d3
    cmp     0, a0
    beq     fr_ret
    cmp     0, a1
    beq     fr_ret
    mov     (0x14, sp), d0
    mov     a0, d1
    or      d1, d0
    btst    1, d0
    bne     fr_row16
    mov     d3, d0                  # two pixels a store
    asl     16, d0
    or      d0, d3
    mov     a0, d0
    lsr     1, d0
    mov     d0, a0
