r"""rhythm_drum_kit_keys.py -- what each drum key of the KN7000's kits is called, and which kits the styles play.

QUESTION ANSWERED
-----------------
"Which drum kit does each note on a style's drum parts (0 and 7) play, what does that kit
call the key, and does one key layout (the one tools/gen_ic18_rhythm_s.py spells keys by)
hold across the kits?"

The chain the firmware follows, all in table 84's internal voice archive
(kn7000/src/table/voices/internal_archive.s, generated by tools/gen_table_voices.py):
  * a part's sound is {program, bank LSB, bank MSB}; MSB 0x26 = 38 is the kit bank.  The Tone
    hash (ToneKeyFind 0x4856FC51, key MSB<<16 | LSB<<8 | program) gives the tone record;
  * a kit is a TABLE tone (class 0x40, TgNoteOn 0x4C036832 -> TgNoteOnTableTone 0x4C03600D):
    `+0x27 + note*3` is a {program, LSB, MSB} triple per note (`tone_note`), which
    TgPartVoiceRecFetchSel 0x4C03858D -> TgPartVoiceRecFetch 0x4C038535 -> VoiceRecFetchBanked
    0x484496C9 -> VoiceBankClassify 0x485713D6 / VoiceBankLookupInternal 0x4857150D (key
    MSB<<16 | LSB<<8 | program&0x7F) turn into a voice record, whose first 13 bytes are its name.
The kit a note plays is its part's set-up {prog, bank_lsb, bank_msb} (style record +0x11 + 15*part,
bytes 2-4), replaced by a program change in the variation's set-up events.

Prints: each kit the 169 IC18 styles play (notes, keys outside 27-87); per key, the names the
played kits give it; Standard Kit 1 (tone 0x260000)'s full 128-key map; and the share of drum
notes whose kit names the key as Standard Kit 1 does.  Measured 2026-11-02: 188,420 of 203,802
(92.5 %); the rest are the brush, orchestral, bongo/conga, voice and SFX kits' own sounds.
Voice Kit (program 64) keys 74-77 are "Count 1".."Count 4" (the COUNT INTRO patterns).

Run from kn7000/ (read-only, deterministic):

    python3 -I notes/mn10300-names-probes/rhythm_drum_kit_keys.py
"""
import collections
import os
import re
import sys

KN7 = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(KN7, "tools"))
import gen_ic18_rhythm_s as R  # noqa: E402

L = open(os.path.join(KN7, "src/table/voices/internal_archive.s"), "rb").read().decode("latin-1").split("\n")


def section(start_label):
    i = next(k for k, x in enumerate(L) if x.startswith(start_label + ":"))
    out = []
    for x in L[i + 1:]:
        m = re.match(r"\s*\.long\s+(\w+) - InternalVoiceArchive", x)
        if not m:
            break
        out.append(m.group(1))
    return out


voice_dir = section("JkVoiceDirectory")
tone_dir = section("JkToneDirectory")
name = {}
for i, x in enumerate(L):
    m = re.match(r"^((?:Voice|Tone)_\w+):", x)
    if m:
        n = re.match(r'\s*\.ascii\s+"(.*)"', L[i + 1])
        name[m.group(1)] = n.group(1).strip() if n else "?"
voice_key, tone_key, kits = {}, {}, {}
for i, x in enumerate(L):
    if x.startswith("JkVoiceBankEnt") or x.startswith("JkToneEnt"):
        k = int(re.search(r"0x[0-9a-f]+", L[i + 2]).group(0), 16)
        if x.startswith("JkVoiceBankEnt"):
            b = [int(v, 16) for v in re.findall(r"0x[0-9a-f]+", L[i + 3])]
            voice_key[k] = b[0] | b[1] << 8
        else:
            tone_key[k] = int(re.search(r"jk_tone_key\s+(\d+)", L[i + 3]).group(1))
    m = re.match(r"^(Tone_\w+):", x)
    if m and "tone_head_table" in L[i + 2]:
        kits[m.group(1)] = [[int(v, 16) for v in re.findall(r"0x[0-9a-f]+", L[i + 3 + k])] for k in range(128)]


def kit_of(sound):
    p, lsb, msb = sound
    t = tone_key.get(msb << 16 | lsb << 8 | p)
    return tone_dir[t] if t is not None else None


def key_name(sound, key):
    t = kit_of(sound)
    if t not in kits:
        return None
    a, b, c = kits[t][key]
    ix = voice_key.get(c << 16 | b << 8 | (a & 0x7F))
    return name.get(voice_dir[ix]) if ix is not None and ix < len(voice_dir) else None


def main():
    d = open(os.path.join(KN7, "baserom/kn7000_ic18.rom"), "rb").read()
    u24 = lambda o: (d[o] << 16) | (d[o + 1] << 8) | d[o + 2]  # noqa: E731
    u16 = lambda o: (d[o] << 8) | d[o + 1]  # noqa: E731
    st, ci = 0x10000 + u24(0x10000 + 0x1E), 0x10000 + u24(0x10000 + 0x21)
    use = collections.defaultdict(collections.Counter)
    for i in range((ci - st) // 3):
        r = 0x10000 + u24(st + 3 * i)
        base = {p: tuple(d[r + 0x11 + 15 * p + 2:r + 0x11 + 15 * p + 5]) for p in (0, 7)}
        for j in range(20):
            v = r + u24(r + 0x8A + 3 * j)
            ln, kit = u16(v + 4), dict(base)
            o = v + 6
            while o < v + 6 + ln:
                if d[o] & 0xF0 == 0xC0 and d[o] & 15 in (0, 7):
                    kit[d[o] & 15] = tuple(d[o + 1:o + 4])
                o += R.ev_len(d, o) if d[o] >= 0x80 else 1
            o = v + 9 + ln
            e = o + u24(v + 6 + ln)
            while o < e:
                if d[o] & 0xF0 == 0x90 and d[o] & 15 in (0, 7):
                    use[kit[d[o] & 15]][d[o + 1]] += 1
                o += R.ev_len(d, o) if d[o] >= 0x80 else 1
    print("== kits the styles play: {program, LSB, MSB} tone, notes, keys outside 27-87")
    for k, c in sorted(use.items(), key=lambda x: -sum(x[1].values())):
        t = kit_of(k)
        print(f"   {k} {t and name.get(t) or '(no tone in the internal archive)'}: {sum(c.values())},",
              sorted(x for x in c if not 27 <= x <= 87))
    by_key = collections.defaultdict(collections.Counter)
    for kit, c in use.items():
        for key, n in c.items():
            by_key[key][key_name(kit, key)] += n
    std1 = (0, 0, 38)
    agree = total = 0
    print("== per key: Standard Kit 1's name | notes | names the played kits give it")
    for key in range(128):
        n1 = key_name(std1, key)
        c = by_key.get(key, collections.Counter())
        t = sum(c.values())
        agree += c[n1]
        total += t
        print(f"   {key:3d} {n1!r:18s} {t:6d}  {c.most_common(4) if t and c[n1] != t else ''}")
    print(f"== drum notes whose kit names the key as Standard Kit 1 does: {agree} of {total}")
    print("== Voice Kit (program 64) keys 73-78:", [(k, key_name((64, 0, 38), k)) for k in range(73, 79)])


if __name__ == "__main__":
    main()
