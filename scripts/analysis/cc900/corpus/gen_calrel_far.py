#!/usr/bin/env python3
"""Writes firmware/p6_calrel_far2.c: probe calrel's far case (lane_vmb).  p6_calrel_far.c put its 49 KB pad on one
macro-expanded line, which V4.23 refused (THC1-Fatal-150, "Too large string"); this one writes the pad as twelve
functions of 1,000 one-line stores (about 59 KB), so that a call / tail call across it is beyond the 16-bit reach of
calr and jrl, in both directions.  What does asm900 do then: call / jp, or an error?

usage: python3 -I -B gen_calrel_far.py      (from scripts/analysis/cc900/corpus; rewrites the file)
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
out = ['/* Phase 6, probe calrel, far part (generated by ../gen_calrel_far.py; see p6_calrel.c): a call and a tail',
       '   call over about 59 KB, beyond the 16-bit reach of calr and jrl, in both directions. */',
       'extern unsigned char __near flag;',
       'extern unsigned char big[];',
       'void leaf_far(void);',
       '',
       'void leaf_near(void) { flag = 1; }',
       'void call_far(void) { leaf_far(); flag = 10; }',
       'void tail_far(void) { leaf_far(); }']
for k in range(12):
    out.append('void pad%02d(void)' % k)
    out.append('{')
    out += ['    big[%d] = 1;' % (k * 1000 + i) for i in range(1000)]
    out.append('}')
out += ['void leaf_far(void) { flag = 11; }',
        'void call_far_back(void) { leaf_near(); flag = 12; }',
        'void tail_far_back(void) { leaf_near(); }', '']
open(os.path.join(HERE, 'firmware', 'p6_calrel_far2.c'), 'w').write('\n'.join(out))
