import sys

import codegen as cg  # noqa: E402

SETS = ('none', 'O3XS')


class Decline(Exception):
    pass


def need(c):
    if not c:
        raise Decline()


def hx(v):
    return '0x%x' % v


def fdata(v):
    m, e = ('%.16e' % v).split('e')
    return '%s0000e%s%03d' % (m, '-' if int(e) < 0 else '+', abs(int(e)))


# ============================================================================================ types

def is_dbl(t):
    return t is not None and t.kind == 'float' and t.size == 8


def is_int(t):
    return t is not None and t.kind == 'int' and t.size == 2 and t.signed


def is_long(t):
    return t is not None and t.kind == 'int' and t.size == 4 and t.signed


def strip(n):
    return cg.strip(n)


# ============================================================================================ AST -> IR

class Fn:
    """the function's context for classification: its double parameter(s), locals, callee"""

    def __init__(self, f):
        self.f = f
        self.params = {}
        self.locals = {}
        self.iparams = {}
        self.pparams = {}


def gname(d):
    return '_' + d.name


def fexpr(n, C):
    """a double expression -> IR tuple"""
    n = strip(n)
    need(is_dbl(n.ty))
    if n.k == 'load':
        v = strip(n.e)
        need(v.k == 'var')
        d = v.decl
        need(is_dbl(d.ty))
        if d.kind == 'global':
            return ('g', gname(d))
        if d.kind == 'param':
            need(d in C.params)
            return ('p', d)
        need(d.kind == 'local' and d in C.locals)
        return ('l', d)
    if n.k == 'fconst':
        need(n.value is not None)
        return ('k', float(n.value))
    if n.k == 'call':
        return ('call',) + callee(n, C)
    if n.k == 'bin':
        need(n.op in ('+', '-', '*', '/'))
        return ('bin', n.op, fexpr(n.l, C), fexpr(n.r, C))
    if n.k == 'un':
        need(n.op == '-')
        return ('neg', fexpr(n.e, C))
    if n.k == 'cast':
        need(n.kind == 'IntegralToFloating')
        x = strip(n.e)
        if x.k == 'load' and is_long(x.ty):
            v = strip(x.e)
            need(v.k == 'var' and v.decl.kind == 'global' and is_long(v.decl.ty))
            return ('l2d', gname(v.decl))
        need(is_int(x.ty))
        return ('i2d', iexpr(x, C))
    if n.k == 'cond':
        return ('cond', cond(n.c, C), fexpr(n.a, C), fexpr(n.b, C))
    raise Decline()


def callee(n, C):
    """a call of `double fd(double)` -> (symbol, argument IR)"""
    fn = strip(n.fn)
    need(fn.k == 'var' and fn.decl.kind == 'func')
    t = fn.decl.ty
    need(t is not None and t.kind == 'func' and is_dbl(t.ret))
    need(re.search(r'\(\s*double\s*\)', t.spell or '') is not None)
    need(len(n.args) == 1)
    return gname(fn.decl), fexpr(n.args[0], C)


def ivar(n):
    """a load of an int global -> its symbol"""
    n = strip(n)
    need(n.k == 'load' and is_int(n.ty))
    v = strip(n.e)
    need(v.k == 'var' and v.decl.kind == 'global' and is_int(v.decl.ty))
    return gname(v.decl)


def iexpr(n, C):
    """an int expression of the probes: gi, gi + K"""
    n = strip(n)
    if n.k == 'load':
        return ('iv', ivar(n))
    if n.k == 'bin' and n.op == '+' and strip(n.r).k == 'const':
        return ('iadd', ivar(n.l), strip(n.r).value)
    raise Decline()


REL = {'<=': 0, '<': 1, '>=': 2, '>': 3, '==': 4, '!=': 5}
NEGREL = {'<=': '>', '<': '>=', '>=': '<', '>': '<=', '==': '!=', '!=': '=='}


def cond(n, C):
    """a condition -> IR: ('fcmp', rel, A, B), ('fcmpz', rel, A), ('itest', sym), ('icmp', rel, sym, K),
    ('and', a, b), ('or', a, b), ('not', c)"""
    n = strip(n)
    if n.k == 'bin' and n.op in REL:
        l, r = strip(n.l), strip(n.r)
        if is_dbl(l.ty):
            if r.k == 'fconst' and r.value == 0.0:
                return ('fcmpz', n.op, fexpr(l, C))
            return ('fcmp', n.op, fexpr(l, C), fexpr(r, C))
        need(r.k == 'const')
        return ('icmp', n.op, ivar(l), r.value)
    if n.k == 'bin' and n.op in ('&&', '||'):
        return ('and' if n.op == '&&' else 'or', cond(n.l, C), cond(n.r, C))
    if n.k == 'un' and n.op == '!':
        return ('not', cond(n.e, C))
    return ('itest', ivar(n))


def stmts(n, C):
    n = strip(n) if n.k not in ('block',) else n
    if n.k == 'block':
        out = []
        for c in n.body:
            out += stmts(c, C)
        return out
    return [stmt(n, C)]


def stmt(n, C):
    k = n.k
    if k == 'decl':
        d = n.var
        need(is_dbl(d.ty) and n.init is None)
        C.locals[d] = True
        return ('nop', n)
    if k == 'expr':
        e = strip(n.e)
        if e.k == 'call':
            fn = strip(e.fn)
            if fn.k == 'var' and fn.decl.ty is not None and fn.decl.ty.kind == 'func' and \
                    fn.decl.ty.ret is not None and fn.decl.ty.ret.kind == 'void':
                need(re.search(r'\(\s*double\s*\)', fn.decl.ty.spell or '') is not None and len(e.args) == 1)
                return ('vcall', n, gname(fn.decl), fexpr(e.args[0], C))
            return ('call', n) + callee(e, C)
        if e.k == 'opassign':
            need(is_dbl(e.ty) and e.op in ('+', '-', '*', '/'))
            return ('fopset', n, e.op, lval(e.l, C), fexpr(e.r, C))
        if e.k == 'incdec':
            v = strip(e.e)
            need(v.k == 'var' and v.decl.kind == 'global' and is_int(v.decl.ty))
            return ('iinc', n, gname(v.decl), 1 if e.op == '++' else -1, 'post' if e.post else 1)
        need(e.k == 'bin' and e.op == '=')
        if is_dbl(e.ty):
            return ('fset', n, lval(e.l, C), fexpr(e.r, C))
        l = strip(e.l)
        r = strip(e.r)
        if l.k == 'var' and l.decl.kind == 'global' and is_long(l.decl.ty) and r.k == 'cast' and \
                r.kind == 'FloatingToIntegral':
            return ('d2l', n, gname(l.decl), fexpr(r.e, C))
        if l.k == 'var' and l.decl.kind == 'global' and is_int(l.decl.ty):
            g = gname(l.decl)
            if r.k == 'const':
                return ('iset', n, g, r.value)
            if r.k == 'bin' and r.op == '+' and strip(r.r).k == 'const' and strip(r.r).value == 1 and \
                    strip(r.l).k == 'load' and strip(strip(r.l).e).k == 'var' and strip(strip(r.l).e).decl is l.decl:
                return ('iinc', n, g, 1, 2)
            if r.k == 'bin' and r.op in ('&&', '||') or r.k == 'bin' and r.op in REL and is_dbl(strip(r.l).ty):
                return ('ibool', n, g, cond(r, C))
            if r.k == 'cast' and r.kind == 'FloatingToIntegral':
                return ('d2i', n, g, fexpr(r.e, C))
        return int_assign(n, l, r, C)
    if k == 'if':
        return ('if', n, cond(n.cond, C), stmts(n.then, C), stmts(n.els, C) if n.els is not None else None)
    if k == 'while':
        return ('while', n, cond(n.cond, C), stmts(n.body, C))
    if k == 'do':
        return ('do', n, stmts(n.body, C), cond(n.cond, C))
    if k == 'for':
        need(n.init is None and n.cond is None and n.inc is None)
        return ('forever', n, stmts(n.body, C))
    if k == 'break':
        return ('break', n)
    if k == 'return':
        if n.value is None:
            return ('ret', n, None)
        need(is_dbl(strip(n.value).ty))
        return ('ret', n, fexpr(n.value, C))
    raise Decline()


# ---------------------------------------------------------------------------------------------- int statements

def iplace(n, C):
    """an int / long / char / pointer / float object -> ('g', sym, size) for a global, ('el', text, size) for an
    element at a constant or a member of a global struct, ('dp', ptr sym, size) for *gp, ('pm', ptr sym, off, size)
    for gps->m, ('pa', param decl, size) for an int parameter"""
    n = strip(n)
    t = n.ty
    need(t is not None and (t.kind in ('int', 'ptr') or t.kind == 'float' and t.size == 4))
    size = 4 if t.kind == 'ptr' else t.size
    need(size in (1, 2, 4))
    if n.k == 'var':
        d = n.decl
        if d.kind == 'global':
            return ('g', gname(d), size)
        need(d.kind == 'param' and size == 2 and d in C.iparams)
        return ('pa', d, size)
    if n.k == 'index':
        b = strip(n.base)
        need(b.k == 'var' and b.decl.kind == 'global' and b.decl.ty is not None and b.decl.ty.kind == 'array')
        i = strip(n.idx)
        need(i.k == 'const' and i.value is not None and i.value > 0)
        return ('el', '%s + %s' % (gname(b.decl), hx(i.value * size)), size)
    if n.k == 'member':
        off = cg.member_offset(n)
        if n.arrow:
            p = strip(n.base)
            need(p.k == 'load' and strip(p.e).k == 'var' and strip(p.e).decl.kind == 'global')
            need(off == 0)
            return ('dp', gname(strip(p.e).decl), size)
        b = strip(n.base)
        need(b.k == 'var' and b.decl.kind == 'global')
        return ('el', gname(b.decl) if off == 0 else '%s + %s' % (gname(b.decl), hx(off)), size)
    if n.k == 'deref':
        p = strip(n.e)
        need(p.k == 'load' and strip(p.e).k == 'var' and strip(p.e).decl.kind in ('global', 'param'))
        d = strip(p.e).decl
        if d.kind == 'param':
            need(d in C.pparams)
            return ('dpp', d, size)
        return ('dp', gname(d), size)
    raise Decline()


def iload_src(n, C):
    """a value read from an int object (through loads and same-size casts) -> (place, signed)"""
    n = strip(n)
    while n.k == 'cast' and n.kind in ('NoOp', 'IntegralCast') and strip(n.e).ty is not None and \
            strip(n.e).ty.size == n.ty.size:
        n = strip(n.e)
    need(n.k == 'load')
    t = n.ty
    return iplace(n.e, C), bool(getattr(t, 'signed', False)) and t.kind == 'int'


def int_assign(n, l, r, C):
    """dst = src (a copy, with a widening or narrowing), dst = src op K / -src / src == K, dst op= src"""
    dst = iplace(l, C)
    w = r
    if w.k == 'cast' and w.kind == 'IntegralCast' and strip(w.e).ty is not None and strip(w.e).ty.size != w.ty.size:
        src, sg = iload_src(w.e, C)
        need(src[2] in (1, 2) and dst[2] in (1, 2, 4) and (dst[2] > src[2] and sg or dst[2] < src[2]))
        return ('icopy', n, dst, src, sg, 1)
    if w.k == 'un' and w.op == '-':
        src, sg = iload_src(w.e, C)
        need(dst[2] == 2 and src[2] == 2)
        return ('iop', n, dst, src, 'neg', None)
    if w.k == 'bin' and w.op in ('+', '&', '*', '<<') and strip(w.r).k == 'const':
        src, sg = iload_src(w.l, C)
        need(dst[2] == src[2] and dst[2] in (2, 4))
        return ('iop', n, dst, src, w.op, strip(w.r).value)
    if w.k == 'bin' and w.op == '==' and strip(w.r).k == 'const':
        src, sg = iload_src(w.l, C)
        need(dst[2] == 2 and src[0] == 'g' and src[2] == 2)
        return ('ieqk', n, dst, src, strip(w.r).value)
    explicit = w.k == 'cast' and getattr(w, 'explicit', False)
    src, sg = iload_src(w, C)
    need(src[2] == dst[2])
    need(not (src == dst))
    return ('icopy', n, dst, src, sg, 2 if explicit else 1)       # gi = (int)gu2: 2 units (fpp11 w09)


def lval(n, C):
    n = strip(n)
    need(n.k == 'var' and is_dbl(n.decl.ty))
    d = n.decl
    if d.kind == 'global':
        return ('g', gname(d))
    if d.kind == 'param':
        need(d in C.params)
        return ('p', d)
    need(d.kind == 'local' and d in C.locals)
    return ('l', d)


INT_DST = ('iset', 'iinc', 'icopy', 'iop', 'ieqk', 'ibool', 'd2i')


class Ghost:
    """the statement node of a call left behind by a dropped assignment"""
    k = 'ghost'


def int_dst(x):
    """the int global a statement writes, or None"""
    if x[0] in ('iset', 'iinc', 'ibool', 'd2i'):
        return x[2]
    if x[0] in ('icopy', 'iop', 'ieqk') and x[2][0] == 'g' and x[2][2] == 2:
        return x[2][1]
    return None


def int_reads(x, g):
    """the statement reads the int global g"""
    if x[0] == 'iinc':
        return x[2] == g
    if x[0] in ('icopy', 'iop', 'ieqk'):
        return x[3] == ('g', g, 2) or x[3][0] not in ('g', 'el', 'pa')
    if x[0] == 'ibool':
        hit = []
        walk(x[3], lambda t: hit.append(t) if t[0] in ('itest', 'icmp') and t[1 if t[0] == 'itest' else 2] == g else None)
        return bool(hit)
    if x[0] in ('iset', 'd2i'):
        return False
    return True


def has_call(x):
    hit = []
    walk(x[2:], lambda t: hit.append(t) if t[0] == 'call' and isinstance(t[1], str) else None)
    return bool(hit)


def ivars_read(x):
    """int globals a statement (or its condition) tests or reads"""
    out = set()
    walk(list(x[2:]) if x[0] != 'dead' else [], lambda t: out.add(t[1]) if t[0] == 'itest' else
         (out.add(t[2]) if t[0] == 'icmp' else None))
    if x[0] in ('icopy', 'iop', 'ieqk') and x[3][0] == 'g':
        out.add(x[3][1])
    if x[0] == 'iinc':
        out.add(x[2])
    return out


def ends_with_iset(lst):
    return bool(lst) and lst[-1][0] == 'iset'


def o3_guard(body):
    """-O3 -XS tracks an int global's value in WA and in the test that follows; the shapes where it does are declined:
    a statement reading what the previous one stored (fpp10 e06, fpp11 w21 / w27 / w44), two elements of one array
    (w38: a common base), a test after a loop or an if that ends storing its variable (fpp9 v6 / v8 / v40, fpp11 w23 /
    w24), an else-if on the same variable (fpp8 mk06), a while right after a constant store (fpp9 v1)"""
    prev = None
    for x in body:
        for b in children(x):
            if b:
                o3_guard(b)
        if prev is not None:
            g = int_dst(prev) if prev[0] != 'dead' else None
            if g is not None and prev[0] in ('icopy', 'iop', 'ieqk', 'iset') and g in ivars_read(x) and \
                    (int_dst(x) == g or prev[0] != 'iset' and prev[3][0] == 'g' and int_dst(x) == prev[3][1]):
                raise Decline()
            tests = ivars_read(('c', None, x[2])) if x[0] in ('if', 'while') else set()
            if prev[0] in ('do', 'while') and tests & ivars_read(('c', None, prev[3] if prev[0] == 'do' else prev[2])):
                raise Decline()
            if prev[0] == 'if' and any(b and b[-1][0] == 'iset' and b[-1][2] in tests for b in children(prev)):
                raise Decline()
            if prev[0] == 'icopy' and x[0] == 'icopy' and prev[3][0] == 'el' and x[3][0] == 'el':
                raise Decline()
        if x[0] == 'if' and x[4] and x[4][0][0] == 'if' and ivars_read(('c', None, x[2])) & ivars_read(('c', None, x[4][0][2])):
            raise Decline()
        if x[0] == 'while' and x[3] and x[3][-1][0] in ('icopy', 'iop') and \
                int_dst(x[3][-1]) in ivars_read(('c', None, x[2])):
            raise Decline()
        prev = x


def dead_stores(body):
    """-O3 -XS: an int global's assignment that the next statement overwrites without reading it is dropped; its
    calls stay (fpp7 n01 / n08 / n09 / n17 / n20 / m13, fpp6 se2, fpp8 nv07-nv10, fpp10 e34)"""
    out = []
    for x in body:
        if x[0] == 'if':
            x = (x[0], x[1], x[2], dead_stores(x[3]), dead_stores(x[4]) if x[4] is not None else None)
        elif x[0] == 'while':
            x = (x[0], x[1], x[2], dead_stores(x[3]))
        elif x[0] in ('do', 'forever'):
            x = (x[0], x[1], dead_stores(x[2])) + x[3:]
        g = int_dst(x)
        if out and g is not None and int_dst(out[-1]) == g and not int_reads(x, g) and not has_call(x):
            out[-1] = ('dead', out[-1][1], out[-1])     # its temporaries stay, its calls too (fpp7 n17 / n20)
        out.append(x)
    return out


# ---------------------------------------------------------------------------------------------- the region flag (E1)

def is_memory(x):
    x = strip(x)
    if x.k == 'var':
        return x.decl.kind in ('global', 'param')
    return x.k in ('deref', 'index', 'member')


def mem_leaf(x):
    x = strip(x)
    while x.k == 'cast' and (x.kind == 'NoOp' or (x.kind == 'IntegralCast' and strip(x.e).ty.size == x.ty.size)):
        x = strip(x.e)
    if x.k == 'load':
        x = strip(x.e)
    return x if x.k in ('var', 'deref', 'index', 'member') else None


def same_obj(a, b):
    a, b = mem_leaf(a), mem_leaf(b)
    return a is not None and b is not None and a.k == 'var' and b.k == 'var' and a.decl is b.decl


def is_reset(st):
    """a resetting statement (E1, model fpe3.is_reset): a plain copy between memory objects of an integer, pointer
    or float type, `m op= m2` / `m = m op m2`, a long ++ / --, `if (m & c)`; the region is then D, not D + D'"""
    k = st.k
    if k == 'if':
        c = strip(st.cond)
        return c.k == 'bin' and c.op == '&' and mem_leaf(c.l) is not None and strip(c.r).k == 'const' and \
            not is_dbl(c.ty)
    if k != 'expr':
        return False
    e = strip(st.e)
    if e.k == 'opassign' and not (e.ty is not None and e.ty.kind == 'float'):
        if e.op in ('+', '-', '*', '/', '&', '|', '^'):
            return is_memory(e.l) and mem_leaf(e.r) is not None
        return False
    if e.k == 'incdec' and e.ty is not None and e.ty.kind == 'int' and e.ty.size == 4:
        return is_memory(e.e)
    if e.k != 'bin' or e.op != '=' or is_dbl(e.ty):
        return False
    r = strip(e.r)
    while r.k == 'cast' and (r.kind == 'NoOp' or (r.kind == 'IntegralCast' and strip(r.e).ty.size == r.ty.size)):
        r = strip(r.e)
    if r.k == 'bin' and r.op in ('+', '-', '*', '/', '&', '|', '^') and not (e.ty is not None and e.ty.kind == 'float'):
        if same_obj(e.l, r.l) and mem_leaf(r.r) is not None and strip(r.r).k != 'const':
            return is_memory(e.l)
        if r.op in ('+', '*', '&', '|', '^') and same_obj(e.l, r.r) and mem_leaf(r.l) is not None and \
                strip(r.l).k != 'const':
            return is_memory(e.l)
        if r.op == '+' and strip(r.r).k == 'const' and strip(r.r).value == 0:
            r = strip(r.l)
        else:
            return False
    while r.k == 'cast' and r.kind == 'NoOp':
        r = strip(r.e)
    if r.k == 'load':
        r = strip(r.e)
    if r.k not in ('var', 'deref', 'index', 'member'):
        return False
    if r.k == 'var' and strip(e.l).k == 'var' and strip(e.l).decl is r.decl:
        return False
    return is_memory(e.l) and is_memory(r)


def any_reset(body, opt=False):
    for i, s in enumerate(body):
        if s[0] == 'dead':
            continue
        if not opt and i and s[0] == 'icopy' and body[i - 1][0] == 'iop' and body[i - 1][2] == s[2] and \
                s[3] != s[2]:
            continue                                   # a copy after a dropped store does not reset (fpp11 w22)
        if is_reset(s[1]):
            return True
        for b in children(s):
            if b and any_reset(b):
                return True
    return False


def classify(f):
    C = Fn(f)
    for d in f.params:
        if is_dbl(d.ty):
            C.params[d] = True
        elif is_int(d.ty):
            C.iparams[d] = True
        else:
            need(d.ty is not None and d.ty.kind == 'ptr')
            C.pparams[d] = True
    need(len(f.params) <= 1)
    need(f.ret is not None and (f.ret.kind == 'void' or is_dbl(f.ret)))
    body = [s for s in stmts(f.body, C) if s[0] != 'nop']
    tail = []
    for i, s in enumerate(body):                       # code after a return is dropped, its units stay (fpp7 n21)
        if s[0] == 'ret':
            body, tail = body[:i + 1], [('dead', x[1], x) for x in body[i + 1:]]
            break
    while body and not is_dbl(f.ret):                  # a trailing `return;`, a trailing `if (c) return;` does nothing
        last = body[-1]                                # (fpp7 m21, m22, m32); the calls of c stay (fpp6 hr1)
        if last[0] == 'ret' and last[2] is None:
            body = body[:-1]
            tail = [('dead', last[1], last)] + tail
            continue
        if last[0] == 'if' and last[4] is None and len(last[3]) == 1 and last[3][0][0] == 'ret' and last[3][0][2] is None:
            calls = []
            walk(last[2], lambda t: calls.append(t) if t[0] == 'call' else None)
            need(all(not any(isinstance(y, tuple) and y[0] == 'call' for y in [c[2]]) for c in calls))
            body = body[:-1] + [('call', last[1], c[1], c[2]) for c in calls]
            if GHOST_IF and not calls:                 # (fpp6 hr1: with a call in c, the call alone)
                tail = [('dead', last[1], last)] + tail
            continue
        break
    return C, body + tail


GHOST_IF = True


# ============================================================================================ helpers on the IR

def walk(x, fn):
    if isinstance(x, tuple):
        fn(x)
        for y in x[1:]:
            if isinstance(y, (tuple, list)):
                walk(y, fn)
    elif isinstance(x, list):
        for y in x:
            walk(y, fn)


def ncalls(x):
    n = [0]

    def f(t):
        if t and t[0] == 'call' and isinstance(t[1], str) and t[1].startswith('_'):
            n[0] += 1
    if isinstance(x, tuple) and x and x[0] == 'call' and not isinstance(x[1], str):
        n[0] += 1
        walk(x[3], f)
        return n[0]
    walk(x, f)
    return n[0]


def addressable(x):
    return x[0] in ('g', 'k', 'p', 'l')


def weight(x):
    """Sethi-Ullman: temporaries an expression needs"""
    if addressable(x):
        return 0
    if x[0] == 'bin':
        a, b = weight(x[2]), weight(x[3])
        return max(a, b) if a != b else a + 1
    if x[0] == 'neg':
        return max(weight(x[1]), 1)
    return 1


# ============================================================================================ allocation

class Slot:
    def __init__(self, sid, kind, size, cidx):
        self.id, self.kind, self.size, self.cidx = sid, kind, size, cidx
        self.busy = True
        self.off = None


class Alloc:
    """frame temporaries (E3): op slots pooled (free again at each statement, and as soon as their value is read:
    free-dead), the most recently freed on top; call and long slots never reused"""

    def __init__(self):
        self.slots = []
        self.stack = []
        self.log = []
        self.nst = 0
        self.shadow = set()           # slots a long took in the shadow allocator (D')
        self.saved = 0

    def begin(self, node):
        self.nst += 1
        self.log.append(('stmt', node))
        for s in sorted(self.slots, key=lambda s: s.cidx):
            if s.kind == 'op' and s.busy:
                self.release(s)

    def release(self, s):
        s.busy = False
        if s in self.stack:
            self.stack.remove(s)
        self.stack.append(s)

    def get(self, kind, size=8, shadow=True):
        if kind == 'op':
            free = [s for s in self.stack if not s.busy and s.size == size]
            if free:
                s = free[-1]
                s.busy = True
                self.stack.remove(s)
                self.log.append(('get', 'op', s))
                return s
        if kind == 'long' and shadow:   # the shadow (D'): a long takes a free 8-byte slot, an op slot or an ended call's
            cand = [x for x in self.slots if x.size == 8 and x not in self.shadow and
                    (x.kind == 'op' and not x.busy or x.kind == 'call' and x.nst < self.nst)]
            if cand:
                self.shadow.add(cand[-1])
                self.saved += 4
        s = Slot(len(self.slots), kind, size, len(self.slots))
        s.nst = self.nst
        self.slots.append(s)
        self.log.append(('get', kind, s))
        return s

    def dead(self, *slots):
        """free-dead: op slots whose value was read, shallow first"""
        for s in sorted([s for s in slots if s is not None and s.kind == 'op' and s.busy], key=lambda s: s.cidx):
            self.release(s)


# ============================================================================================ the window rule (E2)

PHANTOM = True
W_SEQ = (3, 7, 17, 21, 25)
T_SEQ = (3, 7, 15, 21, 25)


def is_fcmp(c):
    hit = []
    walk(c, lambda t: hit.append(t) if t[0] in ('fcmp', 'fcmpz') else None)
    return bool(hit)


def units(s):
    """-> (units at the statement's start, nested calls)"""
    k = s[0]
    if k == 'dead':
        if s[2][0] == 'if':                            # a dropped trailing `if (c) return;`: its closing unit
            return end_units(s[2]), 0
        return units(s[2])
    if k == 'call':
        return 1, ncalls(s[3])
    if k == 'vcall':
        return 1, ncalls(s[3])
    if k == 'fopset':
        return 1, ncalls(s[4])
    if k == 'fset':
        r = s[3]
        n = ncalls(r)
        if r[0] == 'call':
            return 1, n - 1
        if r[0] == 'cond':
            return 0, n
        if r[0] == 'i2d':
            return 0, n
        if r[0] == 'l2d':
            return 2, n
        if r[0] in ('bin', 'neg'):
            conv = sum(1 for x in (r[2:] if r[0] == 'bin' else r[1:]) if isinstance(x, tuple) and x[0] == 'i2d')
            return 2 - conv, n
        return 1, n
    if k == 'd2l':
        return 2, ncalls(s[3])
    if k == 'd2i':
        return 1, ncalls(s[3])
    if k == 'icopy':
        return (s[5] if len(s) > 5 else 1), 0
    if k == 'ieqk':
        return 1, 0
    if k == 'iop':
        return 2, 0
    if k == 'iset':
        return 1, 0
    if k == 'iinc':
        return (1 if s[4] == 'post' else s[4]), 0
    if k == 'ibool':
        return 1, ncalls(s[3])
    if k == 'ret':
        v = s[2]
        if v is None:
            return 0, 0
        n = ncalls(v)
        if v[0] == 'call':
            return 1, n
        if v[0] == 'cond':
            return 0, n
        if v[0] in ('bin', 'neg'):
            return (1 if n else 2), n
        return 1, n
    if k in ('if', 'while'):
        return 0, ncalls(s[2])
    if k == 'do':
        return 0, ncalls(s[3])
    if k == 'forever':
        return 0, 0
    if k == 'break':
        return 0, 0
    return 1, 0


def end_units(s):
    if s[0] == 'if':
        return -1 if is_fcmp(s[2]) else 0
    if s[0] == 'while':
        return -3 if is_fcmp(s[2]) else 0
    if s[0] == 'do':
        return -1 if is_fcmp(s[3]) else 0
    return 0


def body_nodes(s):
    out = set()

    def f(lst):
        for x in lst or []:
            out.add(id(x[1]))
            for b in children(x):
                f(b)
    for b in children(s):
        f(b)
    return out


def children(s):
    if s[0] == 'if':
        return [s[3], s[4]]
    if s[0] in ('while', 'forever'):
        return [s[3] if s[0] == 'while' else s[2]]
    if s[0] == 'do':
        return [s[2]]
    return []


def root_stmt(s):
    return s is not None and s[0] == 'fset' and s[3][0] in ('bin', 'neg')


def from_log(log, irof):
    """(stmts, created) as fpwindow.from_log: created[slot] = (kind letter, creation index, k)"""
    stl = []
    created = {}
    k = [0]
    root = [None, False]
    for i, e in enumerate(log):
        if e[0] == 'stmt':
            st = irof(e[1])
            stl.append([st, [], None])
            if root_stmt(st):
                j = i + 1
                first_op = None
                while j < len(log) and log[j][0] == 'get':
                    if log[j][1] == 'op':
                        first_op = j
                        break
                    j += 1
                stl[-1][2] = first_op
                if first_op is None and root[0] is None and PHANTOM:
                    root[0] = k[0]
                    root[1] = False
                    k[0] += 1
            continue
        o = e[2]
        if o not in created:
            kk = None
            if e[1] == 'op':
                is_root = bool(stl) and stl[-1][2] == i
                if is_root and root[0] is not None and not root[1]:
                    kk = root[0]
                    root[1] = True
                else:
                    kk = k[0]
                    k[0] += 1
                    if is_root and root[0] is None:
                        root[0] = kk
                        root[1] = True
            created[o] = (e[1][0], len(created), kk)
            if not stl:
                stl.append([None, [], None])
            stl[-1][1].append(o)
    return [(x[0], x[1]) for x in stl], created


def sequence(stl, created):
    out = []
    stack = []

    def close(upto):
        while len(stack) > upto:
            node, ids, start = stack.pop()
            if node[0] in ('while', 'do', 'forever'):
                out.extend([(w, []) for w, _ in out[start:]])
            e = end_units(node)
            if e:
                out.append((e, []))
    for node, offs in stl:
        while stack and (node is None or id(node[1]) not in stack[-1][1]):
            close(len(stack) - 1)
        own, nested = units(node) if node is not None else (1, 0)
        if node is not None and node[0] == 'iinc' and node[4] == 'post' and not stack:
            own = 2                                    # a top-level gi++ / gi-- counts 2 (fpp11 w13 / w17), 1 in a
                                                       # loop body (fpp8 mk04, mk07)
        att = [o for o in offs if created[o][0] != 'o']
        calls = [o for o in att if created[o][0] == 'c']
        other = [o for o in att if created[o][0] != 'c']
        top = node is not None and node[0] == 'call'
        ret = node is not None and node[0] == 'ret' and node[2] is not None and node[2][0] == 'call'
        head, rest = (calls[:1], calls[1:]) if (top or ret) else ([], calls)
        if ret:
            nested -= 1
            out.append((1, head))
            out.append((own + 1, other + rest[nested:]))
        else:
            out.append((own, head + other + rest[nested:]))
        for j in range(min(nested, len(rest))):
            out.append((1, []))
            out.append((1, [rest[j]]))
        if node is not None and node[0] in ('if', 'while', 'do', 'forever'):
            stack.append((node, body_nodes(node),
                          len(out) - (1 + 2 * min(nested, len(rest))) if node[0] != 'if' else len(out)))
    close(0)
    return out


def layout(stl, created):
    """top-down list of slots"""
    seq = sequence(stl, created)
    ops = sorted((o for o in created if created[o][0] == 'o'), key=lambda o: created[o][1])
    kof = {o: (created[o][2] if created[o][2] is not None else n) for n, o in enumerate(ops)}
    want = {o: W_SEQ[min(kof[o], len(W_SEQ) - 1)] for o in ops}
    thr = {o: T_SEQ[min(kof[o], len(T_SEQ) - 1)] for o in ops}
    total = sum(w for w, _ in seq)
    B = []
    count = 0
    placed = set()
    for w, att in reversed(seq):
        B.extend(sorted(att, key=lambda o: -created[o][1]))
        count += w
        for o in ops:
            if o not in placed and total >= thr[o] and count >= want[o]:
                B.append(o)
                placed.add(o)
    rest = [o for o in ops if o not in placed]
    B = sorted((o for o in rest if total < thr[o]), key=lambda o: -want[o]) + B + [o for o in rest if total >= thr[o]]
    return list(reversed(B))


# ============================================================================================ code generation

class Addr:
    """an address operand, rendered once the frame is laid out: a slot, the frame (hidden pointer, parameters,
    locals: offset from the frame's top), or a symbol"""

    def __init__(self, kind, x, push):
        self.kind, self.x, self.push = kind, x, push


class Gen:
    def __init__(self, C, opt):
        self.C = C
        self.opt = opt
        self.lines = []
        self.consts = []
        self.A = Alloc()
        self.push = 0                 # bytes pushed since the frame was allocated (XIZ, pending pops, arguments)
        self.pending = 0
        self.nlab = 0
        self.xiz = False
        self.sret = is_dbl(C.f.ret)
        self.later_call = None        # set per statement: a call comes before the next control-flow point
        self.locals = {}
        self.optional = set()

    def label(self):
        self.nlab += 1
        return 'L%d' % self.nlab

    def emit(self, op, *args):
        self.lines.append((op, list(args)))

    def lab(self, name, optional=False):
        self.flush()
        self.lines.append((name + ':', None))
        if optional:
            self.optional.add(name)

    def const(self, v):
        lab = 'S%d' % (50000 + len(self.consts))
        self.consts.append((lab, v))
        return lab

    # ----------------------------------------------------------------------------------- addresses
    def addr(self, v):
        """an operand value -> Addr"""
        k = v[0]
        if k == 'g':
            return Addr('sym', v[1], 0)
        if k == 'k':
            return Addr('sym', self.const(v[1]), 0)
        if k == 'slot':
            return Addr('slot', v[1], self.push)
        if k == 'p':
            return Addr('param', v[1], self.push)
        if k == 'l':
            return Addr('local', v[1], self.push)
        raise Decline()

    def lda(self, reg, a):
        self.emit('lda', reg, a)

    def flush(self):
        if self.pending:
            self.emit('lda', 'XSP', ('XSP+', self.pending))
            self.push -= self.pending
            self.pending = 0

    def maybe_flush(self):
        """before the result of a call is read: the pops wait only for a later call before any control flow"""
        if self.pending and not self.later_call:
            self.flush()

    def ret_ptr(self, reg='XWA'):
        if self.xiz_ret:
            self.emit('ld', reg, 'XIZ')
        else:
            self.emit('ld', reg, ('(RET)', self.push))


def peephole(lines):
    """`j cc,L1 / j L2 / L1:` -> `j !cc,L2 / L1:` (fpp6 hr2, fpp7 n22: an if whose arm is a return)"""
    INV = {'eq': 'ne', 'ne': 'eq', 'gt': 'le', 'le': 'gt', 'lt': 'ge', 'ge': 'lt', 'ugt': 'ule', 'ule': 'ugt',
           'ult': 'uge', 'uge': 'ult'}
    out = list(lines)
    i = 0
    while i + 1 < len(out):                            # decw 0x1,(X) / cpw (X),0x0 -> subw (X),0x1 (fpp7 m15)
        a, b = out[i], out[i + 1]
        if a[0] in ('decw', 'incw') and b[0] == 'cpw' and b[1][1] == '0x0' and a[1][1] == b[1][0]:
            out[i] = ('subw' if a[0] == 'decw' else 'addw', [a[1][1], a[1][0]])
            del out[i + 1]
        i += 1
    i = 0
    while i + 2 < len(out):
        a, b, c = out[i], out[i + 1], out[i + 2]
        if a[0] == 'j' and len(a[1]) == 2 and b[0] == 'j' and len(b[1]) == 1 and c[1] is None and \
                c[0] == a[1][1] + ':' and a[1][0] in INV:
            out[i] = ('j', [INV[a[1][0]], b[1][0]])
            del out[i + 1]
            continue
        i += 1
    return out


def hoist_arms(lines):
    """-O3 -XS: an instruction both arms of a test start with goes before the test (fpp8 mr09 / mr10: ld XWA,(ret)
    above cp HL,0x0 / cpw (_gi),0x0)"""
    out = list(lines)
    for i in range(len(out) - 2):
        t, j, x = out[i], out[i + 1], out[i + 2]
        if not (t[0] in ('cp', 'cpw') and j[0] == 'j' and len(j[1]) == 2):
            continue
        k = [n for n, l in enumerate(out) if l[1] is None and l[0] == j[1][1] + ':']
        if len(k) != 1 or k[0] + 1 >= len(out):
            continue
        y = out[k[0] + 1]
        if x == y and x[1] is not None and x[0] in ('ld', 'lda') and x[1][0] == 'XWA':
            del out[k[0] + 1]
            del out[i + 2]
            out.insert(i, x)
    return out


def merge_labels(lines):
    """two labels in a row are one (fpp8 mk06: the inner if's skip label is the outer if's end)"""
    alias = {}
    prev = None
    for op, args in lines:
        if args is None and op.endswith(':'):
            if prev is not None:
                alias[op[:-1]] = prev
            else:
                prev = op[:-1]
        else:
            prev = None
    out = []
    for op, args in lines:
        if args is None and op[:-1] in alias:
            continue
        if args is not None:
            args = [alias.get(a, a) if isinstance(a, str) else a for a in args]
        out.append((op, args))
    return out


def render(G, frame, offs):
    out = []
    G.lines = merge_labels(peephole(G.lines))
    used = set(a for op, args in G.lines if args for a in args if isinstance(a, str))
    G.lines = [(op, args) for op, args in G.lines if not (args is None and op[:-1] in G.optional and op[:-1] not in used)]
    if G.opt:
        G.lines = hoist_arms(G.lines)
    if G.consts:
        for lab, v in G.consts:
            out += ['\talign\t2', lab + ':', '\tfdatad\t%s' % fdata(v)]

    def addr(a):
        if isinstance(a, Addr):
            if a.kind == 'sym':
                return a.x
            if a.kind == 'slot':
                n = offs[a.x] + a.push
            elif a.kind == 'param':
                n = frame + 4 + (4 if G.sret else 0) + a.push
            elif a.kind == 'local':
                n = G.locals[a.x] + a.push
            else:
                raise Decline()
            return 'XSP+%s' % hx(n) if n else 'XSP'
        if isinstance(a, tuple) and a[0] == '(RET)':
            return '(XSP+%s)' % hx(frame + 4 + a[1])
        if isinstance(a, tuple) and a[0] == 'XSP+':
            return 'XSP+%s' % hx(a[1])
        if isinstance(a, tuple) and a[0] == 'mem':
            return '(%s)' % addr(a[1])
        return a
    if frame:
        out.append('\tdec\t%s,XSP' % hx(frame) if frame <= 8 else '\tlda\tXSP,XSP-%s' % hx(frame))
    if not frame and G.lines and G.lines[-1][0] == 'EPILOGUE' and not G.lines[-1][1][0]:
        ends = set()                                   # no frame: a jump to the label before `ret` is a return
        for op, args in reversed(G.lines[:-1]):        # (fpopa fa_a_GGI: cpw (_gi),0x0 / ret eq)
            if args is None and op.endswith(':'):
                ends.add(op[:-1])
            else:
                break
        G.lines = [(('ret', [args[0]]) if op == 'j' and args and len(args) == 2 and args[1] in ends else
                    ('ret', []) if op == 'j' and args and len(args) == 1 and args[0] in ends else (op, args))
                   for op, args in G.lines]
    for op, args in G.lines:
        if args is None:
            out.append(op)
            continue
        if op == 'EPILOGUE':
            n = frame + args[0]
            if n:
                out.append('\tinc\t%s,XSP' % hx(n) if n <= 8 else '\tlda\tXSP,XSP+%s' % hx(n))
            out.append('\tret')
            continue
        txt = ','.join(addr(a) for a in args)
        out.append('\t%s\t%s' % (op, txt) if txt else '\t' + op)
    return out


