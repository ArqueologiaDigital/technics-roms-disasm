def whole_(f, s):
    C, body = classify(f)
    need(shape_key(f, body, s) not in UNSOLVED)
    sh = stmt_shapes(body)
    need(sh <= SHAPES)                                 # the six probes' statements only
    calltests = []
    walk(body, lambda t: calltests.append(t) if t[0] == 'if' and ncalls(t[2]) else None)
    need(len(calltests) < 4)                           # a run of ifs on calls drifts (fpp5 hc5 / hc6, fpp6 hr4-hr6)
    need(any(x.split(':')[0] in ('fset', 'fopset', 'call', 'vcall', 'd2l', 'd2i') or 'fcmp' in x or
             x.startswith('ret:(') for x in sh))         # some double arithmetic
    G = Gen(C, s.startswith('O3'))
    G.after = []
    G.depth = 0
    G.brk = None
    G.xiz_ret = False
    G.need_xiz = False
    G.exit_used = False
    if G.opt:
        body = dead_stores(body)
        o3_guard(body)
    gen_stmts(G, body)
    if G.exit_used:
        G.flush()
        G.lab('L99999')
    G.lines.append(('EPILOGUE', [G.pending]))
    # ---- layout
    irmap = {}

    def reg(lst):
        for x in lst:
            irmap[id(x[1])] = x
            for b in children(x):
                reg(b or [])
    reg(body)
    stl, created = from_log(G.A.log, lambda node: irmap.get(id(node)))
    order = layout(stl, created) if created else []
    D = sum(sl.size for sl in G.A.slots)
    region = D if any_reset(body, opt=G.opt) else 2 * D - G.A.saved
    offs = {}
    top = region
    for sl in order:
        top -= sl.size
        offs[sl] = top
    frame = region
    need(not G.need_xiz)
    if TRACE is not None:
        TRACE.update(G=G, offs=offs, frame=frame, region=region, D=D, stl=stl, created=created, order=order)
    return render(G, frame, offs)


