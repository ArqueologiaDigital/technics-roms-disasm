"""fppw.py -- the cc900 V4.23 oracle's code for the double-arithmetic probes fpp6.c .. fpp11.c (double operations
through the ._f* helpers, frame temporaries for their results), at none and -O3 -XS, from the model's AST.

    whole(f, set) -> [listing lines after the function label] or None      set: 'none' or 'O3XS'

    python3 fppw.py --check [PROBE...] [SET...] [--show N] [--only REGEX]   score against the oracle listings
    python3 fppw.py --rename OUT_DIR                                        every global renamed, same scores

Run from scripts/analysis/cc900 with the model directory on sys.path.  The function is classified from its AST:
a closed statement vocabulary (double assignments and compound assignments of globals, parameters and locals, calls
of a `double f(double)`, double compares in if / while / do, a few int statements of a global).  The code is
generated by an engine of our own (evaluation order, helper operands, pushes and pending pops); the frame
temporaries are allocated (rules E3 of research-scratch sessions/2026-11-10_cc900-fp-e3) and ordered (the window
rule E2, sessions/2026-11-09_cc900-fp-e2b) by the same engine.  The rules and what is tabulated are in
fpp-FAMILIES.md beside this file.
"""
