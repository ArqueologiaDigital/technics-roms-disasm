def check(p, s, show=0, only=None, src=None, ren=None):
    import frontend
    import listing
    want = listing.split(open(RUNS + PROBES[p] + '/out/v423/%s/probes/%s.asm' % (s, p), encoding='latin-1').read())
    unit = frontend.load(src or 'corpus/probes/%s.c' % p, [], [])
    ok = wrong = dec = 0
    shown = 0
    for f in unit.functions:
        if only and not re.search(only, f.name):
            continue
        W = [l for l in want.get('_' + f.name, []) if 'section' not in l][1:]
        if ren:
            W = [ren(l) for l in W]
        got = whole(f, s)
        if got is None:
            dec += 1
            continue
        if listing.normalise_labels(got) == listing.normalise_labels(W):
            ok += 1
        else:
            wrong += 1
            if BRIEF:
                a_, b_ = listing.normalise_labels(W), listing.normalise_labels(got)
                i_ = listing.diff_first(a_, b_) or 0
                print('%-6s %-7s @%3d  %-62s | %s' % (p, f.name, i_, ' / '.join(x.strip() for x in a_[i_:i_ + 3]),
                                                     ' / '.join(x.strip() for x in b_[i_:i_ + 3])))
            if shown < show:
                shown += 1
                print('---- %s' % f.name)
                a, b = listing.normalise_labels(W), listing.normalise_labels(got)
                for k in range(max(len(a), len(b))):
                    x = a[k].strip() if k < len(a) else ''
                    y = b[k].strip() if k < len(b) else ''
                    print('  %s %-36s | %s' % (' ' if x == y else '*', x, y))
    print('%-6s %-5s exact %4d  wrong %4d  declined %4d' % (p, s, ok, wrong, dec))
    return ok, wrong, dec


def rename_check(outdir, ps, ss):
    """every extern global and called function of each probe renamed x_<name>_q in a copy under outdir, compiled by
    whole() and compared with the oracle listing renamed the same way in memory"""
    import frontend
    for p in ps:
        src = open('corpus/probes/%s.c' % p).read()
        u = frontend.load('corpus/probes/%s.c' % p, [], [])
        defined = {f.name for f in u.functions}
        names = sorted(n for n, d in u.decls.items() if n not in defined and getattr(d, 'kind', '') in ('global', 'func'))
        rx = re.compile(r'\b(%s)\b' % '|'.join(re.escape(n) for n in names))
        out = os.path.join(outdir, '%s_renamed.c' % p)
        open(out, 'w').write(rx.sub(lambda m: 'x_%s_q' % m.group(1), src))
        orx = re.compile(r'(?<![\w.])_(%s)\b' % '|'.join(re.escape(n) for n in names))
        for s in ss:
            check(p, s, src=out, ren=lambda l: orx.sub(lambda m: '_x_%s_q' % m.group(1), l))


