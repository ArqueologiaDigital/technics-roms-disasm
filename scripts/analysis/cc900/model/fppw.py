def whole(f, set='none'):
    if set not in SETS:
        return None
    try:
        return whole_(f, set)
    except Decline:
        return None
    except Exception:                                                  # (a shape the engine did not foresee)
        if os.environ.get('FPPW_DEBUG'):
            raise
        return None


