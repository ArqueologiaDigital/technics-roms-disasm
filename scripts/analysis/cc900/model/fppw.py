OPNAME = {'+': 'add', '-': 'sub', '*': 'mul', '/': 'div'}


def eval_val(G, x):
    """compute x where it needs a temporary -> ('slot', Slot) or an addressable IR value"""
    if addressable(x):
        return x
    k = x[0]
    if k == 'call':
        s = G.A.get('call')
        do_call(G, x, ('slot', s))
        return ('slot', s)
    if k == 'bin':
        l, r = x[2], x[3]
        cl, cr = not addressable(l), not addressable(r)
        if cl and cr:
            vl, vr = eval_two(G, x[1], l, r)
            dst = choose_dst(G, [vl, vr])
        elif cl or cr:
            v = eval_val(G, l if cl else r)
            vl, vr = (v, r) if cl else (l, v)
            dst = choose_dst(G, [v])
        else:
            vl, vr = l, r
            dst = ('slot', G.A.get('op'))
        op_into(G, x[1], vl, vr, dst)
        return dst
    if k == 'neg':
        v = eval_val(G, x[1])
        dst = choose_dst(G, [v]) if not addressable(x[1]) else ('slot', G.A.get('op'))
        neg_into(G, v, dst)
        return dst
    if k == 'i2d':
        dst = ('slot', G.A.get('op'))
        i2d_into(G, x, dst)
        return dst
    raise Decline()


def eval_two(G, op, l, r):
    """two computed operands: the heavier first (Sethi-Ullman), the right one on a tie; when the left one went
    first, a commutative operation takes the later value as its first operand (XBC)"""
    if ncalls(l) > ncalls(r) or ncalls(l) == ncalls(r) and weight(l) > weight(r):   # calls first (fpp7 w5 / w7,
        vl = eval_val(G, l)                                                           # fpp10 f05 / p04), then the
        vr = eval_val(G, r)                                                           # heavier side (fpp8 q3)
        if op in ('+', '*'):
            return vr, vl
        return vl, vr
    vr = eval_val(G, r)
    vl = eval_val(G, l)
    return vl, vr


def choose_dst(G, vals):
    """R_A / R_C: an operation never writes a call slot; with two operation temporaries the later-created one"""
    ops = [v[1] for v in vals if v[0] == 'slot' and v[1].kind == 'op']
    if len(ops) == 2:
        return ('slot', max(ops, key=lambda s: s.cidx))
    if len(ops) == 1:
        return ('slot', ops[0])
    return ('slot', G.A.get('op'))


def slot_of(v):
    return v[1] if v[0] == 'slot' else None


def dest_addr(G, dst):
    """('slot', s) / ('g', sym) / ('p', d) / ('l', d) / ('ret',)"""
    if dst[0] == 'ret':
        return None
    return G.addr(dst)


def op_into(G, op, vl, vr, dst):
    if any(slot_of(v) is not None and slot_of(v).kind == 'call' for v in (vl, vr)):
        G.maybe_flush()
    if dst[0] == 'ret':
        G.ret_ptr()
        G.lda('XBC', G.addr(vl))
        G.lda('XDE', G.addr(vr))
    else:
        al, ar, ad = G.addr(vl), G.addr(vr), dest_addr(G, dst)
        if G.opt and same(vl, dst):
            G.lda('XWA', ad)
            G.emit('ld', 'XBC', 'XWA')
            G.lda('XDE', ar)
        elif G.opt and same(vr, dst):
            G.lda('XBC', al)
            G.lda('XWA', ad)
            G.emit('ld', 'XDE', 'XWA')
        else:
            G.lda('XBC', al)
            G.lda('XDE', ar)
            if dst[0] == 'xiz':
                G.emit('ld', 'XWA', 'XIZ')
            else:
                G.lda('XWA', ad)
    G.emit('cal', '._f%s_d' % OPNAME[op])
    G.A.dead(*[slot_of(v) for v in (vl, vr) if slot_of(v) is not (slot_of(dst) if dst[0] == 'slot' else None)])


def same(a, b):
    return a[0] == b[0] and a[1] is b[1] if a[0] in ('slot', 'p', 'l') else (a == b and a[0] == 'g')


def neg_into(G, v, dst):
    if slot_of(v) is not None and slot_of(v).kind == 'call':
        G.maybe_flush()
    if dst[0] == 'ret':
        G.ret_ptr()
        G.lda('XBC', G.addr(v))
    elif dst[0] == 'xiz':
        G.lda('XBC', G.addr(v))
        G.emit('ld', 'XWA', 'XIZ')
    else:
        G.lda('XBC', G.addr(v))
        G.lda('XWA', dest_addr(G, dst))
    G.emit('cal', '._fneg_d')
    G.A.dead(slot_of(v) if slot_of(v) is not (slot_of(dst) if dst[0] == 'slot' else None) else None)


def copy_into(G, v, dst):
    if slot_of(v) is not None and slot_of(v).kind == 'call':
        G.maybe_flush()
    if dst[0] == 'ret':
        G.ret_ptr()
        G.lda('XBC', G.addr(v))
    elif dst[0] == 'xiz':
        G.lda('XBC', G.addr(v))
        G.emit('ld', 'XWA', 'XIZ')
    else:
        G.lda('XBC', G.addr(v))
        G.lda('XWA', dest_addr(G, dst))
    G.emit('cal', '._fld_dd')
    G.A.dead(slot_of(v))


def i2d_into(G, x, dst):
    """(double)gi: the int widened into a long temporary, then ._fld_dl"""
    iv = x[1]
    t = G.A.get('long', 4)
    if dst[0] == 'ret':
        G.ret_ptr()
    if iv[0] == 'iv':
        G.emit('ld', 'BC' if dst[0] == 'ret' else 'WA', ('mem', iv[1]))
        r = 'XBC' if dst[0] == 'ret' else 'XWA'
    else:
        G.emit('ld', 'WA', ('mem', iv[1]))
        G.emit('inc', hx(iv[2]), 'WA')
        r = 'XWA'
    G.emit('exts', r)
    G.emit('ld', ('mem', Addr('slot', t, G.push)), r)
    G.lda('XBC', Addr('slot', t, G.push))
    if dst[0] != 'ret':
        G.lda('XWA', dest_addr(G, dst))
    G.emit('cal', '._fld_dl')


def push_arg(G, v):
    """a double argument pushed through XIY / XIX, high half first"""
    G.lda('XIY', G.addr(v))
    G.emit('ld', 'XIX', '(XIY+0x4)')
    G.emit('push', 'XIX')
    G.push += 4
    G.emit('ld', 'XIX', '(XIY)')
    G.emit('push', 'XIX')
    G.push += 4
    G.A.dead(slot_of(v))


def do_call(G, x, dst):
    """fd(arg) with its result at dst: a slot, a global (pushw), a parameter / local"""
    fn, arg = x[1], x[2]
    v = eval_val(G, arg)
    push_arg(G, v)
    if dst[0] == 'g':
        G.emit('pushw', '%s >> 16' % dst[1])
        G.emit('pushw', '%s & 0xffff' % dst[1])
    else:
        G.lda('XWA', G.addr(dst))
        G.emit('push', 'XWA')
    G.push += 4
    G.emit('cal', fn)
    G.pending += 12
    G.calls_done += 1
    after_call(G)


def after_call(G):
    """the pops wait for a later call before any control flow while the two together stay within 32 bytes (fpp7
    m29: fd; fd; vd -> one lda XSP,XSP+0x20); at the very end they merge with the frame's release"""
    nb = 12 if G.calls_done < G.stmt_calls else G.later_call
    at_end = G.depth == 0 and G.last_stmt and G.calls_done == G.stmt_calls and G.call_is_last
    if (not nb or G.pending + nb > 32) and not at_end:
        G.flush()


# ============================================================================================ statements

def gen_stmts(G, body, i0=0):
    for i, s in enumerate(body):
        gen_stmt(G, s, body, i)


def calls_before_cf(rest):
    """the argument bytes of the first call in the statements `rest` before any control flow (0: none)"""
    for s in rest:
        if s[0] == 'vcall':
            return 8
        if s[0] in ('call',):
            return 12
        if s[0] in ('fset', 'fopset', 'd2l', 'd2i', 'ibool') and ncalls(s) > 0:
            return 12
        if s[0] in ('if', 'while', 'do', 'forever', 'break', 'ret'):
            return 12 if (s[0] == 'if' and ncalls(s[2]) > 0 or s[0] == 'ret' and s[2] is not None and
                          ncalls(s[2]) > 0) else 0
    return 0


def gen_stmt(G, s, body, i):
    G.A.begin(s[1])
    nxt = body[i + 1] if i + 1 < len(body) else None
    G.drop_store = not G.opt and nxt is not None and s[0] in ('icopy', 'iop') and \
        not (s[0] == 'iop' and s[4] == '*') and int_dst(s) is not None and \
        (nxt[0] == 'iset' and s[2] == ('g', nxt[2], 2) or
         s[0] == 'iop' and nxt[0] == 'icopy' and nxt[2] == s[2] and nxt[3] != s[2])   # fpp11 w22: gi = -gi;
                                                                                    # gi = gi2 (not e34's two copies)
    if G.drop_store and i + 2 < len(body) and int_dst(s) in ivars_read(body[i + 2]) and \
            int_dst(body[i + 2]) == int_dst(s):
        raise Decline()                                # fpp11 w44: the chain folds further
    G.wa_dead = getattr(G, 'pending_wa', None)
    G.pending_wa = None
    G.cur = s
    k = s[0]
    rest = [x for x in body[i + 1:] + G.after if x[0] != 'dead']
    G.later_call = calls_before_cf(rest) if k not in ('if', 'while', 'do', 'forever') else 0
    G.calls_done = 0
    G.stmt_calls = {'if': lambda: ncalls(s[2]), 'while': lambda: ncalls(s[2]), 'do': lambda: ncalls(s[3]),
                    'forever': lambda: 0, 'vcall': lambda: ncalls(s[3]) + 1}.get(k, lambda: ncalls(s))()
    G.last_stmt = not rest
    G.call_is_last = k in ('call', 'vcall') or k == 'fset' and s[3][0] == 'call'
    if k == 'vcall':                                   # vd(x): the double pushed, no result (fpp6 ve*, fpp7 m29)
        v = eval_val(G, s[3])
        push_arg(G, v)
        G.emit('cal', s[2])
        G.pending += 8
        G.calls_done += 1
        after_call(G)
        return
    if k == 'call':
        do_call(G, ('call', s[2], s[3]), ('slot', G.A.get('call')))
        return
    if k == 'fset':
        gen_fset(G, s[2], s[3])
        return
    if k == 'fopset':
        dst = s[3]
        x = s[4]
        v = eval_val(G, x)
        op_into(G, s[2], dst, v, dst)
        return
    if k == 'iset':
        if getattr(G, 'wa_dead', None) == s[2]:        # fpp10 e17: gi = gi2; gi = 9 -> ld WA,(_gi2) / ld WA,0x9 /
            G.emit('ld', 'WA', hx(s[3]))               # ld (_gi),WA
            G.emit('ld', ('mem', s[2]), 'WA')
            return
        G.emit('ldw', ('mem', s[2]), hx(s[3]))
        return
    if k == 'iinc':
        G.emit('incw' if s[3] > 0 else 'decw', hx(1), ('mem', s[2]))
        return
    if k == 'break':
        need(G.brk is not None)
        G.flush()
        G.emit('j', G.brk)
        return
    if k == 'dead':                                    # -O3 -XS: an overwritten int assignment
        d = s[2]
        if d[0] in ('ret', 'if') or G.A.nst and d is not None and d[0] in ('iset', 'icopy', 'iop', 'iinc') and \
                not G.opt:
            return
        if d[0] == 'd2i':                              # the conversion stays, its store goes (fpp7 n17)
            need(addressable(d[3]))
            t = G.A.get('long', 4, shadow=False)
            G.lda('XBC', G.addr(d[3]))
            G.lda('XWA', Addr('slot', t, G.push))
            G.emit('cal', '._fld_ld')
        elif d[0] == 'ibool':
            c = d[3]
            need(c[0] == 'fcmp')
            for v in (c[2], c[3]):
                if not addressable(v):
                    need(v[0] == 'call' and ncalls(v[2]) == 0)
                    G.stmt_calls = 1
                    eval_val(G, v)
        else:
            need(ncalls(d) == 0)
        return
    if k == 'icopy':
        gen_icopy(G, s)
        return
    if k == 'iop':
        gen_iop(G, s)
        return
    if k == 'ieqk':
        G.emit('cpw', ('mem', s[3][1]), hx(s[4]))
        G.emit('scc', 'eq', 'WA')
        istore(G, s[2], 'WA')
        return
    if k == 'ibool':
        gen_ibool(G, s)
        return
    if k == 'd2i':
        v = eval_val(G, s[3])
        t = G.A.get('long', 4, shadow=False)            # (fpp7 m17: gi = (int)gd4 keeps D' = D)
        G.maybe_flush()
        G.lda('XBC', G.addr(v))
        G.lda('XWA', Addr('slot', t, G.push))
        G.emit('cal', '._fld_ld')
        G.emit('ld', 'XWA', ('mem', Addr('slot', t, G.push)))
        G.emit('ld', ('mem', s[2]), 'WA')
        return
    if k == 'd2l':
        v = eval_val(G, s[3])
        G.lda('XBC', G.addr(v))
        G.lda('XWA', s[2])
        G.emit('cal', '._fld_ld')
        return
    if k == 'ret':
        gen_return(G, s[2])
        if not (G.depth == 0 and G.last_stmt):
            G.flush()
            G.emit('j', 'L99999')
            G.exit_used = True
        return
    if k == 'if':
        gen_if(G, s, body, i)
        return
    if k in ('while', 'do', 'forever'):
        gen_loop(G, s, body, i)
        return
    raise Decline()


REG = {1: 'A', 2: 'WA', 4: 'XWA'}


def iaddr(G, p):
    """a place's memory operand (registers it needs loaded first)"""
    if p[0] == 'g':
        return ('mem', p[1])
    if p[0] == 'el':
        return ('mem', p[1])
    if p[0] == 'pa':
        return ('mem', Addr('param', p[1], G.push))
    raise Decline()


def iload(G, p, reg=None):
    reg = reg or REG[p[2]]
    if p[0] in ('dp', 'dpp'):
        if p[0] == 'dp':
            G.emit('ld', 'XWA', ('mem', p[1]))
        else:
            G.emit('ld', 'XWA', ('mem', Addr('param', p[1], G.push)))
        G.emit('ld', reg, '(XWA)')
        return
    G.emit('ld', reg, iaddr(G, p))


def istore(G, p, reg):
    if p[0] in ('dp', 'dpp'):
        raise Decline()
    if G.drop_store:
        G.pending_wa = p[1]
        return
    G.emit('ld', iaddr(G, p), reg)


def gen_icopy(G, s):
    dst, src, sg = s[2], s[3], s[4]
    if dst[0] in ('dp', 'dpp'):                       # *gp = x: the pointer first (fpp10 e24, fpp11 w19 / w39)
        if dst[0] == 'dp':
            G.emit('ld', 'XBC', ('mem', dst[1]))
        else:
            G.emit('ld', 'XBC', ('mem', Addr('param', dst[1], G.push)))
        need(src[2] == dst[2] == 2)
        iload(G, src)
        G.emit('ld', '(XBC)', 'WA')
        return
    if src[2] == dst[2]:
        iload(G, src)
        istore(G, dst, REG[dst[2]])
        return
    if src[2] < dst[2]:                                # widening: exts (fpp10 e27 gl = gi, e37 gi = gc)
        iload(G, src)
        G.emit('exts', REG[dst[2]])
        istore(G, dst, REG[dst[2]])
        return
    iload(G, src)                                      # narrowing: the low part (fpp10 e26 gi = (int)gl, e36 gc = gi)
    istore(G, dst, REG[dst[2]])


def gen_iop(G, s):
    dst, src, op, k = s[2], s[3], s[4], s[5]
    r = REG[dst[2]]
    iload(G, src)
    if op == 'neg':
        G.emit('neg', r)
    elif op == '+':
        need(1 <= k <= 8)
        G.emit('inc', hx(k), r)
    elif op == '&':
        G.emit('and', r, hx(k))
    elif op == '*':
        need(r == 'WA')
        G.emit('muls', 'XWA', hx(k))
    elif op == '<<':
        G.emit('sla', hx(k), r)
    istore(G, dst, r)


def gen_ibool(G, s):
    """gi = (a > b): the helper's answer in HL (fpp6 hq1, fpp7 m09); gi = c && d: 1 / 0 through WA (fpp8 mc07)"""
    c = s[3]
    if c[0] == 'fcmp':
        va = eval_val(G, c[2])
        vb = eval_val(G, c[3])
        G.maybe_flush()
        G.lda('XWA', G.addr(va))
        G.lda('XBC', G.addr(vb))
        G.emit('ld', 'DE', hx(REL[c[1]]))
        G.emit('cal', '._fcmp_d')
        G.A.dead(slot_of(va), slot_of(vb))
        G.emit('ld', ('mem', s[2]), 'HL')
        return
    need(c[0] in ('and', 'or'))
    lf, lend = G.label(), G.label()
    gen_cond(G, c, lf, False)
    G.emit('ld', 'WA', hx(1))
    G.emit('j', lend)
    G.lab(lf)
    G.emit('ld', 'WA', hx(0))
    G.lab(lend)
    G.emit('ld', ('mem', s[2]), 'WA')


def gen_fset(G, dst, x):
    if addressable(x):
        if x[0] == 'k' or x[0] in ('g', 'p', 'l'):
            copy_into(G, x, dst)
            return
    k = x[0]
    if k == 'call':
        if dst[0] == 'g':
            do_call(G, x, dst)
            return
        do_call(G, x, dst)
        return
    if k == 'bin':
        l, r = x[2], x[3]
        cl, cr = not addressable(l), not addressable(r)
        if cl and cr:
            vl, vr = eval_two(G, x[1], l, r)
        elif cl:
            vl, vr = eval_val(G, l), r
        elif cr:
            vl, vr = l, eval_val(G, r)
            if x[1] in ('+', '*'):                 # the computed right operand of a commutative operation goes first
                vl, vr = vr, vl                    # (fpp8 mv02: gd3 = gd4 * gi -> lda XBC,<gi as a double>)
        else:
            vl, vr = l, r
        op_into(G, x[1], vl, vr, dst)
        return
    if k == 'neg':
        neg_into(G, eval_val(G, x[1]), dst)
        return
    if k == 'i2d':
        i2d_into(G, x, dst)
        return
    if k == 'l2d':
        G.lda('XBC', x[1])
        G.lda('XWA', dest_addr(G, dst))
        G.emit('cal', '._fld_dl')
        return
    raise Decline()


def gen_return(G, x):
    if x is None:
        G.flush()
        return
    if not G.sret:
        raise Decline()
    k = x[0]
    if addressable(x):
        G.flush()
        copy_into(G, x, ('ret',))
        return
    if k == 'bin' and addressable(x[2]) and addressable(x[3]):
        G.flush()
        op_into(G, x[1], x[2], x[3], ('ret',))
        return
    if k == 'neg' and addressable(x[1]):
        G.flush()
        neg_into(G, x[1], ('ret',))
        return
    if k == 'i2d':
        G.flush()
        i2d_into(G, x, ('ret',))
        return
    if ncalls(x) == 0 and k == 'bin':
        G.flush()
        G.need_xiz = True
        G.emit('ld', 'XIZ', ('(RET)', G.push))
        l, r = x[2], x[3]
        cl, cr = not addressable(l), not addressable(r)
        if cl and cr:
            vl, vr = eval_two(G, x[1], l, r)
        elif cl:
            vl, vr = eval_val(G, l), r
        else:
            vl, vr = l, eval_val(G, r)
        op_into(G, x[1], vl, vr, ('xiz',))
        return
    v = eval_val(G, x)
    G.flush()
    copy_into(G, v, ('ret',))


# ----------------------------------------------------------------------------------------------- control flow

def gen_cond(G, c, target, when):
    """jump to target when the condition is `when` (True / False)"""
    k = c[0]
    if k == 'itest':
        G.emit('cpw', ('mem', c[1]), hx(0))
        G.emit('j', 'ne' if when else 'eq', target)
        return
    if k == 'icmp':
        rel = c[1] if when else NEGREL[c[1]]
        G.emit('cpw', ('mem', c[2]), hx(c[3]))
        G.emit('j', {'>': 'gt', '<': 'lt', '>=': 'ge', '<=': 'le', '==': 'eq', '!=': 'ne'}[rel], target)
        return
    if k in ('fcmp', 'fcmpz'):
        rel = c[1] if when else NEGREL[c[1]]
        if k == 'fcmp':
            va = eval_val(G, c[2])
            vb = eval_val(G, c[3])
            G.maybe_flush()
            G.lda('XWA', G.addr(va))
            G.lda('XBC', G.addr(vb))
            G.emit('ld', 'DE', hx(REL[rel]))
            G.emit('cal', '._fcmp_d')
            G.A.dead(slot_of(va), slot_of(vb))
        else:
            va = eval_val(G, c[2])
            G.maybe_flush()
            G.lda('XWA', G.addr(va))
            G.emit('ld', 'BC', hx(REL[rel]))
            G.emit('cal', '._fcmp_zd')
            G.A.dead(slot_of(va))
        G.emit('cp', 'HL', hx(0))
        G.emit('j', 'ne', target)
        return
    if k == 'not':
        gen_cond(G, c[1], target, not when)
        return
    if k == 'and':
        if not when:
            gen_cond(G, c[1], target, False)
            gen_cond(G, c[2], target, False)
            return
        skip = G.label()
        gen_cond(G, c[1], skip, False)
        gen_cond(G, c[2], target, True)
        G.lab(skip)
        return
    if k == 'or':
        if when:
            gen_cond(G, c[1], target, True)
            gen_cond(G, c[2], target, True)
            return
        body = G.label()
        gen_cond(G, c[1], body, True)
        gen_cond(G, c[2], target, False)
        G.pending_label = body
        return
    raise Decline()


def put_pending_label(G):
    lab = getattr(G, 'pending_label', None)
    if lab:
        G.lab(lab)
        G.pending_label = None


def gen_if(G, s, body, i):
    c, then, els = s[2], s[3], s[4]
    if not els and len(then) == 1 and then[0][0] == 'break':   # if (c) break;  -> c true -> the loop's end
        need(G.brk is not None)
        gen_cond(G, c, G.brk, True)
        G.flush()
        return
    lelse = G.label()
    gen_cond(G, c, lelse, False)
    G.flush()
    put_pending_label(G)
    saved = G.after
    G.after = body[i + 1:] + saved
    G.depth += 1
    gen_stmts(G, then)
    if els:
        lend = G.label()
        G.emit('j', lend)
        G.lab(lelse)
        gen_stmts(G, els)
        G.lab(lend)
    else:
        G.lab(lelse)
    G.depth -= 1
    G.after = saved


def gen_loop(G, s, body, i):
    """while (c) S: none `c false -> E; B: S; c true -> B; E:`; -O3 -XS with an int test `j T; B: S; T: c true -> B`
    (fpp7 m14).  do S while (c): `B: S; c true -> B`.  for (;;) S: `B: S; j B; E:` (break -> E)"""
    saved = G.after
    G.after = body[i + 1:] + saved
    G.depth += 1
    lb, le = G.label(), G.label()
    brk = G.brk
    G.brk = le
    k = s[0]
    if k == 'while':
        c, inner = s[2], s[3]
        if G.opt and not is_fcmp(c):
            lt = G.label()
            G.emit('j', lt)
            G.lab(lb)
            gen_stmts(G, inner)
            G.lab(lt)
            gen_cond(G, c, lb, True)
            G.lab(le, True)
        else:
            gen_cond(G, c, le, False)
            G.flush()
            G.lab(lb)
            gen_stmts(G, inner)
            gen_cond(G, c, lb, True)
            G.lab(le)
    elif k == 'do':
        G.lab(lb)
        gen_stmts(G, s[2])
        gen_cond(G, s[3], lb, True)
        G.lab(le, True)
    else:
        G.lab(lb)
        gen_stmts(G, s[2])
        G.emit('j', lb)
        G.lab(le, True)
    G.brk = brk
    G.depth -= 1
    G.after = saved


# ============================================================================================ the function

def frame_of(G, order, reset):
    D = sum(s.size for s in G.A.slots)
    return D


def signature(f, body):
    """a canonical text of the function's IR: globals renamed in order of appearance, parameters and locals by
    position, constants kept"""
    names = {}

    def r(x):
        if isinstance(x, str):
            if x.startswith('_'):
                return names.setdefault(x, 'g%d' % len(names))
            return x
        if isinstance(x, (int, float)) or x is None:
            return repr(x)
        if isinstance(x, list):
            return '[' + ','.join(r(y) for y in x) + ']'
        if isinstance(x, tuple):
            if x and isinstance(x[0], str) and len(x) > 1 and not isinstance(x[1], (str, tuple, list, int, float)) \
                    and x[1] is not None and hasattr(x[1], 'k'):
                return '(' + ','.join([x[0]] + [r(y) for y in x[2:]]) + ')'
            return '(' + ','.join(r(y) for y in x) + ')'
        if hasattr(x, 'kind') and hasattr(x, 'name'):
            return 'D%s%s' % (x.kind[0], [d.name for d in f.params].index(x.name) if x in f.params else '')
        return '?'
    return '%s|%s|%s' % (getattr(f.ret, 'spell', '?'), ','.join(getattr(d.ty, 'spell', '?') for d in f.params), r(body))


def stmt_shapes(body, out=None):
    """the shapes of a body's statements (recursively): kind and operands with globals renamed in order within the
    statement, constants and parameters by kind"""
    out = set() if out is None else out
    for x in body:
        names = {}

        def r(y):
            if isinstance(y, str):
                return names.setdefault(y, 'g%d' % len(names)) if y.startswith('_') else y
            if isinstance(y, bool) or y is None:
                return repr(y)
            if isinstance(y, (int, float)):
                return 'K'
            if isinstance(y, list):
                return 'B'
            if isinstance(y, tuple):
                return '(' + ','.join(r(z) for z in y) + ')'
            if hasattr(y, 'kind') and hasattr(y, 'name'):
                return 'D' + y.kind[0]
            return '?'
        if x[0] == 'dead':
            stmt_shapes([x[2]], out)
            continue
        out.add(x[0] + ':' + ','.join(r(y) for y in x[2:]))
        for b in children(x):
            if b:
                stmt_shapes(b, out)
    return out


def shape_key(f, body, s):
    import hashlib
    return hashlib.sha1(('%s|%s' % (s, signature(f, body))).encode()).hexdigest()[:12]




