#!/usr/bin/env python3
r"""How many maincpu labels does a version share, by name, with v10?

QUESTION ANSWERED
    The cross-version policy wants one name per thing in every KN5000 maincpu tree.  This counts, from the
    committed symbol reference files (symbols/maincpu_<v>_symbols_reference.txt, regenerated by
    l2_symbol_reference.py --regen), how many of a version's labels are also v10 label names, and how many
    are not -- at any git revision, so a renaming pass can be measured before/after.

RUN
    python3 scripts/analysis/version_shared_names.py [--rev REV] [v7 v9 ...]
"""
import argparse
import subprocess


def names(rev, v):
    path = "symbols/maincpu_%s_symbols_reference.txt" % v
    txt = subprocess.run(["git", "show", "%s:%s" % (rev, path)], capture_output=True, text=True,
                         check=True).stdout if rev else open(path).read()
    return {l.split()[0] for l in txt.splitlines() if l and not l.startswith("#") and len(l.split()) == 2}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rev", default=None, help="git revision (default: the working tree)")
    ap.add_argument("versions", nargs="*", default=["v7", "v9"])
    a = ap.parse_args()
    ten = names(a.rev, "v10")
    for v in a.versions:
        n = names(a.rev, v)
        print("%-4s labels %6d  also a v10 name %6d  not a v10 name %5d" % (v, len(n), len(n & ten), len(n - ten)))


if __name__ == "__main__":
    main()
