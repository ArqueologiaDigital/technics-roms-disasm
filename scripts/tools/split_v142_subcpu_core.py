#!/usr/bin/env python3
r"""split_v142_subcpu_core.py -- split the KN5000 sub-CPU payload's core code into per-subject files.

QUESTION THIS ANSWERS / JOB IT DOES (join/split phase A4, wsa1/notes/PLAN-join-and-split.md sec 10)
    v142/subcpu/kn5000_subprogram_v142.s held the whole core of the payload -- 58,847 lines,
    1.5 MB, between `.include "subcpu_data_tables.s"` and `.include "subcpu_fp_math.s"` -- as one
    listing.  This cuts that core into 14 files under v142/subcpu/core/, at the 14 section banners
    the listing already carries (each a `; ====` line opening the header of the routine that
    starts the section), and puts one `.include` per file where the text was.  NOTHING ELSE CHANGES:
    every line moves, verbatim and in order, so the image is the same object assembled from the
    same text.

    Where to cut is not a judgement made here: every cut is at a banner that a previous pass wrote
    in front of a routine header, and --check asserts each cut line is a banner followed (after
    comments) by a label definition, i.e. that no cut falls inside a routine.  The file names say
    which subject DOMINATES each file (the label-prefix census --census prints); they are not a
    claim that every routine in a file belongs to it -- the payload was linked in its own order,
    and that order is kept.

    v141 and v140 are generated from this tree (scripts/generators/create_v141_subcpu_source.py,
    create_v140_subcpu_source.py); they copy core/ too and find each EDIT's text in whichever
    file now holds it, so they split the same way.

RUN (repo root)
    python3 scripts/tools/split_v142_subcpu_core.py --apply          # one-shot (done 2026-10-31)
    python3 scripts/tools/split_v142_subcpu_core.py --check REV      # the split preserves REV's text
    python3 scripts/tools/split_v142_subcpu_core.py --census         # label prefixes per file
    python3 scripts/tools/split_v142_subcpu_core.py --where REV N    # old line N of REV's main file, now

    ⚠ Line-number references to kn5000_subprogram_v142.s (25 in this repository, more in
    ../technics-docs) were each written against some revision of the monolith.  --where maps a line
    of REV's file to its place now, but only the reference's author knows which REV it meant.

    --check REV re-expands the root's core `.include` lines with the files' contents and compares
    the result, byte for byte, with kn5000_subprogram_v142.s as it was at REV (130735749 is the
    last revision before the split) -- and does the same for the generated v141 and v140 trees.
    `make gate` is the other half of the proof.
"""
import collections
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TREE = os.path.join(ROOT, "v142/subcpu")
MAIN = "kn5000_subprogram_v142.s"
CORE = "core"

# (the heading line right after the cut banner, file name)
CUTS = [
    (b"; Core: RESET, Initialization, Main Loop, Voice Management,", "01_reset_and_main_loop.s"),
    (b"; AUDIO SYSTEM INITIALIZATION", "02_audio_system_init.s"),
    (b"; TaskSched_TaskDescriptorTable -- the scheduler's static TASK TABLE", "03_task_scheduler_kernel.s"),
    (b"; InterCPU_Latch_Setup - Setup inter-CPU communication via latches", "04_intercpu_link.s"),
    (b"; ToneGen_Read_Register - Read one tone-generator register", "05_voice_params_and_tvf.s"),
    (b"; Voice_Calc_LevelPair_* -- the three-pair ENVELOPE writers.", "06_voice_envelopes_and_channels.s"),
    (b"; Voice_CtrlChange - Process MIDI Control Change messages", "07_voice_ctrlchange.s"),
    (b"; Voice_NoteOn - Process MIDI Note On messages", "08_voice_noteon_and_tonegen.s"),
    (b"; DSP_AlgoSelect -- Select DSP algorithm for a voice slot", "09_dsp_algo_select.s"),
    (b"; DSP_VoiceParamReadWrite -- Read/write a single DSP parameter", "10_dsp_voice_params.s"),
    (b"; RingBuf_ReadByte - Read single byte from audio ring buffer", "11_ringbuf_and_midi_dispatch.s"),
    (b"; DSP2_Init - Initialize second DSP chip", "12_dsp2_init.s"),
    (b"; Audio_Process_DSP - DSP audio processing main loop", "13_audio_process_dsp_and_effects.s"),
    (b"; DSP CONTROL ROUTINES", "14_dsp_control_routines.s"),
]
END = b"; --- Floating-Point Math Library ---"
INC = b'\t.include "%s/%s"'
BEGIN_MARK = b"; >>> BEGIN CORE INCLUDES (generated by scripts/tools/split_v142_subcpu_core.py; do not edit by hand)"
END_MARK = b"; <<< END CORE INCLUDES"
LABEL = re.compile(rb"^([A-Za-z_.][\w.]*):")


def cut_points(L):
    """Line indices (of the banner `; ====` line) where each piece starts, plus the end."""
    idx = []
    for head, _ in CUTS:
        hits = [i for i in range(1, len(L)) if L[i].startswith(head) and L[i - 1].startswith(b"; ====")]
        if len(hits) != 1:
            sys.exit("cut heading %r found %d times (want 1)" % (head, len(hits)))
        idx.append(hits[0] - 1)
    end = [i for i, l in enumerate(L) if l == END]
    if len(end) != 1:
        sys.exit("end marker found %d times" % len(end))
    if idx != sorted(idx) or idx[-1] >= end[0]:
        sys.exit("cuts out of order")
    return idx, end[0]


def check_cut_is_between_routines(L, i):
    """From the banner at i, only comments and blank lines come before the first label."""
    for l in L[i:i + 80]:
        if LABEL.match(l):
            return True
        if l.strip() and not l.startswith(b";"):
            return False
    return False


def apply():
    path = os.path.join(TREE, MAIN)
    L = open(path, "rb").read().split(b"\n")
    idx, end = cut_points(L)
    for i in idx:
        if not check_cut_is_between_routines(L, i):
            sys.exit("cut at line %d is not in front of a routine" % (i + 1))
    os.makedirs(os.path.join(TREE, CORE), exist_ok=True)
    bounds = idx + [end]
    for k, (_, name) in enumerate(CUTS):
        body = L[bounds[k]:bounds[k + 1]]
        open(os.path.join(TREE, CORE, name), "wb").write(b"\n".join(body) + b"\n")
    block = [BEGIN_MARK,
             b"; The payload's core code, in link order, one file per subject (the cut points are the",
             b"; section banners the listing already had; the subject in each name is the one that",
             b"; dominates the file, see the tool's --census).  Moved verbatim on 2026-10-31.",
             ] + [INC % (CORE.encode(), n.encode()) for _, n in CUTS] + [END_MARK]
    new = L[:idx[0]] + block + L[end:]
    open(path, "wb").write(b"\n".join(new))
    print("wrote %d core files; %s is %d lines (was %d)" % (len(CUTS), MAIN, len(new), len(L)))


def check(rev, ver="v142"):
    """`ver` v141 / v140: the generated trees split the same way (their generators copy core/)."""
    tree, main = os.path.join(ROOT, "%s/subcpu" % ver), "kn5000_subprogram_%s.s" % ver
    cur = open(os.path.join(tree, main), "rb").read()
    L = cur.split(b"\n")
    i = L.index(BEGIN_MARK)
    j = L.index(END_MARK)
    incs = L[i + 1:j]
    pieces = []
    for l in incs:
        m = re.match(rb'^\t\.include "core/([^"]+)"$', l)
        if m:
            pieces.append(open(os.path.join(tree, CORE, m.group(1).decode()), "rb").read()[:-1])
        elif not l.startswith(b";"):
            sys.exit("unexpected line in core include block: %r" % l)
    rebuilt = b"\n".join(L[:i] + [b"\n".join(pieces)] + L[j + 1:])
    old = subprocess.run(["git", "show", "%s:%s/subcpu/%s" % (rev, ver, main)], cwd=ROOT,
                         capture_output=True, check=True).stdout
    ok = rebuilt == old
    print("%s: %d core files, expanded root %s %s's %s (%d bytes)"
          % (ver, len(pieces), "==" if ok else "!=", rev, main, len(old)))
    names = [n for _, n in CUTS]
    got = sorted(f for f in os.listdir(os.path.join(tree, CORE)) if f.endswith(".s"))
    if got != sorted(names):
        print("core/ holds %r, expected %r" % (got, names))
        ok = False
    for name in names:
        PL = open(os.path.join(tree, CORE, name), "rb").read().split(b"\n")
        if not (PL[0].startswith(b"; ====") and check_cut_is_between_routines(PL, 0)):
            print("%s does not open with a banner in front of a routine" % name)
            ok = False
    return ok


def where(rev, n):
    """Old line n of REV's kn5000_subprogram_v142.s -> its file:line now (the split is a pure move)."""
    old = subprocess.run(["git", "show", "%s:v142/subcpu/%s" % (rev, MAIN)], cwd=ROOT,
                         capture_output=True, check=True).stdout.split(b"\n")
    idx, end = cut_points(old)
    i = n - 1
    if i < idx[0]:
        return "v142/subcpu/%s:%d" % (MAIN, n)
    if i >= end:
        cur = open(os.path.join(TREE, MAIN), "rb").read().split(b"\n")
        return "v142/subcpu/%s:%d" % (MAIN, cur.index(END) + 1 + (i - end))
    bounds = idx + [end]
    for k, (_, name) in enumerate(CUTS):
        if bounds[k] <= i < bounds[k + 1]:
            return "v142/subcpu/%s/%s:%d" % (CORE, name, i - bounds[k] + 1)


def census():
    for _, name in CUTS:
        t = open(os.path.join(TREE, CORE, name), "rb").read().split(b"\n")
        labs = [m.group(1) for m in map(LABEL.match, t) if m and not m.group(1).startswith(b".")]
        pre = collections.Counter(x.split(b"_")[0] for x in labs).most_common(5)
        print("%-40s %6d lines %4d labels  %s" % (name, len(t), len(labs),
              ", ".join("%s %d" % (a.decode(), b) for a, b in pre)))


if __name__ == "__main__":
    a = sys.argv[1:]
    if a == ["--apply"]:
        apply()
    elif len(a) == 2 and a[0] == "--check":
        sys.exit(0 if all([check(a[1], v) for v in ("v142", "v141", "v140")]) else 1)
    elif len(a) == 3 and a[0] == "--where":
        print(where(a[1], int(a[2])))
    elif a == ["--census"]:
        census()
    else:
        sys.exit(__doc__)
