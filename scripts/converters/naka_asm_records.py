#!/usr/bin/env python3
r"""naka_asm_records.py -- the NAKA widget records that live in the assembler sources, as one
named-field macro call per record.

QUESTION ANSWERED
-----------------
"What are the widget records that are not in the C sources?"  187 elements of the registered
Viewable tables have no typed C record.  118 of them are spelled in .s files as `naka_node` /
`naka_header` lines followed by bare `.short` / `.byte` rows.  This tool gives them the same
reading as the C records:

  --gen     writes <tree>/maincpu/shared/naka_gui.s, included right after shared/event_codes.s:
              * NAKA_CLASS_<Class> for every class event_codes.s does not define yet;
              * the property value names (CL_*, BD_*, VF_*, AL_*, ES_*, SS_*, LM_*, FR_*, PT_*,
                TR_*, IT_*, idu*, CF_*; fonts / bitmaps / icons by dump name), as in naka_classes.h;
              * one macro per class, `NAKA_REC_<Class> <field>=..., ...`, whose keyword arguments are
                the class chain's propname fields in record order, the rectangle as x, y, w, h
                (RectX2Proc / RectY2Proc: x2 = x + w - 1);
              * IDX_<label> = the element index of every labelled record of a registered Viewable
                table, so a link names the object it points at.
  --apply   rewrites every record whose label starts a block of plain data lines that ends exactly
            at the record's last byte (the next label is at address + allsize) as
                <label>:
                    NAKA_REC_<Class> super=IDX_..., sub=NAKA_INDEX_NONE, ..., x=8, y=4, w=35, h=108, ...
            from the tree's own ROM bytes and ELF symbols, keeping every comment of the block.

The values are the bytes the block held, so the image does not change (make gate).

RUN (repository root, built tree)
    python3 scripts/converters/naka_asm_records.py --tree v10 --gen [--check]
    python3 scripts/converters/naka_asm_records.py --tree v10 --apply [--report]
"""
import argparse
import bisect
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, 'scripts', 'analysis'))
sys.path.insert(0, os.path.join(ROOT, 'scripts', 'generators'))
import nakarest_objtab_map as O          # noqa: E402
import gen_naka_gui_headers as H         # noqa: E402
import naka_gui_model as G               # noqa: E402

SIMPLE = {'.byte', '.short', '.long', '.hword', '.word', 'naka_node', 'naka_header'}
NONE = 0xFFFF


def read(p):
    return open(p, 'rb').read().decode('latin-1')


def labelled_elements(m):
    """(slot, k) -> (address, label) for every element of a registered Viewable table whose
    record address carries a label (ROM, or the work-RAM image of a DRAM record)."""
    out, seen = {}, set()
    for r in m.regs:
        if r['cls'] != 0x1600010 or not m.inrom(r['table']):
            continue
        for k, a in enumerate(m.entries(r)):
            ra = a if m.inrom(a) else G.rom_image_of(a)
            if ra is None:
                continue
            lab = m.name_of(ra)
            if lab[0] == ra and lab[1] and not lab[1].startswith('.') and (r['slot'], k) not in out:
                out[(r['slot'], k)] = (ra, lab[1])
    return out


def existing_equs(tree):
    txt = read(os.path.join(ROOT, tree, 'maincpu', 'shared', 'event_codes.s'))
    return set(re.findall(r'^\.equ\s+(\w+)\s*,', txt, re.M))


def gen(tree, m):
    have = existing_equs(tree)
    out = ['; naka_gui.s -- GENERATED by scripts/converters/naka_asm_records.py --gen; do not edit.',
           ';',
           '; The NAKA class ids, property value names and record macros for the widget records written',
           '; in assembler (the C sources use naka_classes.h for the same).  A record macro NAKA_REC_<Class>',
           '; takes the class chain\'s own field names (propname) as keyword arguments, in record order; the',
           '; rectangle is x, y, w, h (RectX2Proc / RectY2Proc: x2 = x + w - 1, y2 = y + h - 1).',
           ';',
           '']
    out.append('; NAKA class ids (ClassProc: 0x016S_KKKK = entry KKKK of the Class table in slot 0x16S)')
    for cid in sorted(m.classes):
        n = 'NAKA_CLASS_' + m.classes[cid]['name']
        if n not in have:
            out.append('.equ %s, 0x%x' % (n, cid))
    out.append('')
    out.append('; property value names: SupportClass_PropTypeRecords[letter - \'A\'] (see naka_classes.h)')
    for ch, (proc, vals, src) in sorted(H.prop_types(m).items()):
        out.append('; letter %s, %s' % (ch, proc))
        for name, v in vals:
            if re.match(r'^[A-Za-z_]\w*$', name):
                out.append('.equ %s, 0x%x' % (name, v & 0xFFFFFFFF))
    out.append('')
    out.append('; element index of every labelled record of a registered Viewable table')
    for (slot, k), (a, lab) in sorted(labelled_elements(m).items()):
        out.append('.equ IDX_%s, %d\t; Viewable slot 0x%X element %d' % (lab, k, slot, k))
    out.append('')
    out.append('; one record macro per class')
    for cid in sorted(m.classes):
        c = m.classes[cid]
        fl, size = H.class_layout(m, c)
        params, body, off = [], [], 0
        for o, f, n, ch in fl:
            if o > off:
                params.append('pad_%d=0' % off)
                body += ['\t.byte \\pad_%d' % off] + ['\t.byte 0'] * (o - off - 1)
                off = o
            if ch == 'M':
                body.append('\t.long NAKA_CLASS_%s' % c['name'])
            elif ch == 'P':
                params += ['x', 'y', 'w', 'h']
                body.append('\t.short \\x, \\y, (\\x) + (\\w) - 1, (\\y) + (\\h) - 1')
            else:
                params.append(f)
                body.append('\t%s \\%s' % ({1: '.byte', 2: '.short', 4: '.long'}[n], f))
            off = o + n
        if off < size:
            params.append('pad_%d=0' % off)
            body += ['\t.byte \\pad_%d' % off] + ['\t.byte 0'] * (size - off - 1)
        out.append('.macro NAKA_REC_%s %s' % (c['name'], ', '.join(params)))
        out += body
        out.append('.endm')
    return '\n'.join(out) + '\n'


class Names:
    def __init__(self, tree, m):
        self.m = m
        self.elems = labelled_elements(m)
        self.prop = {}
        for ch, (proc, vals, src) in H.prop_types(m).items():
            d = {}
            for n, v in vals:
                if re.match(r'^[A-Za-z_]\w*$', n):
                    d.setdefault(v & 0xFFFFFFFF, n)
            self.prop[ch] = d
        txt = read(os.path.join(ROOT, tree, 'maincpu', 'shared', 'event_codes.s'))
        self.ids = {}
        for n, v in re.findall(r'^\.equ\s+(\w+)\s*,\s*(0x[0-9a-fA-F]+)', txt, re.M):
            for pre in ('TITLE_', 'NAKA_MODE_', 'NAKA_APFUNC_', 'NAKA_FUNC_', 'NAKA_MAINFUNC_'):
                if n.startswith(pre):
                    self.ids.setdefault(pre, {}).setdefault(int(v, 16), n)
        self.addrs = [a for a, n in m.rev]

    def idname(self, pres, v):
        for p in pres:
            n = self.ids.get(p, {}).get(v)
            if n:
                return n
        return None

    def rom_ref(self, v):
        if not self.m.inrom(v):
            return None
        i = bisect.bisect_right(self.addrs, v) - 1
        if i < 0:
            return None
        a, n = self.m.rev[i]
        if a == v:
            return n
        if v - a <= 64:
            return '%s + %d' % (n, v - a)
        return None


def value(nm, slot, letter, v, size):
    if letter == '[':
        if v == NONE:
            return 'NAKA_INDEX_NONE'
        e = nm.elems.get((slot, v))
        return 'IDX_' + e[1] if e else str(v)
    if letter == ']':
        if v == 0:
            return 'VF_None'
        parts, rest = [], v
        for bit, n in ((1, 'VF_Invisible'), (2, 'VF_Fixed'), (4, 'VF_Change'), (8, 'VF_Const'), (16, 'VF_InvisibleBox')):
            if v & bit:
                parts.append(n)
                rest &= ~bit
        if rest:
            parts.append('0x%x' % rest)
        return ' | '.join(parts)
    if letter in nm.prop and v in nm.prop[letter]:
        return nm.prop[letter][v]
    n = {'a': ('TITLE_',), '`': ('NAKA_MODE_',), 'j': ('NAKA_APFUNC_', 'NAKA_FUNC_', 'NAKA_MAINFUNC_'),
         'k': ('NAKA_MAINFUNC_', 'NAKA_FUNC_', 'NAKA_APFUNC_')}.get(letter)
    if n:
        x = nm.idname(n, v)
        if x:
            return x
    if letter in 'tN' and v not in (0, 0xFFFFFFFF):
        e = nm.elems.get((v >> 16, v & 0xFFFF))
        if e:
            return '0x%x + IDX_%s' % (v & 0xFFFF0000, e[1])
    if size == 4:
        r = nm.rom_ref(v)
        if r:
            return r
    if letter in 'AB' and v < 0x8000:
        return str(v)
    return '0x%x' % v


def record_call(nm, m, slot, a):
    c = m.record_class(a)
    fl, size = H.class_layout(m, c)
    args, off = [], 0
    for o, f, n, ch in fl:
        if o > off:
            if m.u8(a + off):
                args.append('pad_%d=0x%x' % (off, m.u8(a + off)))
            if any(m.u8(a + x) for x in range(off + 1, o)):
                return None
            off = o
        if ch == 'M':
            pass
        elif ch == 'P':
            x1, y1, x2, y2 = (int.from_bytes(m.rom[a + o + 2 * i - 0xE00000:a + o + 2 * i + 2 - 0xE00000], 'little', signed=True)
                              for i in range(4))
            args += ['x=%d' % x1, 'y=%d' % y1, 'w=%d' % (x2 - x1 + 1), 'h=%d' % (y2 - y1 + 1)]
        else:
            v = {1: m.u8, 2: m.u16, 4: m.u32}[n](a + o)
            args.append('%s=%s' % (f, value(nm, slot, ch, v, n)))
        off = o + n
    if off < size:
        if m.u8(a + off):
            args.append('pad_%d=0x%x' % (off, m.u8(a + off)))
        if any(m.u8(a + x) for x in range(off + 1, size)):
            return None
    return '\tNAKA_REC_%s %s' % (c['name'], ', '.join(args)), size


def apply(tree, m, report=False, write=True):
    nm = Names(tree, m)
    syms = sorted(set(a for a, n in m.rev))
    deflines = {}
    files = sorted(glob.glob(os.path.join(ROOT, tree, 'maincpu', '**', '*.s'), recursive=True))
    texts = {}
    for p in files:
        if p.endswith('naka_gui.s'):
            continue
        L = read(p).split('\n')
        texts[p] = L
        for i, l in enumerate(L):
            mm = re.match(r'^([A-Za-z_]\w*):', l)
            if mm:
                deflines[mm.group(1)] = (p, i)
    done, skipped = 0, {}
    edits = {}
    for (slot, k), (a, lab) in sorted(nm.elems.items()):
        if not m.inrom(m.entries(m.by_slot[slot])[k]) and False:
            continue
        c = m.record_class(a)
        if not c or lab not in deflines:
            continue
        p, i = deflines[lab]
        if 'ui_widgets' in p and p.endswith('.c'):
            continue
        L = texts[p]
        rest = L[i].split(':', 1)[1]
        body, j = [rest], i + 1
        while j < len(L) and not re.match(r'^[A-Za-z_]\w*:', L[k] if False else L[j]):
            body.append(L[j])
            j += 1
        kinds = set()
        for b in body:
            code = b.split(';')[0].strip()
            if code:
                kinds.add(code.split()[0])
        if not kinds or not kinds <= SIMPLE:
            skipped[lab] = 'not plain data: ' + ','.join(sorted(kinds))
            continue
        if not any(x in kinds for x in ('naka_node', 'naka_header', '.byte', '.short', '.long')):
            continue
        nbytes = 0
        for b in body:
            code = b.split(';')[0].strip()
            if code:
                op, rest = code.split()[0], code[len(code.split()[0]):].strip()
                nbytes += {'naka_node': 12, 'naka_header': 4}.get(op) or \
                    {'.byte': 1, '.short': 2, '.hword': 2, '.long': 4, '.word': 4}[op] * len(rest.split(','))
        if nbytes != c['allsize']:
            skipped[lab] = 'the block holds %d bytes, the record %d' % (nbytes, c['allsize'])
            continue
        i2 = bisect.bisect_right(syms, a)
        if i2 >= len(syms) or syms[i2] != a + c['allsize']:
            skipped[lab] = 'the block does not end at the record end'
            continue
        call = record_call(nm, m, slot, a)
        if call is None:
            skipped[lab] = 'non-zero padding'
            continue
        comments = [b for b in body if b.strip().startswith(';')]
        tail = [b.split(';', 1)[1] for b in body if ';' in b and not b.strip().startswith(';') and b.split(';')[0].strip()]
        new = ['%s:' % lab] + comments + ['\t; ' + t.strip() for t in tail] + [call[0]]
        edits.setdefault(p, []).append((i, j, new))
        done += 1
    for p, ed in edits.items():
        L = texts[p]
        for i, j, new in sorted(ed, reverse=True):
            # keep blank lines that ended the block
            trail = []
            while j - 1 > i and L[j - 1].strip() == '':
                trail.append('')
                j -= 1
            L[i:j] = new + trail
        if write:
            open(p, 'wb').write('\n'.join(L).encode('latin-1'))
    print('%s: %d records written as NAKA_REC_ macro calls; %d skipped' % (tree, done, len(skipped)))
    if report:
        for lab, why in sorted(skipped.items()):
            print('  skipped %-40s %s' % (lab, why))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--tree', default='v10')
    ap.add_argument('--gen', action='store_true')
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--apply', action='store_true')
    ap.add_argument('--report', action='store_true')
    a = ap.parse_args()
    m = O.Map(a.tree)
    if a.gen:
        p = os.path.join(ROOT, a.tree, 'maincpu', 'shared', 'naka_gui.s')
        text = gen(a.tree, m)
        cur = read(p) if os.path.exists(p) else None
        if a.check:
            print('naka_asm_records --gen --check %s: %s' % (a.tree, 'up to date' if cur == text else 'STALE'))
            sys.exit(0 if cur == text else 1)
        if cur != text:
            open(p, 'wb').write(text.encode('latin-1'))
            print('wrote', os.path.relpath(p, ROOT))
    if a.apply or a.report:
        apply(a.tree, m, a.report, write=a.apply)


if __name__ == '__main__':
    main()
