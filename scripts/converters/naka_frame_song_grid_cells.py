#!/usr/bin/env python3
r"""naka_frame_song_grid_cells.py -- frame the SONG1 / SONG2 grid-box cells of the work-RAM image by their records.

QUESTION ANSWERED
-----------------
"What are the 10 odd-aligned words field_18a3 .. field_18b7 of naka_sequencer_channels.c?" (register item
N-d8cf1242).  Blob offset o is the power-on value of RAM 0x3D524 + 0x7B0 + o (Boot_InitWorkRAM), so
blob 0x18A2..0x18BD is RAM 0x3F576..0x3F591.  The records that use those cells say what they are
(naka_ctrl_menu_body.c; field letters from naka_classes.h):

    SONG1_AcMstSong1GridBox  .pcol = RAM 0x3F576 (letter s, a 32-bit cell), .prow = 0x3F57A (s),
                             .crow = 0x3F57E (s), .nowsongctgdtno = 0x3F582, .nowsongctgmaxpage =
                             0x3F584, .nowsongctgpage = 0x3F586 (letter n, 16-bit)
    SONG2 (its Window)       parent = 0x3F588, child = 0x3F58C (letter r, 32-bit)
    SONG2_AcMstSong2GridBox  .selrow = 0x3F590 (n)

The C cut those 28 bytes as `SONG1_AcMstSong1GridBox_Pcol[1]`, eight words from the odd offset 0x18A3,
`str_12[2]` (an "" string that is the high byte of nowsongctgpage and the low byte of SONG2's parent),
two more words, `NakaData_RomEnd_ptr_3` (0x00FFFFFF: the end of SONG2's child, -1, and the low byte of
SONG2's selrow) and `pad_291[1]`.  Framed by the records, the members take the names of the cells the
records already spell (RAM_SONG1_AcMstSong1GridBox_Prow ...), with the same bytes: Pcol / Prow / Crow =
0x00CF6A00 / 0x00CF6A10 / 0x00CF6A2C, the three counters 7, 1, 1, SONG2's parent / child -1, its selrow 0.
The image does not change (make gate); naka_ram_cells.h is regenerated by gen_naka_gui_headers.py
(RAM_str_12 and RAM_NakaData_RomEnd_ptr_3, which nothing used, go).

RUN (repository root), per tree v10, v9, v7 (their text is the same here):
    python3 scripts/converters/naka_frame_song_grid_cells.py --tree v10
    python3 scripts/generators/gen_naka_gui_headers.py
It refuses a tree it has already converted.
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

OLD_MEMBERS = """\
    uint8_t SONG1_AcMstSong1GridBox_Pcol[1];
    uint16_t field_18a3;
    uint16_t field_18a5;
    uint16_t field_18a7;
    uint16_t field_18a9;
    uint16_t field_18ab;
    uint16_t field_18ad;
    uint16_t field_18af;
    uint16_t field_18b1;
    char str_12[2];
    uint16_t field_18b5;
    uint16_t field_18b7;
    uint32_t NakaData_RomEnd_ptr_3;
    uint8_t pad_291[1];
"""
NEW_MEMBERS = """\
    /* SONG1_AcMstSong1GridBox's pcol / prow / crow (letter s, 32-bit) and its three song-category
     * counters, then SONG2's window parent / child (letter r) and its grid box's selrow: the cells
     * those records name (scripts/converters/naka_frame_song_grid_cells.py) */
    uint32_t SONG1_AcMstSong1GridBox_Pcol;  /* letter s cell (32-bit) */
    uint32_t SONG1_AcMstSong1GridBox_Prow;  /* letter s cell (32-bit) */
    uint32_t SONG1_AcMstSong1GridBox_Crow;  /* letter s cell (32-bit) */
    uint16_t SONG1_AcMstSong1GridBox_Nowsongctgdtno;
    uint16_t SONG1_AcMstSong1GridBox_Nowsongctgmaxpage;
    uint16_t SONG1_AcMstSong1GridBox_Nowsongctgpage;
    int32_t SONG2_Parent;  /* letter r cell (32-bit) */
    int32_t SONG2_Child;  /* letter r cell (32-bit) */
    uint16_t SONG2_AcMstSong2GridBox_Selrow;
"""
OLD_INIT = """\
    .SONG1_AcMstSong1GridBox_Pcol = { 0 },

    .field_18a3 = 0xCF6A,

    .field_18a5 = 0x1000,

    .field_18a7 = 0xCF6A,

    .field_18a9 = 0x2C00,

    .field_18ab = 0xCF6A,

    .field_18ad = 0x0700,

    .field_18af = 0x0100,

    .field_18b1 = 0x0100,

    .str_12 = ALIGNED_STRING(""),

    .field_18b5 = NAKA_NONE,

    .field_18b7 = NAKA_NONE,

    .NakaData_RomEnd_ptr_3 = NAKA_ADDR(NakaData_RomEnd),

    .pad_291 = { 0 },
"""
NEW_INIT = """\
    .SONG1_AcMstSong1GridBox_Pcol = 0x00CF6A00,

    .SONG1_AcMstSong1GridBox_Prow = 0x00CF6A10,

    .SONG1_AcMstSong1GridBox_Crow = 0x00CF6A2C,

    .SONG1_AcMstSong1GridBox_Nowsongctgdtno = 0x0007,

    .SONG1_AcMstSong1GridBox_Nowsongctgmaxpage = 0x0001,

    .SONG1_AcMstSong1GridBox_Nowsongctgpage = 0x0001,

    .SONG2_Parent = -1,

    .SONG2_Child = -1,

    .SONG2_AcMstSong2GridBox_Selrow = 0x0000,
"""


def rd(p):
    return open(p, 'rb').read().decode('latin-1')


def wr(p, t):
    open(p, 'wb').write(t.encode('latin-1'))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--tree', required=True, choices=['v10', 'v9', 'v7'])
    a = ap.parse_args()
    p = os.path.join(ROOT, a.tree, 'maincpu', 'ui_widgets', 'naka_sequencer_channels.c')
    t = rd(p)
    if 'SONG1_AcMstSong1GridBox_Prow;' in t:
        sys.exit('naka_frame_song_grid_cells: %s already converted' % a.tree)
    for old, new, what in ((OLD_MEMBERS, NEW_MEMBERS, 'members'), (OLD_INIT, NEW_INIT, 'initializers')):
        if t.count(old) != 1:
            sys.exit('naka_frame_song_grid_cells: %s: %s not found' % (a.tree, what))
        t = t.replace(old, new)
    wr(p, t)
    print('naka_frame_song_grid_cells %s: 10 field_XX + 4 misframed members -> 9 cells of SONG1 / SONG2' % a.tree)


if __name__ == '__main__':
    main()
