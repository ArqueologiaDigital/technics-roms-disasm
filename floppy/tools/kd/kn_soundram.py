"""kn_soundram.py -- the payload describer of the KN6000 sound-memory files (.TM): "KN6000 SOUND RAM".

QUESTION IT ANSWERS
  "Which records does a saved sound memory hold?"  The layout is the KN7000 program's (kn7000_manual.sym):
    +0x00     "KN6000 SOUND RAM" (SoundRamHeaderModelGet 0x4844AF2C accepts it as model 1; the KN7000 writes
              "KN7000 SOUND RAM", SoundRamSignatureWrite 0x4844B29C)
    +0x10     40 SOUND EDIT records of 0x2C8 bytes (CustomSoundEditRecFetch 0x484845E1's stride): a 0x54-byte
              header whose first 16 bytes are the name (accessors TgPartAuxHdr45Get.. read +0x45..+0x47),
              4 mod units of 0x7A at +0x54 (TgPartAuxModRecPtr 0x4C00C25B), 4 elements of 0x23 at +0x23C
              (TgPartAuxElemRecPtr 0x4C00C28D; 0x54 + 4*0x7A + 4*0x23 = 0x2C8)
    +0x6F50   the custom-sound (kit) block (kn7000/notes/custom-data-ic21.md: CustomVoiceRecFetch 0x4844A42F):
              a 0x27-byte header (the kit name first), 128 {program, bank LSB, bank MSB} references, then 128
              voice records of 0x8E: a 16-byte head (13-character name), 2 sub-records of 0x1C at +0x10
              (TgPartLocalEditModRecPtr), 2 elements of 0x23 at +0x48 (TgPartLocalEditElemRecPtr)
    +0xB7F7   a byte ([INFERENCE] the edit index the KN5000 file has here), then the LE16 checksum the firmware
              keeps at RAM +0xB7F8: ~(LE16 sum of the 0x37A0 halfwords of the 40 sound records), KN6000
              func_4C07D7C1 (from 0x8402F4F4 = block 0x8402F4E4 + 0x10; KN7000 func_4844AC9B, 0x840327F8).  It is
              validated against RAM at power-on (func_4C07E1D4: a mismatch re-initialises the sounds,
              func_4C07DD55) and recomputed after every .TM load (PostTmTransLoad 0x4C07DF7B -> func_4C07DEC8),
              so a file's word is never read.  It matches in 12 of the 50 files; [INFERENCE] the others were
              saved after sounds were changed by a path that does not recompute it
              (notes/floppy-leftovers-2026-10-31/probes/tm_tail.py, tm_tail2.py).
  Records are content-addressed include files in floppy/kn6000/include/tm/, shared by every disk.
"""
import hashlib
import os

INC = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), 'kn6000', 'include', 'tm')
GEN = 'floppy/tools/kd/kn_soundram.py'


def rows(b, w=16):
    return ['\t.byte\t' + ', '.join(str(x) for x in b[k:k + w]) for k in range(0, len(b), w)]


def s_esc(b):
    return '"' + ''.join(chr(c) if 0x20 <= c < 0x7F and c not in (0x22, 0x5C) else '\\%03o' % c for c in b) + '"'


def item(kind, body, lines):
    name = '%s_%s.s' % (kind, hashlib.sha1(body).hexdigest()[:12])
    os.makedirs(INC, exist_ok=True)
    text = '\n'.join(['; Generated by %s; regenerate rather than edit (floppy/README.md).' % GEN] + lines) + '\n'
    path = os.path.join(INC, name)
    if not os.path.exists(path) or open(path, 'rb').read() != text.encode('latin-1'):
        open(path, 'wb').write(text.encode('latin-1'))
    return 'tm/' + name


def v(b):
    return ', '.join(str(x) for x in b)


def sound(r):
    L = ['; A SOUND EDIT record, 0x2C8 bytes (SOUND_HEAD / SOUND_MOD / VOICE_ELEM, kn7000/src/include/voice_record.inc).', '',
         '\t.ascii\t%s' % s_esc(r[:16]), '\tSOUND_HEAD\t%s' % v(r[16:0x54])]
    for u in range(4):
        L.append('\tSOUND_MOD\t%s\t; mod unit %d' % (v(r[0x54 + 0x7A * u:0x54 + 0x7A * (u + 1)]), u + 1))
    for e in range(4):
        L.append('\tVOICE_ELEM\t%s\t; element %d' % (v(r[0x23C + 0x23 * e:0x23C + 0x23 * (e + 1)]), e + 1))
    return item('sound', r, L)


def voice(r):
    L = ['; A voice record, 0x8E bytes (VOICE_HEAD / VOICE_SUB / VOICE_ELEM, kn7000/src/include/voice_record.inc).', '',
         '\t.ascii\t%s' % s_esc(r[:13]), '\tVOICE_HEAD_TAIL\t%s' % v(r[13:16])]
    for u in range(2):
        L.append('\tVOICE_SUB\t%s\t; sub-record %d' % (v(r[0x10 + 0x1C * u:0x2C + 0x1C * u]), u + 1))
    for e in range(2):
        L.append('\tVOICE_ELEM\t%s\t; element %d' % (v(r[0x48 + 0x23 * e:0x6B + 0x23 * e]), e + 1))
    return item('voice', r, L)


def typer(ctx, part, p, ref, lab):
    if part != 1 or p[:16] != b'KN6000 SOUND RAM' or len(p) != 0x10 + 40 * 0x2C8 + 0x1A7 + 128 * 0x8E + 3:
        return None
    L = ['\t.include\t"voice_record.inc"', '', lab + ':', '\t.ascii\t"KN6000 SOUND RAM"\t; SoundRamHeaderModelGet: model 1']
    for k in range(40):
        r = p[0x10 + 0x2C8 * k:0x10 + 0x2C8 * (k + 1)]
        L.append('\t.include\t"%s"\t; sound %d: %s' % (sound(r), k + 1, r[:16].decode('latin-1').strip()))
    kb = 0x10 + 40 * 0x2C8
    kit = p[kb:kb + 0x1A7]
    L += ['%s_Kit:' % lab, '\t.ascii\t%s\t; kit name' % s_esc(kit[:16]), '; kit header +0x10..+0x26'] + rows(kit[16:0x27], 23)
    L.append('; 128 references {program, bank LSB, bank MSB}')
    for k in range(0, 128, 8):
        L.append('\t.byte\t' + ', '.join('%d, %d, %d' % tuple(kit[0x27 + 3 * j:0x2A + 3 * j]) for j in range(k, k + 8))
                 + '\t; %d-%d' % (k, k + 7))
    for k in range(128):
        r = p[kb + 0x1A7 + 0x8E * k:kb + 0x1A7 + 0x8E * (k + 1)]
        L.append('\t.include\t"%s"\t; voice %d: %s' % (voice(r), k, r[:13].decode('latin-1').strip()))
    t = p[-3:]
    s = (~sum(p[i] | p[i + 1] << 8 for i in range(0x10, kb, 2))) & 0xFFFF
    L.append('\t.byte\t%d\t; [INFERENCE] the edit index (the KN5000 file has one here)' % t[0])
    L.append('\t.short\t0x%04x\t; %s' % (t[1] | t[2] << 8, 'the sound records\' checksum, ~(LE16 sum) (func_4C07D7C1)'
                                       if s == t[1] | t[2] << 8 else 'a stale checksum (the records give 0x%04x); no load reads it, PostTmTransLoad recomputes it' % s))
    return L
