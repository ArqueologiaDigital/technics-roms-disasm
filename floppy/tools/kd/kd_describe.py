"""kd_describe.py -- the describer half of floppy/tools/kd, shared by floppy/kn6000 and floppy/kn7000.

QUESTION IT ANSWERS
  "How does a compressed disk file become source?"  A compressed file is held as three things:
    files/<unit>.s        the unit: its container header, typed (kd.inc), and an .incbin of each stored
                          stream, which is a build product (census: generated)
    payload/<unit>.pN.s   each part's payload, inflated, as its own llvm-mc source: typed by the kind's
                          payload describer (`typers`), or one generic .incbin of the reference payload
    kd.mk                 the make rules that assemble each payload and compress it with the part's coder
  floppy/tools/kd/kd.mk includes every <model>/<disk>/kd.mk.  The reference payloads
  (build/<model>/<disk>/<extracted>.pN.ref) come from `kd.py unpack-dir` over the extracted files, so a
  payload source can .incbin what it does not type yet.

  Side effect: describe_* write payload/ and kd.mk under floppy/<model>/<disk>/ themselves (the generator's
  describe() interface returns only the unit).  At exit, payload sources of the disks it touched that no
  call wrote are removed, so the tree is exactly the generator's output.
"""
import atexit
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import kd  # noqa: E402

FLOPPY = os.path.dirname(os.path.dirname(HERE))
GEN = 'floppy/tools/kd/kd_describe.py'
EXT = {'deflate104': 'zd', 'lzss_j': 'zl'}
WHAT_CODEC = {'deflate104': 'kd.py encode deflate104 (zlib 1.0.4, level 6)',
              'lzss_j': 'kd.py encode lzss_j (LZSS, 8 KB ring)'}

_written = {}      # (model, disk) -> {relpath: text}
_rules = {}        # (model, disk) -> [make lines]


def _flush():
    for (model, disk), files in _written.items():
        root = os.path.join(FLOPPY, model, disk)
        pdir = os.path.join(root, 'payload')
        os.makedirs(pdir, exist_ok=True)
        for rel, text in files.items():
            p = os.path.join(root, rel)
            if not os.path.exists(p) or open(p, 'rb').read() != text.encode('latin-1'):
                open(p, 'wb').write(text.encode('latin-1'))
        for f in os.listdir(pdir):
            if 'payload/' + f not in files:
                assert os.path.dirname(os.path.join(pdir, f)) == pdir
                os.unlink(os.path.join(pdir, f))
        mk = ['# Generated by %s; regenerate with `make -C floppy src-%s` (floppy/README.md).' % (GEN, model),
              '# The stored streams of %s/%s: each one assembled from payload/ (or taken from the image' % (model, disk),
              '# it compresses) and encoded by its part\'s coder.  Rules: floppy/tools/kd/kd.mk.', '']
        mk += _rules[(model, disk)]
        text = '\n'.join(mk) + '\n'
        p = os.path.join(root, 'kd.mk')
        if not os.path.exists(p) or open(p).read() != text:
            open(p, 'w').write(text)


atexit.register(_flush)


def _reg(model, disk):
    key = (model, disk)
    if key not in _written:
        _written[key] = {}
        _rules[key] = []
    return _written[key], _rules[key]


CURRENT = [None, None]   # (model, disk) of the file being described, for typers that write include files


def extra_file(name, text):
    """A payload-side include file (payload/<name>), written and kept like the payload sources."""
    assert '/' not in name and name.endswith('.s')
    _reg(*CURRENT)[0]['payload/' + name] = text


def payload_label(ctx, i):
    return 'P_%s_p%d' % (ctx.label[2:], i)


def payload_source(ctx, i, codec, data, typer):
    """The text of payload/<unit>.p<i>.s."""
    ref = '%s.p%d.ref' % (ctx.extracted, i)
    lab = payload_label(ctx, i)
    body = typer(ctx, i, data, ref, lab) if typer else None
    if isinstance(body, tuple) and body[0] == 'kn7asm':
        head = ['# Generated by %s from %s; regenerate rather than edit (floppy/README.md).' % (GEN, ctx.ref),
                '# %s, part %d: the payload, inflated (%d bytes); compressed by %s.'
                % (ctx.path, i, len(data), WHAT_CODEC[codec]), '# Assembled by kn7000/tools/kn7asm.py (KD_PART7).', '']
        return '\n'.join(head + body[1]) + '\n', 'kn7asm'
    head = ['; Generated by %s from %s; regenerate rather than edit (floppy/README.md).' % (GEN, ctx.ref),
            '; %s, part %d: the payload, inflated (%d bytes); compressed by %s.'
            % (ctx.path, i, len(data), WHAT_CODEC[codec]), '']
    if body is None:
        body = ['; No payload describer for this kind yet: the bytes are the reference payload\'s',
                '; (kd.py unpack-dir of the disk\'s copy of the file).',
                '%s:\t.incbin\t"%s", 0, %d' % (lab, ref, len(data))]
    elif isinstance(body, str):
        body = body.rstrip('\n').split('\n')
    tail = ['', '\t.if\t(. - %s) - %d' % (lab, len(data)),
            '\t.error\t"%s part %d: the payload is not %d bytes"' % (ctx.path, i, len(data)), '\t.endif']
    if not any(x.startswith(lab + ':') for x in body):
        body = [lab + ':'] + body
    return '\n'.join(head + body + tail) + '\n', 'llvm-mc'


def describe_kd(ctx, model, typers=None, note=None):
    """The unit of a KD or K1 file, with its payload sources; None for a file that is not compressed.
    `typers` maps an extension to typer(ctx, part, payload, refname, label) -> lines | None.
    `note` is an optional list of comment lines describing what the file is."""
    ext = ctx.path.rsplit('.', 1)[-1].upper()
    kind, hdr, parts = kd.parse(ctx.data, ext)
    if kind == 'RAW':
        return None
    files, rules = _reg(model, ctx.disk)
    CURRENT[:] = [model, ctx.disk]
    typer = (typers or {}).get(ext)
    lab = ctx.label
    codec = parts[0][0]
    L = ['; %s' % x for x in (note or [])]
    if note:
        L.append('')
    L += ['\t.include\t"kd.inc"', lab + ':']
    if kind == 'KD':
        magic = hdr[:4].decode('ascii')
        flags = hdr[6] << 8 | hdr[7]
        if len(parts) == 1:
            L.append('\tkd_one\t"%s", 0x%04x, %d\t\t; %s, one part' % (magic, flags, len(parts[0][1]), codec))
        else:
            L.append('\tkd_two\t"%s", 0x%04x, %d, %d, %s_s1, %s_e1, %s_s2, %s_e2, %d\t; %s, two parts'
                     % (magic, flags, len(parts[0][1]), len(parts[1][1]), lab, lab, lab, lab,
                        2 if codec == 'deflate104' else 0, codec))
    else:
        L.append('\tk1_head\t"%s", %d\t\t; deflate104, one part' % (hdr[:1].decode(), len(parts[0][1])))
        L += k1_rest(ctx, ext, hdr)
    for i, (c, data, stream) in enumerate(parts, 1):
        z = '%s.p%d.%s' % (ctx.extracted, i, EXT[c])
        L.append('%s_s%d:\t.incbin\t"%s"\t; census: generated -- floppy/tools/kd/%s of payload/%s.p%d.s'
                 % (lab, i, z, WHAT_CODEC[c], ctx.unit, i))
        L.append('%s_e%d:' % (lab, i))
        text, asm = payload_source(ctx, i, c, data, typer)
        files['payload/%s.p%d.s' % (ctx.unit, i)] = text
        rules.append('$(eval $(call %s,%s,%s,%s,%s,%d,%s))' % ('KD_PART7' if asm == 'kn7asm' else 'KD_PART',
                                                              model, ctx.disk, ctx.unit, ctx.extracted, i, EXT[c]))
    return L


def k1_rest(ctx, ext, hdr):
    """The rest of a K1 header (after magic and size)."""
    if ext == 'AST':
        a, b = hdr[8:12], hdr[12:16]
        return ['\t.long\t0x%08x, 0x%08x\t; never written by func_4852D0E5: the old contents of its stack frame'
                % (int.from_bytes(a, 'little'), int.from_bytes(b, 'little'))]
    return ['\t.byte\t' + ', '.join('0x%02x' % x for x in hdr[8:])]


def describe_image(ctx, model, imgvar, what):
    """A K1 file whose payload is a whole image built elsewhere (an .AST's custom-data flash image):
    the unit compresses that image, `$(imgvar)` in make."""
    ext = ctx.path.rsplit('.', 1)[-1].upper()
    kind, hdr, parts = kd.parse(ctx.data, ext)
    assert kind == 'K1' and len(parts) == 1
    files, rules = _reg(model, ctx.disk)
    lab = ctx.label
    z = '%s.p1.zd' % ctx.extracted
    L = ['; %s' % x for x in what] + ['', '\t.include\t"kd.inc"', lab + ':',
         '\tk1_head\t"%s", %d\t\t; deflate104, one part' % (hdr[:1].decode(), len(parts[0][1]))]
    L += k1_rest(ctx, ext, hdr)
    L.append('%s_s1:\t.incbin\t"%s"\t; census: generated -- floppy/tools/kd/%s of $(%s)'
             % (lab, z, WHAT_CODEC['deflate104'], imgvar))
    rules.append('$(eval $(call KD_IMAGE,%s,%s,%s,%s))' % (model, ctx.disk, ctx.extracted, imgvar))
    return L
