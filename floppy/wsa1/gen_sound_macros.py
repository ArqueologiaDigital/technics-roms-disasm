#!/usr/bin/env python3
"""gen_sound_macros.py -- the WSA1R sound-record macros, named from Technics' published layout.

QUESTION IT ANSWERS: "what is each byte of a WSA1R tone (NORMAL SOUND) and drum (DRUM SOUND) record?"  The
names are the Reference Guide's, transcribed in wsa1/notes/sysex-probes/sound_layout.json (each block checked
to tile its parent by sysex_sound_layout.py): NORMAL SOUND is the 713-byte record (GENERAL DATA 217, TONE DATA
4 x 81, MODELING DATA 4 x 43), DRUM SOUND the kit (KIT DATA 0x98, SOUND SELECT 0x100) and 128 NOTE DATA
blocks of 150.  These are exactly the record strides SoundRam_ClearFourBanks (prom_c 0xFC386C) writes into
the sound flash, so the .TM file's records are these records.  Writes floppy/wsa1/include/wsa1_sound.inc:
one macro per block, one parameter per byte, named after the field that covers the byte (a field of n bytes
gives name_0 .. name_{n-1}; a byte no field covers is rsv_<offset>).
Run: python3 -I floppy/wsa1/gen_sound_macros.py
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = os.path.join(HERE, '..', '..', 'wsa1', 'notes', 'sysex-probes', 'sound_layout.json')
OUT = os.path.join(HERE, 'include', 'wsa1_sound.inc')


def ident(name):
    s = name.lower().replace('&', 'and').replace('~', '_')
    s = re.sub(r'\(.*?\)', '', s)
    s = re.sub(r'[^a-z0-9]+', '_', s).strip('_')
    return s[:40].rstrip('_') or 'x'


def params(block, base, size):
    names = {}
    for e in block['entries']:
        a = int(e['at'], 16) - base
        b = int(e.get('to') or e['at'], 16) - base
        n = ident(e['name'])
        for k in range(a, b + 1):
            names[k] = n if a == b else '%s_%d' % (n, k - a)
    out, seen = [], {}
    for k in range(size):
        n = names.get(k, 'rsv_%02x' % k)
        if n in seen:
            n = '%s_%02x' % (n, k)
        seen[n] = 1
        out.append(n)
    return out


def macro(name, ps, doc, skip_name=0):
    L = ['; ' + d for d in doc]
    q = ps[skip_name:]
    L += ['\t.macro\t%s %s' % (name, ', '.join(q))]
    for k in range(0, len(q), 16):
        L.append('\t.byte\t' + ', '.join('\\' + x for x in q[k:k + 16]))
    return L + ['\t.endm']


def main():
    d = json.load(open(SPEC))
    normal, drum = d['areas']
    L = ['; wsa1_sound.inc -- GENERATED by floppy/wsa1/gen_sound_macros.py from wsa1/notes/sysex-probes/',
         '; sound_layout.json (the Reference Guide\'s NORMAL SOUND and DRUM SOUND layouts); do not edit by hand.',
         '; A name field (the first 16 / 13 bytes) is not a parameter: the caller writes it with .ascii first.',
         '', '\t.ifndef\tWSA1_SOUND_INC', '\t.set\tWSA1_SOUND_INC, 1']
    want = {('NORMAL SOUND', 'GENERAL DATA'): ('snd_general', 16), ('NORMAL SOUND', 'TONE DATA'): ('snd_tone', 0),
            ('NORMAL SOUND', 'MODELING DATA'): ('snd_modeling', 0), ('DRUM SOUND', 'KIT DATA'): ('kit_general', 16),
            ('DRUM SOUND', 'SOUND SELECT'): ('kit_sound_select', 0)}
    for area in (normal, drum):
        for b in area['blocks']:
            subs = b.get('blocks') or [b]
            for sb in subs:
                key = (area['name'], sb['name'])
                base = int(sb['at'], 16)
                size = int(sb['to'], 16) - base + 1
                if key in want:
                    mname, skip = want[key]
                elif area['name'] == 'DRUM SOUND' and b['name'] == 'NOTE DATA':
                    mname = 'note_' + ident(sb['name']).replace('note_', '')
                    skip = 13 if sb['name'] == 'NOTE GENERAL DATA' else 0
                else:
                    continue
                if sb['name'] == 'SOUND SELECT':
                    continue
                ps = params(sb, base, size)
                L += [''] + macro(mname, ps, ['%s / %s: %d bytes at %s (%s)' % (area['name'], sb['name'], size, sb['at'],
                                                                                  'x%d' % b['count'] if b['count'] > 1 else 'once')], skip)
    L += ['', '\t.endif']
    open(OUT, 'w').write('\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
